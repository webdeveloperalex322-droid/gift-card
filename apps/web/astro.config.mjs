/**
 * Конфигурация Astro для apps/web (задача Э3-01).
 *
 * Версии проверены в установленных пакетах, а не по памяти:
 *   - astro 7.2.4 (`apps/web/node_modules/astro/package.json`);
 *   - @astrojs/node 11.1.4 (`apps/web/node_modules/@astrojs/node/package.json`).
 */

import node from '@astrojs/node';
import { defineConfig } from 'astro/config';

export default defineConfig({
  // «Гибридный режим» отдельным значением `output` в этой версии НЕ выражается:
  // в типе конфига остались ровно два значения — `output?: 'static' | 'server'`
  // (проверено: `apps/web/node_modules/astro/dist/types/public/config.d.ts`,
  // строка 316; прежнего `'hybrid'` там нет). Актуальная форма гибрида —
  // «статика по умолчанию + отказ от пререндера на нужных маршрутах»:
  // `output: 'static'` вместе с адаптером, а SSR-маршрут объявляет
  // `export const prerender = false`.
  //
  // Выбрано `'static'`, а не `'server' + prerender = true`, потому что дефолт
  // обязан быть безопасным: забытый флаг на статической странице даёт лишний
  // SSR (медленнее, но верно), а забытый флаг при обратном выборе дал бы
  // запечённый в артефакт HTML там, где ожидался ответ из БД.
  output: 'static',

  // Standalone: адаптер поднимает собственный HTTP-сервер (`dist/server/entry.mjs`),
  // отдельного express-обвязки не требуется. Он же обслуживает статику
  // заранее отрендеренных маршрутов и, при `trailingSlash: 'never'`, сам отдаёт
  // на них одиночный 301 — см. `@astrojs/node/dist/serve-static.js`, ветка
  // `case "never"`.
  adapter: node({ mode: 'standalone' }),

  // Решение Ч-21: единая форма БЕЗ завершающего слеша. Прежняя формулировка
  // плана («always») отменена.
  //
  // Почему именно 'never', а не 'ignore' с редиректом только в нашем middleware:
  // при 'ignore' Astro сам схлопывает повторные завершающие слеши в форму СО
  // слешем (`collapseDuplicateTrailingSlashes(pathname, true)`), и наш редирект
  // добавил бы второй шаг — то есть цепочку из двух 301. При 'never' обе
  // реализации целятся в одну и ту же каноническую форму, поэтому редирект
  // всегда одиночный. Правило при этом всё равно закодировано у нас
  // (`src/routing/path-policy.ts` + `src/middleware.ts`): поведение фреймворка
  // не является контрактом проекта, а исключений (админка, URL файлов) Astro не
  // знает.
  trailingSlash: 'never',

  build: {
    // Парный к `trailingSlash: 'never'` формат вывода: документация типа
    // конфига прямо связывает их («`file` - Set `trailingSlash: 'never'`»,
    // `config.d.ts`, раздел build.format). При `directory` заранее отрендеренная
    // страница жила бы в `/путь/index.html`, а её `Astro.url.pathname` во время
    // сборки заканчивался бы слешем — то есть не совпадал бы с каноническим
    // видом URL.
    format: 'file',
  },

  // Панель разработчика вставляет клиентский скрипт на каждую страницу.
  // Инвариант «нулевой клиентский JS по умолчанию» проверяется в том числе
  // curl'ом по dev-серверу, поэтому панель выключена.
  devToolbar: { enabled: false },

  server: {
    // Порт зафиксирован явно: на него смотрит BASE_URL приёмки SEO.
    port: 4321,
  },

  // `site` НЕ задан намеренно. Он сделал бы `Astro.site` вторым источником
  // хоста рядом с `SITE_URL`, а `CLAUDE.md` («Правила URL») требует ровно один:
  // абсолютный URL собирает единственный хелпер `buildAbsoluteUrl` из
  // `@otkritka/shared`, читающий только `SITE_URL` в рантайме. Расхождение
  // canonical со sitemap обнаруживается уже после индексации.
});
