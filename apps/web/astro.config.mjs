/**
 * Конфигурация Astro для apps/web.
 *
 * Версии проверены в установленных пакетах, а не по памяти:
 *   - astro 7.2.4 (`apps/web/node_modules/astro/package.json`);
 *   - @astrojs/node 11.1.4 (`apps/web/node_modules/@astrojs/node/package.json`).
 */

import node from '@astrojs/node';
import { defineConfig } from 'astro/config';

export default defineConfig({
  // «Гибридный режим» отдельным значением `output` в этой версии НЕ выражается:
  // в типе конфига остались ровно два значения — `output?: 'static' | 'server'`
  // (проверено: `apps/web/node_modules/astro/dist/types/public/config.d.ts`,
  // строка 316; прежнего `'hybrid'` там нет). Актуальная форма гибрида —
  // «статика по умолчанию + отказ от пререндера на нужных маршрутах»:
  // `output: 'static'` вместе с адаптером, а SSR-маршрут объявляет
  // `export const prerender = false`.
  //
  // Выбрано `'static'`, а не `'server' + prerender = true`, потому что дефолт
  // обязан быть безопасным: забытый флаг на статической странице даёт лишний
  // SSR (медленнее, но верно), а забытый флаг при обратном выборе дал бы
  // запечённый в артефакт HTML там, где ожидался ответ из БД.
  output: 'static',

  // Режим middleware: адаптер отдаёт ТОЛЬКО обработчик приложения и не поднимает
  // сервер сам. Сервер, порядок обработки запроса и отдачу статики держит
  // `src/server/` — см. `src/server/entry.mts`.
  //
  // Почему не `standalone`, который был здесь раньше. В standalone адаптер
  // ставит перед приложением свой статический обработчик
  // (`@astrojs/node/dist/serve-static.js`), и он отвечает РАНЬШЕ
  // пользовательского middleware. Замерено контролёром `url-guard` на собранном
  // сервере:
  //   - `/%2F` ⇄ `/%2F/` — бесконечный цикл 301 (`decodeURI` не раскрывает
  //     `%2F`, а `send` внутри раскрывает через `decodeURIComponent`, попадает в
  //     корень `dist/client`, видит каталог и добавляет слеш);
  //   - `////` → `///` → `//` → `/` — три перехода, промежуточные `Location`
  //     протокольно-относительны (снимается ровно один слеш: `urlPath.slice(0, -1)`);
  //   - ветка «каталог + завершающий слеш» зависит от платформы: `lstat` на
  //     каталоге со слешем в Windows даёт `ENOENT`, в Linux — успех.
  // Ни одно из трёх не лечится в middleware Astro: до него эти ответы не
  // доходят. Поэтому порядок обработки принадлежит нам — это не вкусовое
  // решение, а единственный способ выполнить требование «одиночный 301, цепочки
  // запрещены» на всём множестве путей.
  adapter: node({ mode: 'middleware' }),

  // Решение Ч-21: единая форма БЕЗ завершающего слеша.
  //
  // Значение оставлено согласованным с нашей нормализацией, хотя встроенный
  // редирект Astro теперь недостижим: приложению передаются только цели в
  // канонической форме, а на них `redirectTrailingSlash` возвращает путь без
  // изменений. Согласованность всё равно нужна — от `trailingSlash` зависит и
  // сопоставление маршрутов, и то, каким Astro считает канонический вид пути при
  // пререндере. Расхождение здесь дало бы разные формы в артефакте и в ответе.
  trailingSlash: 'never',

  build: {
    // Парный к `trailingSlash: 'never'` формат вывода: документация типа конфига
    // прямо связывает их («`file` - Set `trailingSlash: 'never'`», `config.d.ts`,
    // раздел build.format). При `directory` заранее отрендеренная страница жила
    // бы в `/путь/index.html`, а её `Astro.url.pathname` во время сборки
    // заканчивался бы слешем — то есть не совпадал бы с каноническим видом URL.
    //
    // Следствие, которое обязано быть закрыто и закрыто: страница лежит на диске
    // как `<путь>.html`, поэтому у неё есть ВТОРОЕ имя, похожее на адрес.
    // Отдавать его нельзя — это второй URL одного материала с 200. Отказ живёт в
    // политике пути (`src/routing/path-policy.ts`, шаг 4: любой путь,
    // оканчивающийся на `.html`, отвечает 404 — с 2026-08-28 в канонической
    // форме пути после таблицы переносов, решение `not-found-unless-moved`, а в
    // форме со слешем или с пустым сегментом сразу; статикой он не отдаётся ни в
    // одном случае), а не в форме вывода: то же самое потребовалось бы и при
    // `directory`, только вторым адресом был бы `/путь/index.html`.
    format: 'file',

    // Приложение Astro переехало с `entry.mjs`, потому что этим именем теперь
    // называется НАШ сервер (`src/server/entry.mts` → `dist/server/entry.mjs`).
    // Имя — контракт: на `dist/server/entry.mjs` смотрят смоук, стенд
    // SEO-приёмки и `astro preview`. Значение обязано совпадать с
    // `ASTRO_APP_FILE_NAME` из `src/server/astro-app.ts`.
    serverEntry: 'astro-app.mjs',
  },

  // Панель разработчика вставляет клиентский скрипт на каждую страницу.
  // Инвариант «нулевой клиентский JS по умолчанию» проверяется в том числе
  // curl'ом по dev-серверу, поэтому панель выключена.
  devToolbar: { enabled: false },

  server: {
    // Порт зафиксирован явно: на него смотрит BASE_URL приёмки SEO. Его же
    // читает наш вход (`options.port` из собранного приложения), а `PORT` из
    // окружения его перебивает.
    port: 4321,
  },

  // `site` НЕ задан намеренно. Он сделал бы `Astro.site` вторым источником
  // хоста рядом с `SITE_URL`, а `CLAUDE.md` («Правила URL») требует ровно один:
  // абсолютный URL собирает единственный хелпер `buildAbsoluteUrl` из
  // `@otkritka/shared`, читающий только `SITE_URL` в рантайме. Расхождение
  // canonical со sitemap обнаруживается уже после индексации.
});
