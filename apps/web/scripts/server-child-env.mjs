#!/usr/bin/env node
/**
 * Окружение для дочернего процесса СОБРАННОГО сервера apps/web.
 *
 * ## Что здесь было и почему это убрано
 *
 * Здесь жило правило разрешения модулей: в `NODE_PATH` дочернего процесса
 * подставлялось виртуальное хранилище pnpm
 * (`<корень>/node_modules/.pnpm/node_modules`). Поводом было падение собранного
 * сервера первым же обращением к базе —
 *
 *   Error: Cannot find module 'drizzle-kit/api'
 *
 * Правило лечило симптом, а причина была другая, и она названа вердиктом
 * `reviewer` (MINOR 4): `drizzle-kit` — ФАНТОМНАЯ зависимость. Его подтягивает
 * динамическим импортом адаптер Postgres при накате схемы
 * (`@payloadcms/drizzle/dist/postgres/requireDrizzleKit.js`, `createRequire`), а
 * в манифесте `@payloadcms/drizzle` пакет не объявлен вовсе — проверено по его
 * `package.json` в виртуальном хранилище pnpm: в
 * `dependencies` его нет, объявляет его соседний `@payloadcms/db-postgres`. Сборка
 * Astro инлайнит этот код в чанк `apps/web/dist/server/chunks/`, поэтому
 * `createRequire` разрешает `drizzle-kit/api` ОТ НЕГО — и вверх по дереву искал
 * пакет, которого `apps/web` не объявлял.
 *
 * Подстановка виртуального хранилища в `NODE_PATH` делала импортируемым весь
 * склад pnpm целиком, то есть любая другая фантомная зависимость разрешалась бы
 * так же молча — и упала бы на чистой установке или при `node-linker=hoisted`,
 * где склада нет. Поэтому зависимость объявлена там, где она нужна:
 * `drizzle-kit` стоит в `dependencies` пакета `@otkritka/web`, и pnpm кладёт его
 * в `apps/web/node_modules`, то есть в обычную цепочку разрешения от
 * `apps/web/dist/server/chunks/`.
 *
 * ЗАМЕРЕНО после объявления (та же машина, node v26.7.0, pnpm 10.33.0): собранный
 * сервер, запущенный БЕЗ `NODE_PATH` вовсе (`env -u NODE_PATH node
 * ./dist/server/entry.mjs`), поднимается и отдаёт главную со статусом 200, а в
 * его логе проходит «Pulling schema from database» — то есть `drizzle-kit/api`
 * загрузился, а не был обойдён. Версия закреплена точным значением `0.31.7`,
 * совпадающим с тем, что пинует `@payloadcms/db-postgres`: диапазон дал бы вторую
 * копию пакета в дереве.
 *
 * ## Что модуль делает теперь
 *
 * Только собирает окружение дочернего процесса: текущее `process.env` плюс
 * переменные конкретного входа. Значений по умолчанию он не добавляет —
 * `SITE_URL`, `HOST`, `PORT`, `PAYLOAD_DB_PUSH` проходят сквозь него как есть.
 * Дефолт хоста означал бы canonical, собранный не на том хосте (`CLAUDE.md`,
 * «Правила URL»).
 *
 * Модуль остался отдельным, хотя и стал тонким: сервер поднимают ЧЕТЫРЕ входа
 * (скрипт `start`, его же использует стенд SEO-приёмки, и три смоука), и общая
 * точка сборки окружения нужна, чтобы новый вход не заводил свою.
 */

import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';

/**
 * Корень монорепозитория по маркеру `pnpm-workspace.yaml` — то же правило, что в
 * `src/server-env.ts`: привязки к глубине вложенности нет ни в исходниках, ни в
 * сборке.
 *
 * @param {string} from каталог, от которого идёт поиск вверх
 * @returns {string | null}
 */
export function findWorkspaceRoot(from) {
  let dir = from;
  for (;;) {
    if (existsSync(join(dir, 'pnpm-workspace.yaml'))) {
      return dir;
    }
    const parent = dirname(dir);
    if (parent === dir) {
      return null;
    }
    dir = parent;
  }
}

/**
 * Окружение для дочернего процесса собранного сервера.
 *
 * @param {string} _from каталог входа. Параметр сохранён в подписи, потому что
 *   его передают все четыре входа, а смысл у него один — «откуда запускаем»;
 *   значение сейчас не используется, и это лучше, чем менять четыре вызова ради
 *   одного удалённого правила.
 * @param {Record<string, string>} [extra] переменные конкретного входа: `HOST`,
 *   `PORT`, `SITE_URL`. Они переопределяют текущее окружение — так задумано:
 *   стенд обязан управлять адресом сервера, который сам же и поднял.
 * @returns {NodeJS.ProcessEnv}
 */
export function serverChildEnv(_from, extra = {}) {
  return { ...process.env, ...extra };
}
