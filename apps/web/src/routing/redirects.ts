/**
 * Применение таблицы редиректов к запросу (задача Э4-02) — чистое ядро правила.
 *
 * Норма: ТЗ §7.5 («редиректы применяются до рендеринга»), ТЗ §5.6 и таблица
 * статусов `CLAUDE.md`: перенос — ОДИНОЧНЫЙ 301, удалено без замены — 404/410,
 * удалено с заменой — 301 на релевантный URL; «цепочки редиректов запрещены»;
 * п. 23 — массовый редирект удалённых страниц на главную запрещён.
 *
 * ## Что здесь есть и чего здесь нет
 *
 * Есть: решение «что ответить на этот путь». Нет ни базы, ни HTTP: таблица
 * приходит функцией {@link RedirectLookup}, ответ собирает вызывающий
 * (`../middleware.ts`). Поэтому правило проверяется обычным юнит-тестом на
 * каждый случай, включая петлю и цепочку, а не поднятым сервером с
 * подготовленной базой.
 *
 * Нет и второй модели судьбы URL. Решение администратора при снятии страницы с
 * публикации (группа полей `withdrawal` в `apps/cms`) сюда не читается: CMS уже
 * проецирует его в таблицу `redirects` (`ensureSingleRedirect` в
 * `apps/cms/src/collections/redirect-sync.ts`) — 301 с целью, 410 без цели, а
 * решение «404» намеренно не создаёт записи вовсе. Читать саму запись публичный
 * рендер и не смог бы: она уже не `published`, то есть анонимно не существует.
 *
 * ## Почему цепочка схлопывается на ЧТЕНИИ, а не считается невозможной
 *
 * Коллекция `redirects` не допускает цепочек при записи: планировщик
 * (`apps/cms/src/collections/redirects-plan.ts`, задача Э1-06) переписывает
 * `A→B` + `B→C` в `A→C` и отклоняет петли. Это правило ЗАПИСИ. Опираться на него
 * в рантайме нельзя: в таблицу можно попасть мимо Payload — восстановлением
 * дампа, миграцией, ручным SQL, — а результат такой ошибки виден не в админке, а
 * в двух переходах на каждом запросе к перенесённому адресу, то есть в потере
 * веса ссылки.
 *
 * Выбрано СХЛОПЫВАНИЕ, а не отказ, и вот почему. Отказ (500 или «правила нет»)
 * на цепочке означал бы, что при испорченных данных перенесённый адрес отвечает
 * 404 — то есть уже проиндексированный URL умирает молча. Схлопывание же
 * отвечает ровно тем, что администратор и имел в виду: одним переходом на
 * конечный адрес. Цена — до {@link MAX_CHAIN_HOPS} обращений к таблице на таком
 * запросе; в норме их одно.
 *
 * Отказ остаётся ровно там, где правильного ответа НЕТ: петля (любой 301
 * закольцевал бы клиента), цель за пределами сайта, 301 без цели, негодная цель
 * (параметры, фрагмент), непонятный код. Тогда решение —
 * {@link RedirectDecision} вида `broken`: вызывающий пишет причину в лог и
 * отвечает так, как будто правила нет, — то есть 404 от маршрута. Ответить 301
 * «куда-нибудь» здесь нельзя: это и есть тот самый массовый редирект в никуда,
 * который запрещает п. 23.
 *
 * ОГОВОРКА, названная контролёром `url-guard` 2026-08-28. У одного случая
 * `broken` цена та же, от которой модуль отказывался выше: исчерпание
 * {@link MAX_CHAIN_HOPS}. Цепочка длиннее предела даёт 404 на адресе, который
 * может быть проиндексирован. Другого ответа нет — конца цепочки не видно, а
 * ходить по таблице без предела нельзя, — поэтому здесь выбран отказ, и причина
 * в логе называет исчерпание предела прямым текстом. Достижимо только данными,
 * попавшими в таблицу мимо Payload: при записи цепочки схлопываются (Э1-06), и
 * в исправной таблице длина всегда 1.
 *
 * Модуль ЧИСТЫЙ: без Astro, без Payload. Входит в composite-проект
 * `../../tsconfig.node.json`, проверяется юнит-тестом
 * `tests/unit/web-redirects.test.ts`.
 */

import {
  canonicalizePath,
  currentEnv,
  isReservedPath,
  looksLikeAbsoluteUrl,
  type SharedEnv,
} from '@otkritka/shared';

import { decideMediaRequest } from '../server/media-files.js';
import { PERMANENT_REDIRECT_STATUS } from './path-policy.js';

/** Ответ на удалённый без замены URL (`CLAUDE.md`, «HTTP-статусы»). */
export const GONE_STATUS = 410 as const;

/**
 * Предел длины цепочки.
 *
 * Существует не ради производительности, а ради завершимости: цикл ловится
 * множеством посещённых путей, но таблица приходит извне, и запрос, который
 * ходит по ней без предела, — это отказ в обслуживании через данные. Значение с
 * запасом: в исправной таблице цепочек нет вовсе, длина всегда 1.
 */
export const MAX_CHAIN_HOPS = 8;

/** Коды, которые есть в модели (ТЗ §8.1). Временных редиректов не существует. */
const REDIRECT_CODES = ['301', '410'] as const;

/** Строка таблицы `redirects` в том виде, в каком её читает публичный рендер. */
export interface RedirectRule {
  /** Путь-источник в канонической форме. */
  readonly from: string;
  /** Путь-цель для 301; у 410 — `null`. */
  readonly to: string | null;
  readonly code: (typeof REDIRECT_CODES)[number];
}

/**
 * Чтение одной строки таблицы по пути-источнику.
 *
 * Функция, а не готовая таблица: правило обязано работать без базы в тесте и
 * читать её по одному индексированному запросу в рантайме. Целиком таблица не
 * читается никогда — она растёт с каждым переносом и живёт вечно.
 */
export type RedirectLookup = (path: string) => Promise<RedirectRule | null>;

/** Что ответить на этот путь. */
export type RedirectDecision =
  /** Правила нет — страница отдаётся обычным маршрутом. */
  | { readonly action: 'none' }
  /** Перенос: ОДИН переход на конечный адрес. */
  | {
      readonly action: 'redirect';
      readonly status: typeof PERMANENT_REDIRECT_STATUS;
      readonly location: string;
      /** Сколько строк таблицы пройдено. В исправной таблице всегда 1. */
      readonly hops: number;
      /** Цепочка в данных была схлопнута — вызывающий обязан это залогировать. */
      readonly collapsed: boolean;
    }
  /** Удалено без замены. */
  | { readonly action: 'gone'; readonly status: typeof GONE_STATUS; readonly hops: number }
  /**
   * Правило есть, но применять его нельзя: путь обслуживает сам сайт.
   * Вызывающий пишет предупреждение и отдаёт страницу.
   */
  | { readonly action: 'ignored'; readonly reason: string }
  /**
   * Правило есть, но правильного ответа из него не следует. Вызывающий пишет
   * ошибку и отвечает так, как будто правила нет.
   */
  | { readonly action: 'broken'; readonly reason: string };

export interface RedirectResolutionInput {
  /** Путь запроса. Приводится к канонической форме перед поиском. */
  readonly pathname: string;
  /** Строка запроса вместе с `?`, либо пусто. */
  readonly search?: string;
  readonly lookup: RedirectLookup;
  readonly env?: SharedEnv;
}

function isRedirectCode(value: unknown): value is RedirectRule['code'] {
  return typeof value === 'string' && (REDIRECT_CODES as readonly string[]).includes(value);
}

/**
 * Решение по таблице редиректов для одного запроса.
 *
 * Порядок проверок значим:
 *
 *   1. **Пространство `/media` пропускается без обращения к таблице.**
 *      `CLAUDE.md`: «URL файла постоянный». Редирект с `/media/...` означал бы,
 *      что постоянный адрес перестал быть постоянным, а лишний запрос к базе на
 *      каждую картинку — это цена ни за что. Решение по пути принимает
 *      {@link decideMediaRequest} — та же функция, что отдаёт сами файлы, чтобы
 *      «что относится к /media» не имело второго ответа.
 *
 *      Пропуск сужен до `/media` по вердикту `reviewer` от 2026-08-28. До этого
 *      пропускался ЛЮБОЙ путь, не прошедший `isPageRoute`, то есть любой путь с
 *      расширением в последнем сегменте, — и правило с `from = /index.php`,
 *      `/staraya.html`, `/katalog/otkrytka.htm` не срабатывало никогда и ничего
 *      не писало в лог. Перенос со структуры прежнего сайта — прямо названная
 *      причина, по которой в `src/pages/` живёт перехватывающий маршрут
 *      `[...missing].astro`; правило, видное в админке и не работающее на
 *      сайте, обнаруживается по просевшему трафику через месяцы. Свои файловые
 *      маршруты (`/robots.txt`, `/sitemap.xml` и части карты сайта) при этом
 *      по-прежнему защищены — но следующей проверкой, то есть ЗАМЕТНО;
 *   2. **маршрут, который сайт обслуживает сам, не перекрывается.** Реестр
 *      зарезервированных маршрутов (`packages/shared`) перечисляет пути, которые
 *      запись CMS занять не может: `/`, `/otkrytki`, `/podborki`, `/search`, три
 *      служебные страницы, файловые маршруты, путь админки. Правило с такого
 *      пути в таблице может появиться только руками — и увело бы запрос с живой
 *      страницы, причём причина не была бы видна ни в шаблоне, ни в записи.
 *      Проверка стоит и у НАЧАЛА цепочки, и у каждого её звена: дойдя до
 *      зарезервированного пути, проход останавливается на нём. Обратной силы у
 *      правила нет — 301 НА `/otkrytki` или на главную остаётся обычным
 *      переносом, запрещено только идти по правилу С такого пути;
 *   3. **цепочка проходится до конца** с ловлей петли и пределом длины;
 *   4. **410 обрывает проход** на любом шаге: цепочка, ведущая на удалённый
 *      адрес, — это удалённый адрес, а не 301 на пустоту (то же правило, что у
 *      планировщика в CMS).
 *
 * @throws ничего не бросает: любое расхождение данных с моделью возвращается
 *   решением `broken` с причиной. Исключение здесь превратилось бы в 500 на
 *   странице, которая просто переехала.
 */
export async function resolveRedirect(input: RedirectResolutionInput): Promise<RedirectDecision> {
  const env = input.env ?? currentEnv();
  const search = input.search ?? '';

  let start: string;
  try {
    start = canonicalizePath(input.pathname);
  } catch (error) {
    // Обещание «ничего не бросает» относится и к негодному входу. Путь с
    // параметрами или фрагментом сюда прийти не может (строка запроса
    // приезжает отдельным полем), но исключение из этой функции вызывающий
    // диагностирует как «таблица не прочитана» — то есть отправляет
    // разбираться в базу вместо разбора со своим аргументом.
    return {
      action: 'broken',
      reason:
        `Путь запроса «${input.pathname}» путём страницы не является ` +
        `(${error instanceof Error ? error.message : String(error)}). Строка запроса ` +
        'передаётся отдельным полем `search`, поэтому такое значение означает ошибку ' +
        'вызывающего, а не строки таблицы.',
    };
  }

  // Пространство /media таблице переносов не принадлежит: у файла постоянный
  // адрес. Решение принимает та же функция, что отдаёт сами файлы.
  if (decideMediaRequest(start).action !== 'not-media') {
    return { action: 'none' };
  }

  const rule = await input.lookup(start);
  if (rule === null) {
    return { action: 'none' };
  }

  if (isReservedPath(start, env)) {
    return {
      action: 'ignored',
      reason:
        `В таблице редиректов есть правило с «${start}», но этот путь сайт обслуживает сам ` +
        '(реестр зарезервированных маршрутов в @otkritka/shared). Правило НЕ применено: 301 с ' +
        'адреса живой страницы сделал бы её недостижимой, а причина не была бы видна ни в ' +
        'шаблоне, ни в записи. Запись CMS такой путь занять не может, поэтому правило ' +
        'означает ошибку администратора — удалите его в админке.',
    };
  }

  const visited = new Set<string>([start]);
  let current = rule;
  let hops = 0;

  for (;;) {
    hops += 1;

    if (!isRedirectCode(current.code)) {
      return {
        action: 'broken',
        reason:
          `Правило «${current.from}» имеет код «${String(current.code)}», которого в модели ` +
          `нет (только ${REDIRECT_CODES.join(' и ')}). Догадаться о намерении нельзя: 301 и ` +
          '410 — это разная судьба уже проиндексированного URL.',
      };
    }

    if (current.code === '410') {
      return { action: 'gone', hops, status: GONE_STATUS };
    }

    const target = (current.to ?? '').trim();
    if (target === '') {
      return {
        action: 'broken',
        reason:
          `Правило «${current.from}» с кодом 301 не имеет цели. Отдать 301 некуда, а ` +
          'подставить главную нельзя: массовый редирект удалённых страниц на главную запрещён ' +
          '(п. 23 ТЗ). Правило нуждается в правке: либо цель, либо код 410.',
      };
    }
    if (looksLikeAbsoluteUrl(target)) {
      return {
        action: 'broken',
        reason:
          `Правило «${current.from}» ведёт на «${target}» — адрес вне этого сайта (абсолютный ` +
          'или протокольно-относительный). Хост попадает в URL только из SITE_URL через ' +
          'единственный хелпер, а 301 на чужой домен из таблицы переносов — это уже не ' +
          'перенос страницы.',
      };
    }

    let next: string;
    try {
      next = canonicalizePath(target);
    } catch {
      // Цель с параметрами или фрагментом. Схлопывание цепочки делается именно
      // на ЧТЕНИИ и именно ради данных, попавших в таблицу мимо Payload, —
      // значит, негодная цель обязана возвращаться решением, а не исключением:
      // иначе вызывающий диагностирует её как «таблица не прочитана» и
      // отправляет разбираться в базу вместо одной строки.
      return {
        action: 'broken',
        reason:
          `Правило «${current.from}» ведёт на «${target}» — это не путь страницы: у адреса ` +
          'есть параметры или фрагмент. В таблице переносов хранятся пути в канонической ' +
          'форме; отбросить хвост нельзя (301 ушёл бы не туда, куда написал администратор), ' +
          'а подставить его целиком — значит создать индексируемый адрес с параметрами. ' +
          'Правило нуждается в правке.',
      };
    }
    if (visited.has(next)) {
      return {
        action: 'broken',
        reason:
          `Цепочка редиректов замыкается в петлю на «${next}» (начало — «${start}»). Ответить ` +
          '301 нельзя ни на один её адрес: клиент ходил бы по кругу. Правило нуждается в ' +
          'правке; до этого путь отвечает так, как будто правила нет.',
      };
    }
    visited.add(next);

    if (hops >= MAX_CHAIN_HOPS) {
      return {
        action: 'broken',
        reason:
          `ПРЕДЕЛ ДЛИНЫ ЦЕПОЧКИ ИСЧЕРПАН: с «${start}» пройдено ${String(MAX_CHAIN_HOPS)} ` +
          'переходов, конца нет. Проход прекращён, чтобы один запрос не ходил по базе без ' +
          'предела, и адрес отвечает так, как будто правила нет, — то есть 404 на адресе, ' +
          'который, возможно, проиндексирован. Это осознанное исключение из общего решения ' +
          '«схлопывать, а не отказывать»: продолжать проход нельзя, а угадать конец цепочки ' +
          'нечем. Такой таблицы не бывает при записи через Payload (цепочки схлопываются, ' +
          'Э1-06), поэтому строка в логе означает данные, попавшие мимо него.',
      };
    }

    // Цель — маршрут, который сайт обслуживает сам? Тогда цепочка кончается
    // ЗДЕСЬ. Правило с такого пути применять нельзя (то же решение, что у начала
    // цепочки), а сам адрес живой и законной целью переноса является: 301 на
    // `/otkrytki` или на главную — обычный перенос. Находка `url-guard` от
    // 2026-08-28: без этой проверки правило с «/search», попавшее в таблицу мимо
    // Payload, уводило бы запрос ДАЛЬШЕ, с живой служебной страницы.
    if (isReservedPath(next, env)) {
      return {
        action: 'redirect',
        collapsed: hops > 1,
        hops,
        location: `${next}${search}`,
        status: PERMANENT_REDIRECT_STATUS,
      };
    }

    const following = await input.lookup(next);
    if (following === null) {
      return {
        action: 'redirect',
        collapsed: hops > 1,
        hops,
        location: `${next}${search}`,
        status: PERMANENT_REDIRECT_STATUS,
      };
    }
    current = following;
  }
}
