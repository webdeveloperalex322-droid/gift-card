/**
 * Абсолютный self-canonical для шаблонов apps/web.
 *
 * Это ОБЁРТКА, а не вторая реализация: хост берётся единственным хелпером
 * монорепозитория — `buildAbsoluteUrl` из `@otkritka/shared`, а он читает только
 * `SITE_URL` (`CLAUDE.md`, «Правила URL»). Обёртка существует ради одной вещи:
 * привести путь к канонической форме ДО склейки, чтобы canonical страницы,
 * до которой добрались по неканоническому адресу, всё равно указывал на
 * каноническую форму. Хоста здесь нет ни в каком виде — ни дефолта, ни
 * фолбэка, ни плейсхолдера; пустой `SITE_URL` валит рендер внятной ошибкой.
 *
 * Почему в шаблонах не используется `Astro.site`: это был бы ВТОРОЙ источник
 * хоста (значение конфига Astro), и расхождение canonical со sitemap
 * обнаружилось бы уже после индексации. Поэтому `site` в `astro.config.mjs`
 * не задан вовсе — см. комментарий там.
 */

import { buildAbsoluteUrl, canonicalizePath, currentEnv, type SharedEnv } from '@otkritka/shared';

/**
 * Абсолютный канонический URL для пути страницы или файла.
 *
 * @param pathname путь от корня сайта; приводится к канонической форме
 *   (решение Ч-21 — без завершающего слеша).
 * @param env срез окружения; аргумент, а не чтение `process.env` внутри, чтобы
 *   тест проверял несколько значений `SITE_URL` без мутации глобального
 *   окружения.
 * @throws Error если `SITE_URL` не задан или некорректен, а также если вместо
 *   пути передали абсолютный адрес.
 */
export function canonicalUrlFor(pathname: string, env: SharedEnv = currentEnv()): string {
  return buildAbsoluteUrl(canonicalizePath(pathname), env);
}
