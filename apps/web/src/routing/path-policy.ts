/**
 * Решение по СЫРОЙ цели запроса (`req.url`): отдать, отдать одиночный 301,
 * ответить 404, ответить 400 или не обслуживать вовсе.
 *
 * Это ЧИСТАЯ функция. Её вызывает входной сервер `src/server/front-door.ts`
 * ПЕРВЫМ — до статики, до маршрутизации Astro и до какого-либо разбора пути
 * чужим кодом. Разделение сделано ради проверяемости: правило URL —
 * приоритетное требование (`CLAUDE.md`, «Правила URL»), и проверять его только
 * на поднятом сервере значит не проверять почти никогда. Тесты —
 * `tests/unit/web-path-policy.test.ts`, смоук на живом сервере —
 * `apps/web/scripts/smoke-trailing-slash.mjs`.
 *
 * Само правило слеша здесь НЕ переписывается: границу «страница или файл» даёт
 * `isPageRoute`, каноническую форму для сверки — `canonicalizePath`, оба из
 * `@otkritka/shared`. Локальной копии этих правил в `apps/web` быть не должно:
 * второй потребитель (реестр зарезервированных маршрутов, sitemap, хуки Payload)
 * про локальную копию не узнает, и формы канонического URL разойдутся.
 *
 * ## Требование к импортам внутри `src/routing` и `src/server`
 *
 * Относительные импорты — ТОЛЬКО с расширением `.js` (для `.mts` — `.mjs`). Эти
 * модули компилируются `apps/web/tsconfig.node.json` под `module: NodeNext` и
 * запускаются настоящим Node ESM из `dist/`, где расширение обязательно. Форма
 * без расширения собралась бы у `astro check` (там разрешение `Bundler`) и
 * упала бы на `pnpm check` — расхождение, которое проще запретить, чем
 * объяснять. Это же требование делает проект `apps/web/tsconfig.node.json`
 * владельцем проверки типов этих файлов: раньше её выполнял проект тестов, и
 * граница «чей это код» не совпадала с границей «кто его проверяет».
 *
 * ## Почему решение принимается по сырой цели, а не по `URL.pathname`
 *
 * Замерено на astro 7.2.4 + @astrojs/node 11.1.4 в режиме `standalone` (отчёт
 * контролёра `url-guard`, находки 1–3):
 *
 *   - `/%2F` уходил в бесконечный цикл 301. `@astrojs/node/dist/serve-static.js`
 *     декодирует путь через `decodeURI` (он `%2F` не раскрывает), поэтому путь
 *     не считался каталогом и запрос уходил в `send`; `send` декодирует уже
 *     через `decodeURIComponent`, получал `//`, попадал в корень `dist/client`,
 *     видел каталог и отдавал 301 с добавленным слешем, а обработчик Astro этот
 *     слеш снимал. `/%2F` ⇄ `/%2F/`, до исчерпания лимита переходов клиента;
 *   - `////` давал ТРИ перехода: статический обработчик адаптера снимает ровно
 *     один слеш (`urlPath.slice(0, -1)`), а промежуточные `Location` (`///`,
 *     `//`) протокольно-относительны;
 *   - ветка `isDirectory && hasSlash` того же файла зависит от поведения
 *     `lstat` на каталоге с завершающим слешем, а оно РАЗНОЕ в Windows и Linux
 *     (`ENOENT` против успеха). Зелёный смоук на Windows про Linux ничего не
 *     доказывал.
 *
 * Ни одно из трёх не лечится в пользовательском middleware Astro: до него эти
 * ответы не доходят. Поэтому порядок обработки запроса принадлежит нам —
 * адаптер переведён в `mode: 'middleware'`, а статику и нормализацию отдаёт
 * `src/server/`. Решение про `lstat` каталога принимаем мы (каталог не
 * отдаётся и редиректа не порождает), поэтому расхождение платформ перестаёт
 * быть фактором.
 *
 * ## Инварианты, которые обязана держать эта функция
 *
 *   1. одиночный переход: цель `redirect` сама даёт `serve`, `not-found` или
 *      `not-served`, но не второй `redirect`;
 *   2. `location` никогда не начинается с `//` — иначе это открытый редирект на
 *      чужой хост. Держится по построению: путь с пустым сегментом (а
 *      `//что-то` — именно он) до шага редиректа не доходит;
 *   3. ни один путь не даёт цикла: множество ответов замкнуто на
 *      `serve`/`not-found`/`bad-request`/`not-served`;
 *   4. второго адреса у одного материала не появляется: `.html`, `/index.html`
 *      и любые процентно-кодированные псевдонимы отклоняются.
 *
 * Все четыре проверяются юнит-тестами на корпусе путей и смоуком на живом
 * сервере, а не подразумеваются.
 *
 * ## Что осталось за Astro
 *
 * Встроенный обработчик Astro (`dist/core/routing/trailing-slash-handler.js`)
 * при `trailingSlash: 'never'` тоже умеет отдавать 301. Мы до него не доводим:
 * обработчику Astro передаются ТОЛЬКО пути в канонической форме, а на них
 * `redirectTrailingSlash` возвращает путь без изменений и редиректа не
 * возникает. Это не косметика: в теле его 301 `<meta http-equiv="refresh">`
 * указывает НАЗАД на адрес-источник (`relativeLocation: url.pathname`,
 * шаблон `dist/core/routing/3xx.js`) — дефект апстрима, дающий цикл для
 * клиента, который предпочитает meta-refresh заголовку `Location`. Наш 301
 * отдаётся с ПУСТЫМ телом, поэтому дефект недостижим. Смоук проверяет и это
 * (тело всякого нашего 3xx пусто).
 *
 * Маршрут админки Payload остаётся вне зоны Astro: его обслуживает `apps/cms`
 * на своём порту, обратный прокси направляет `PAYLOAD_ADMIN_PATH` туда. Если
 * такой запрос всё же дошёл сюда — это ошибка маршрутизации окружения, и
 * честный ответ на неё 404, а не редирект на чужом роутере.
 */

import {
  canonicalizePath,
  currentEnv,
  isPageRoute,
  parseAdminPath,
  TRAILING_SLASH,
  type SharedEnv,
} from '@otkritka/shared';

/**
 * Форма канонического маршрута зафиксирована решением Ч-21 — БЕЗ завершающего
 * слеша, и нормализация ниже реализует именно её. Проверка на импорте, а не в
 * обработчике запроса: смена `TRAILING_SLASH` обязана валить запуск с внятной
 * ошибкой, а не молча оставлять сервер с правилом, обратным общему пакету.
 */
if (TRAILING_SLASH as boolean) {
  throw new Error(
    'TRAILING_SLASH в @otkritka/shared стал true, а apps/web нормализует пути в форму БЕЗ ' +
      'завершающего слеша (решение Ч-21). Смена формы канонического URL — это 301 всего сайта; ' +
      'её нельзя выполнить переключением константы, нужно переписать decideRequestTarget и ' +
      'тесты на него.',
  );
}

/**
 * Статус переноса — ровно 301 и только он. Литеральный тип, а не `number`:
 * 302 на нормализации пути означал бы, что поисковая система продолжает считать
 * обе формы URL живыми, то есть дубль (`CLAUDE.md`, «HTTP-статусы»).
 */
export const PERMANENT_REDIRECT_STATUS = 301 as const;

export type TargetDecision =
  /**
   * Цель канонична — отдаём файл из `dist/client`, а если его нет, передаём
   * запрос обработчику Astro. `pathname` уже канонический, поэтому обработчик
   * Astro своего редиректа не отдаст.
   */
  | { readonly action: 'serve'; readonly pathname: string; readonly search: string }
  /** Цель неканонична — одиночный 301 на каноническую форму. */
  | {
      readonly action: 'redirect';
      readonly status: typeof PERMANENT_REDIRECT_STATUS;
      readonly location: string;
    }
  /** Адресом материала такой путь не является — честный 404, без редиректа. */
  | { readonly action: 'not-found'; readonly reason: string }
  /**
   * Адресом материала путь не является, но ответ 404 обязан прийти ПОСЛЕ
   * таблицы переносов.
   *
   * Единственный случай — `.html` в последнем сегменте. Оба требования здесь
   * настоящие и до задачи Э4-02 не конфликтовали:
   *
   *   - у заранее отрендеренной страницы не должно быть второго адреса с 200
   *     (`/o-proekte` и `/o-proekte.html`) — поэтому не `serve`;
   *   - перенос со структуры прежнего сайта — прямо названная причина
   *     существования таблицы переносов, а `.html` там самое частое расширение.
   *     Ответить 404, не заглянув в таблицу, значило бы, что правило с
   *     `from = /staraya.html` видно в админке и не работает на сайте (находки
   *     `reviewer` и `url-guard` от 2026-08-28).
   *
   * Поэтому такой запрос НЕ обслуживается статикой (второй адрес не появляется)
   * и передаётся приложению Astro, где middleware спрашивает таблицу: есть
   * правило — 301 или 410, нет правила — тот же 404, что и раньше.
   *
   * Решение выдаётся ТОЛЬКО на канонической форме пути, поэтому
   * `pathname + search` равны сырой цели запроса байт в байт. Это требование, а
   * не совпадение: входной сервер передаёт приложению именно эту строку, а
   * встроенный обработчик слеша Astro срабатывает раньше нашего middleware — на
   * неканонической форме он ответил бы своим 3xx с телом, в котором meta-refresh
   * ведёт НАЗАД на источник (замер `url-guard` 2026-08-28). Неканоническая форма
   * (`/staraya.html/`, `/a//b.html`) до этой ветки не доходит: она получает
   * `not-found`, как и `/staraya.php/`.
   */
  | {
      readonly action: 'not-found-unless-moved';
      readonly pathname: string;
      readonly search: string;
      readonly reason: string;
    }
  /**
   * Цель запроса как таковая некорректна (кодирование, dot-сегменты, не-путь).
   * 400, а не 404: 404 сообщал бы «такой страницы нет», тогда как здесь нет
   * самого адреса — по нему нечего искать.
   */
  | { readonly action: 'bad-request'; readonly reason: string }
  /** Путь обслуживает не Astro (админка Payload). Ни рендера, ни редиректа. */
  | { readonly action: 'not-served'; readonly reason: string };

export interface TargetPolicyInput {
  /**
   * Цель запроса в СЫРОМ виде — ровно то, что пришло в строке запроса
   * (`req.url`): путь и, если есть, `?query`. Ни декодирования, ни разбора
   * парсером URL до этой функции быть не должно — именно потеря сырой формы
   * порождала находки 1–3.
   */
  readonly target: string;
  /** Путь админки Payload — результат {@link adminRoutePrefix}. */
  readonly adminPath: string;
}

/** Повторный слеш, то есть пустой сегмент пути. */
const DUPLICATE_SLASHES = /\/{2,}/;

/** Верхняя граница управляющих символов ASCII и код DEL. */
const LAST_CONTROL_CHAR_CODE = 0x1f;
const DELETE_CHAR_CODE = 0x7f;

/** Расширение, под которым лежат заранее отрендеренные страницы (`build.format: 'file'`). */
const PRERENDERED_PAGE_SUFFIX = '.html';

/**
 * Маршрут Astro страницы 404 — и ЕДИНСТВЕННЫЙ путь, который сайт адресом не
 * считает, хотя файл под него в сборке есть.
 *
 * Страница 404 пререндерена намеренно (обоснование — шапка `src/pages/404.astro`
 * и `src/server/front-door.ts`): и наш входной обработчик, и приложение Astro
 * читают один и тот же `dist/client/404.html`, поэтому тело 404 у сайта одно.
 * Побочное следствие было дефектом: `dist/client/404.html` — обычный файл
 * статики, и отображение «URL → файл» (`clientFileForPath`) превращало запрос
 * `/404` в 200 с телом страницы «Страница не найдена». То есть у сайта был адрес
 * с soft 404 под статусом 200, и в него же вёл нормализующий 301 с `/404/` —
 * при том, что `/404.html` справедливо отклонялся (замер контролёра `url-guard`,
 * условие переноса на этап 4).
 *
 * Индексного вреда не случилось (страница `noindex`, canonical у неё нет,
 * внутренних ссылок на `/404` ноль), но требование «страница 404 отдаёт
 * настоящий 404» на этом адресе не выполнялось, а на этапе 4 адрес с 200
 * пришлось бы отдельным правилом исключать из sitemap.
 *
 * Решение: путь адресом НЕ является — ни со слешем, ни без. Отказ, а не редирект
 * и не 200:
 *
 *   - `not-found` вместо `serve` снимает второй адрес у тела 404;
 *   - `not-found` вместо `redirect` на `/404/` — потому что 301 вёл бы на адрес,
 *     который сам отвечает 404 (тот же запрет, что у пагинации пустого узла);
 *   - тело ответа при этом остаётся ТЕМ ЖЕ единственным: `respondNotFound`
 *     читает `dist/client/404.html`, то есть содержимое страницы никуда не
 *     делось — исчез лишь её собственный адрес.
 *
 * Имя файла выводится отсюда же (`NOT_FOUND_PAGE_FILE`), поэтому «какой файл
 * читает 404» и «какой путь не является адресом» не могут разойтись.
 */
export const NOT_FOUND_PAGE_PATH = '/404';

/** Файл заранее отрендеренной страницы 404 в корне `dist/client`. */
export const NOT_FOUND_PAGE_FILE = `${NOT_FOUND_PAGE_PATH.slice(1)}${PRERENDERED_PAGE_SUFFIX}`;

/**
 * Символы, которых в сегменте пути после декодирования быть не может:
 * разделитель пути, обратный слеш (парсер URL приводит его к `/`) и любой
 * управляющий, включая NUL, табуляцию и перевод строки — последние парсер URL из
 * адреса удаляет, то есть видит адрес иначе, чем видим мы.
 *
 * Разделитель здесь — суть находки 1: `%2F` декодируется в `/` и меняет число
 * сегментов, то есть один адрес превращается в другой уже ПОСЛЕ маршрутизации.
 *
 * Проверка по кодам, а не регулярным выражением: диапазон управляющих символов в
 * литерале regexp — ровно то, на что срабатывает правило eslint
 * `no-control-regex`, и глушить его директивой ради менее читаемой записи
 * незачем.
 */
function hasForbiddenCharacter(segment: string): boolean {
  for (const char of segment) {
    const code = char.codePointAt(0) ?? 0;
    if (code <= LAST_CONTROL_CHAR_CODE || code === DELETE_CHAR_CODE) {
      return true;
    }
    if (char === '/' || char === '\\') {
      return true;
    }
  }
  return false;
}

/**
 * Путь админки Payload из окружения. Значения по умолчанию нет намеренно:
 * захардкоженный `/admin` при нестандартном `PAYLOAD_ADMIN_PATH` означал бы, что
 * Astro нормализует и уводит редиректом чужие маршруты, а настоящую админку
 * пропускает.
 *
 * Разбор значения не повторяется: он живёт в `parseAdminPath` из
 * `@otkritka/shared` — том же, которым пользуется `apps/cms` и реестр
 * зарезервированных маршрутов. Две копии этого разбора однажды уже разошлись.
 *
 * @throws Error если `PAYLOAD_ADMIN_PATH` не задан или задан некорректно.
 */
export function adminRoutePrefix(env: SharedEnv = currentEnv()): string {
  return parseAdminPath(env.PAYLOAD_ADMIN_PATH);
}

/**
 * Убирает ВСЕ завершающие слеши; корень остаётся корнем. Это и есть каноническая
 * форма по решению Ч-21: `/a/` → `/a`, `/a///` → `/a`, `///` → `/`.
 */
function stripTrailingSlashes(pathname: string): string {
  const stripped = pathname.replace(/\/+$/, '');
  return stripped === '' ? '/' : stripped;
}

/** Путь равен префиксу или лежит под ним. `/administrator` под `/admin` не лежит. */
function isUnder(path: string, prefix: string): boolean {
  return path === prefix || path.startsWith(`${prefix}/`);
}

/** Последний непустой сегмент пути; у корня его нет. */
function lastSegment(pathname: string): string | undefined {
  return pathname
    .split('/')
    .filter((segment) => segment !== '')
    .at(-1);
}

/** Разбор сырой цели на путь и строку запроса. Фрагмент в цели запроса недопустим. */
type SplitTarget =
  | { readonly ok: true; readonly path: string; readonly search: string }
  | { readonly ok: false; readonly reason: string };

function splitTarget(target: string): SplitTarget {
  if (target.includes('#')) {
    return {
      ok: false,
      reason:
        `«${target}» содержит «#». Фрагмент в цель HTTP-запроса не входит (RFC 9110): его ` +
        'обрабатывает клиент и на сервер не отправляет. Вырезать фрагмент здесь нельзя — это ' +
        'означало бы обслуживать адрес, которого в протоколе нет.',
    };
  }

  const queryStart = target.indexOf('?');
  const path = queryStart === -1 ? target : target.slice(0, queryStart);
  const search = queryStart === -1 ? '' : target.slice(queryStart);

  if (!path.startsWith('/')) {
    return {
      ok: false,
      reason:
        `«${target}» не является путём от корня. Абсолютная форма цели и форма «*» допустимы ` +
        'только прокси и методу OPTIONS; сайт отвечает по origin-form, поэтому такой запрос ' +
        'отклоняется, а не достраивается догадкой о хосте.',
    };
  }

  return { ok: true, path, search };
}

/** Результат проверки процентного кодирования по сегментам. */
type DecodedPath =
  | { readonly ok: true; readonly decoded: string }
  | { readonly ok: false; readonly reason: string };

/**
 * Проверяет процентное кодирование каждого сегмента и возвращает декодированный
 * путь.
 *
 * Проверка идёт ПО СЕГМЕНТАМ, а не по строке целиком, ровно ради находки 1:
 * `decodeURIComponent` на целом пути превратил бы `/%2F` в `//`, и разница
 * растворилась бы в общем «путь изменился». Здесь же видно, что изменилось
 * именно число сегментов, и отказ получает точную причину.
 */
function decodePathSegments(path: string): DecodedPath {
  const decodedSegments: string[] = [];

  for (const rawSegment of path.split('/')) {
    let decoded: string;
    try {
      decoded = decodeURIComponent(rawSegment);
    } catch {
      return {
        ok: false,
        reason:
          `«${path}»: сегмент «${rawSegment}» не является корректным процентным кодированием. ` +
          'Такой адрес разные потребители (сервер, прокси, краулер) раскроют по-разному, ' +
          'поэтому он отклоняется целиком.',
      };
    }

    if (hasForbiddenCharacter(decoded)) {
      return {
        ok: false,
        reason:
          `«${path}»: сегмент «${rawSegment}» после декодирования содержит разделитель пути или ` +
          'управляющий символ. Число сегментов адреса менялось бы уже ПОСЛЕ маршрутизации — ' +
          'именно так «/%2F» уходил в бесконечный цикл 301 на прежней сборке.',
      };
    }

    if (decoded === '.' || decoded === '..') {
      return {
        ok: false,
        reason:
          `«${path}» содержит dot-сегмент «${decoded}». Клиент обязан свернуть его ДО отправки ` +
          '(RFC 3986), поэтому в цели запроса он означает либо кривой клиент, либо попытку ' +
          'выйти за корень. Свёртка на сервере дала бы второй адрес той же страницы.',
      };
    }

    decodedSegments.push(decoded);
  }

  return { ok: true, decoded: decodedSegments.join('/') };
}

/**
 * Единственное место, где решается судьба входящего запроса.
 *
 * Порядок шагов значим и зафиксирован тестами:
 *
 *   1. разбор сырой цели: фрагмент и не-origin-form отклоняются (400);
 *   2. процентное кодирование по сегментам: `%2F`, `%5C`, управляющие символы и
 *      dot-сегменты отклоняются (400) — см. {@link decodePathSegments};
 *   3. любой оставшийся процентный псевдоним отклоняется (404): канонический
 *      адрес этого сайта кодирования не содержит вовсе (slug — `[a-z0-9-]`,
 *      имена файлов транслитерированы), поэтому `/robots%2Etxt` и `/%2e` — это
 *      второй адрес того же материала, а не опечатка, которую надо исправить
 *      редиректом;
 *   4. `.html` в последнем сегменте — 404, но ПОСЛЕ таблицы переносов
 *      (`not-found-unless-moved`). Заранее отрендеренная страница лежит на диске
 *      как `<путь>.html`, и без этого шага у неё было бы ДВА адреса с 200
 *      (`/o-proekte` и `/o-proekte.html`), причём второй не ловится ни правилом
 *      слеша, ни `isPageRoute`: тот считает путь с расширением URL файла. Тем же
 *      шагом закрывается `/index.html` — второй адрес главной. Статикой такой
 *      путь не обслуживается никогда; отложен только сам ответ 404 — чтобы
 *      правило переноса с легаси-адреса на `.html` работало, а не молчало.
 *      Откладывается ответ ТОЛЬКО на канонической форме пути: `/staraya.html/` и
 *      `/a//b.html` отвечают 404 сразу, тем же правилом, по которому 404 отдают
 *      `/staraya.php/` и `/robots.txt/` (шаг 7);
 *   5. пустой сегмент (`/podborki//prazdniki`) — 404, и проверка стоит ДО снятия
 *      хвостового слеша намеренно. Иначе `/podborki//prazdniki/` получал бы 301
 *      на адрес, который сам же отдаёт 404. Почему 404, а не схлопывание:
 *      схлопывание сделало бы `//evil.example/x` редиректом на
 *      `/evil.example/x`, то есть 301 на выдуманный адрес; отказ вообще не
 *      порождает `Location` и тем самым держит инвариант 2 по построению. Ни
 *      одна наша ссылка такой путь не порождает, а обратный прокси склеивает
 *      повторные слеши сам (`merge_slashes on` у nginx);
 *   6. админка Payload — раньше нормализации: её маршруты Astro не обслуживает
 *      вовсе, поэтому редирект здесь был бы вмешательством в чужой роутер;
 *   7. URL файла (`/robots.txt`, `/sitemap.xml`, `/media/...`) отдаётся как есть,
 *      а с завершающим слешем — 404. Правило слеша к файлам не применяется
 *      (`CLAUDE.md`: «URL файлов слешем не заканчиваются и middleware их не
 *      нормализует»), поэтому 301 на файл мы не выдаём; но и адресом чего-либо
 *      `/robots.txt/` не является;
 *   8. завершающие слеши убираются ОДНИМ 301 — это и есть решение Ч-21;
 *   9. остальное отдаётся.
 */
export function decideRequestTarget(input: TargetPolicyInput): TargetDecision {
  const split = splitTarget(input.target);
  if (!split.ok) {
    return { action: 'bad-request', reason: split.reason };
  }

  const decodedPath = decodePathSegments(split.path);
  if (!decodedPath.ok) {
    return { action: 'bad-request', reason: decodedPath.reason };
  }

  const path = split.path;
  if (decodedPath.decoded !== path) {
    return {
      action: 'not-found',
      reason:
        `«${path}» — процентно-кодированный псевдоним «${decodedPath.decoded}». Канонические ` +
        'адреса этого сайта кодирования не содержат (slug — только [a-z0-9-], имена файлов ' +
        'транслитерированы), поэтому такой адрес не нормализуется редиректом, а не существует: ' +
        'иначе у одного материала было бы сколько угодно адресов с 200.',
    };
  }

  const last = lastSegment(path);
  if (last !== undefined && last.toLowerCase().endsWith(PRERENDERED_PAGE_SUFFIX)) {
    // Таблицу переносов спрашивают ТОЛЬКО о канонической форме такого адреса.
    // Форма со слешем после расширения (`/staraya.html/`) и форма с пустым
    // сегментом (`/a//b.html`) адресами не являются ни на этом сайте, ни на
    // прежнем: ровно так же — 404 без обращения к таблице — сайт уже отвечает на
    // `/staraya.php/` и `/otkrytka.htm/` (шаг 7 ниже). Отказ здесь заодно
    // держит инвариант «приложению уходит цель ИЗ РЕШЕНИЯ»: в ветку
    // `not-found-unless-moved` попадает только путь, равный своей канонической
    // форме, поэтому встроенному обработчику слеша Astro нечего нормализовать —
    // а он срабатывает раньше нашего middleware и отдаёт 3xx с телом, где
    // meta-refresh указывает назад на источник (замер `url-guard` 2026-08-28).
    if (stripTrailingSlashes(path) !== path || DUPLICATE_SLASHES.test(path)) {
      return {
        action: 'not-found',
        reason:
          `«${path}» оканчивается на «${PRERENDERED_PAGE_SUFFIX}», но записан не в канонической ` +
          'форме (завершающий слеш или пустой сегмент). Адресом такой путь не является: URL ' +
          'файла постоянен и второй формы не имеет, поэтому ни 301, ни поиск в таблице ' +
          'переносов ему не полагаются — в таблице лежат адреса прежнего сайта, а формы со ' +
          'слешем после расширения там не было. Ответ тот же, что у «/staraya.php/».',
      };
    }
    return {
      action: 'not-found-unless-moved',
      pathname: path,
      search: split.search,
      reason:
        `«${path}» оканчивается на «${PRERENDERED_PAGE_SUFFIX}». Так называется ФАЙЛ заранее ` +
        'отрендеренной страницы на диске, а не её адрес: адрес — путь без расширения. Отдать ' +
        'оба означало бы два URL с 200 на один материал (запрет «Один материал доступен только ' +
        'по одному пути»). Ответ — 404, но ПОСЛЕ таблицы переносов: со структуры прежнего сайта ' +
        'переносят прежде всего адреса на «.html», и молчаливый 404 отменял бы такое правило ' +
        'целиком.',
    };
  }

  const withoutTrailingSlash = stripTrailingSlashes(path);

  if (DUPLICATE_SLASHES.test(withoutTrailingSlash)) {
    return {
      action: 'not-found',
      reason:
        `«${path}» содержит пустой сегмент. Адресом страницы такой путь не является. Редирект ` +
        'на схлопнутую форму здесь запрещён: ведущий двойной слеш («//host/x») для браузера и ' +
        'краулера — адрес ДРУГОГО хоста, и схлопывание превратило бы его в 301 на выдуманный ' +
        'путь. Отказ не порождает Location вовсе.',
    };
  }

  if (isUnder(withoutTrailingSlash, input.adminPath)) {
    return {
      action: 'not-served',
      reason:
        `«${path}» лежит в маршрутах админки Payload (${input.adminPath} из ` +
        'PAYLOAD_ADMIN_PATH). Их обслуживает apps/cms на своём порту, поэтому apps/web ни ' +
        'рендерит их, ни нормализует: редирект здесь был бы вмешательством в чужой роутер.',
    };
  }

  // Своего адреса у страницы 404 нет — обоснование в {@link NOT_FOUND_PAGE_PATH}.
  // Проверка стоит на пути БЕЗ хвостовых слешей и ДО шага нормализации, поэтому
  // `/404/` тоже получает 404, а не 301 на адрес с 404.
  if (withoutTrailingSlash === NOT_FOUND_PAGE_PATH) {
    return {
      action: 'not-found',
      reason:
        `«${path}» — маршрут страницы 404, а не адрес материала. Тело этой страницы приходит ` +
        'на ЛЮБОЙ несуществующий адрес; собственный адрес с ответом 200 сделал бы её soft 404, ' +
        'то есть страницей, которую пришлось бы отдельным правилом исключать из sitemap. ' +
        'Ответ здесь — тот же 404 с тем же телом.',
    };
  }

  // Предикат зовётся на пути БЕЗ хвостовых слешей, а не на сыром: `isPageRoute`
  // отклоняет протокольно-относительную форму (`//`, `///`) исключением — и это
  // правильно для адреса, который мы СТРОИМ, но здесь вход другой, это цель
  // запроса. Пустые сегменты к этому шагу уже отсечены, а последний непустой
  // сегмент от снятия хвоста не меняется, поэтому решение «страница или файл»
  // остаётся тем же.
  if (!isPageRoute(withoutTrailingSlash)) {
    if (withoutTrailingSlash !== path) {
      return {
        action: 'not-found',
        reason:
          `«${path}» — URL файла с завершающим слешем. Правило слеша (решение Ч-21) описывает ` +
          'маршруты СТРАНИЦ; URL файла постоянен и второй формы не имеет, поэтому 301 здесь ' +
          'означал бы, что постоянный адрес файла перестал быть постоянным. Адресом файла ' +
          'такой путь тоже не является — отсюда 404.',
      };
    }
    return { action: 'serve', pathname: path, search: split.search };
  }

  if (withoutTrailingSlash !== path) {
    return {
      action: 'redirect',
      status: PERMANENT_REDIRECT_STATUS,
      location: `${withoutTrailingSlash}${split.search}`,
    };
  }

  assertCanonical(withoutTrailingSlash);
  return { action: 'serve', pathname: withoutTrailingSlash, search: split.search };
}

/**
 * Сверка с общим пакетом: путь, который мы собираемся отдать как канонический,
 * обязан совпадать с результатом `canonicalizePath`. Это не защита от входных
 * данных (все опасные формы отсечены выше), а защита от РАСХОЖДЕНИЯ двух
 * реализаций одной нормы: если правило в `@otkritka/shared` изменится, сервер
 * упадёт заметно, а не начнёт молча отдавать 200 по двум формам одного URL.
 * Юнит-тест прогоняет через это место весь корпус путей.
 */
function assertCanonical(pathname: string): void {
  const canonical = canonicalizePath(pathname);
  if (canonical !== pathname) {
    throw new Error(
      `Нормализация apps/web разошлась с canonicalizePath из @otkritka/shared: «${pathname}» ` +
        `против «${canonical}». Две формы одного пути, отвечающие 200, — это дубль; продолжать ` +
        'обслуживание запросов в таком состоянии нельзя.',
    );
  }
}

/**
 * Файл в `dist/client`, которым отдаётся канонический путь, — относительный
 * POSIX-путь без ведущего слеша.
 *
 * Правило парное к `build.format: 'file'` из `astro.config.mjs`: заранее
 * отрендеренная страница лежит как `<путь>.html`, корень — как `index.html`, а
 * URL файла отображается сам в себя. Функция чистая и живёт рядом с политикой
 * пути намеренно: это часть отображения «URL → материал», а не деталь работы с
 * файловой системой. Каталоги здесь не возникают вовсе — поэтому и вопрос «что
 * делает `lstat` на каталоге со слешем в Windows и в Linux» перестаёт влиять на
 * ответы сервера (находка 3 контролёра `url-guard`).
 *
 * @param pathname канонический путь из решения `serve`.
 */
export function clientFileForPath(pathname: string): string {
  if (pathname === '/') {
    return `index${PRERENDERED_PAGE_SUFFIX}`;
  }
  const relative = pathname.slice(1);
  return isPageRoute(pathname) ? `${relative}${PRERENDERED_PAGE_SUFFIX}` : relative;
}

/**
 * Каталог неизменяемых артефактов сборки Astro: имя файла содержит хеш
 * содержимого, поэтому ответ кешируется навсегда (`CLAUDE.md`,
 * «Производительность» — длительное кеширование статики).
 *
 * Значение — дефолт `build.assets` в Astro; в `astro.config.mjs` он не
 * переопределяется, и переопределить его без правки этой константы нельзя.
 */
export const IMMUTABLE_ASSETS_PREFIX = '/_astro/';

/** `Cache-Control` для файла из `dist/client`, либо `undefined` — заголовок не ставится. */
export function immutableCacheControlFor(pathname: string): string | undefined {
  return pathname.startsWith(IMMUTABLE_ASSETS_PREFIX)
    ? 'public, max-age=31536000, immutable'
    : undefined;
}
