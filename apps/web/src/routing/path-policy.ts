/**
 * Решение по входящему пути: рендерить, отдать одиночный 301, ответить 404 или
 * не вмешиваться вовсе.
 *
 * Это ЧИСТАЯ функция, а middleware (`../middleware.ts`) — тонкая обёртка над
 * ней. Разделение сделано ради проверяемости: правило завершающего слеша —
 * приоритетное требование (`CLAUDE.md`, «Правила URL», решение Ч-21), и
 * проверять его только на поднятом сервере значит не проверять почти никогда.
 * Тесты — `tests/unit/web-path-policy.test.ts`, смоук на живом сервере —
 * `apps/web/scripts/smoke-trailing-slash.mjs`.
 *
 * Само правило слеша здесь НЕ переписывается: границу «страница или файл» даёт
 * `isPageRoute`, каноническую форму для сравнения — `canonicalizePath`, оба из
 * `@otkritka/shared`. Локальной копии этих правил в `apps/web` быть не должно:
 * второй потребитель (реестр зарезервированных маршрутов, sitemap, хуки Payload)
 * про локальную копию не узнает, и формы канонического URL разойдутся.
 *
 * ## Согласование с самим Astro — это требование, а не вежливость
 *
 * Astro 7.2.4 при `trailingSlash: 'never'` выполняет свой редирект ДО
 * пользовательского middleware: `dist/core/routing/handler.js` вызывает
 * `handleTrailingSlash(state)` и возвращает ответ, не доходя до `render`;
 * правило — `dist/core/routing/trailing-slash-handler.js`. Для заранее
 * отрендеренных страниц то же делает статический обработчик адаптера,
 * `@astrojs/node/dist/serve-static.js`, ветка `case "never"`.
 *
 * Отсюда жёсткое ограничение: на всяком пути, где срабатывает Astro (это ровно
 * пути с завершающим слешем, кроме `/` и внутренних `/_`, `/@`, `/.`, `//`),
 * наша цель обязана СОВПАДАТЬ с его целью. Иначе получается два 301 подряд, то
 * есть цепочка, которая запрещена. Целевая форма Astro — «убрать все
 * завершающие слеши», повторные слеши в СЕРЕДИНЕ он не схлопывает
 * (`collapseDuplicateTrailingSlashes` работает только по хвосту). Поэтому и наше
 * правило убирает только хвост, а путь с пустым сегментом внутри
 * (`/podborki//prazdniki`) не редиректит, а отдаёт 404 — см. {@link decideRequestPath},
 * шаг 5.
 *
 * Своё правило нужно при этом всё равно: у Astro нет и не может быть понятия
 * «путь админки Payload», а поведение фреймворка не является контрактом проекта
 * — смена версии не должна менять форму канонических URL сайта, потому что после
 * индексации это необратимо.
 *
 * Замеренные следствия, которые надо знать проверяющему (astro 7.2.4):
 *   - в `astro dev` встроенный обработчик 301 НЕ отдаёт: при `never` Astro
 *     показывает страницу-предупреждение со статусом 404. Приёмку SEO поэтому
 *     гоняют против собранного сервера, а не против dev;
 *   - маршрут админки с завершающим слешем (`/admin/`) на собранном сервере
 *     всё равно получит 301 от Astro: наше решение `not-served` до него не
 *     доходит. Практических последствий нет — админку Astro не обслуживает
 *     вовсе, её отдаёт `apps/cms` на своём порту, и обратный прокси направляет
 *     `PAYLOAD_ADMIN_PATH` туда, а не сюда. Правило оставлено закодированным,
 *     потому что оно описывает границу ответственности, а не сглаживает
 *     поведение фреймворка.
 */

import {
  canonicalizePath,
  currentEnv,
  isPageRoute,
  isProtocolRelativeUrl,
  parseAdminPath,
  type SharedEnv,
} from '@otkritka/shared';

/**
 * Статус переноса — ровно 301 и только он. Литеральный тип, а не `number`:
 * 302 на нормализации пути означал бы, что поисковая система продолжает считать
 * обе формы URL живыми, то есть дубль (`CLAUDE.md`, «HTTP-статусы»).
 */
export const PERMANENT_REDIRECT_STATUS = 301 as const;

export type PathDecision =
  /** Путь канонический — отдаём страницу или файл. */
  | { readonly action: 'render' }
  /** Путь неканонический — одиночный 301 на каноническую форму. */
  | {
      readonly action: 'redirect';
      readonly status: typeof PERMANENT_REDIRECT_STATUS;
      readonly location: string;
    }
  /** Путь адресом сайта не является — честный 404, без редиректа. */
  | { readonly action: 'not-found'; readonly reason: string }
  /** Путь обслуживает не Astro (админка Payload). Ни рендера, ни редиректа. */
  | { readonly action: 'not-served'; readonly reason: string };

export interface PathPolicyInput {
  /** `URL.pathname` запроса, как его увидел сервер. */
  readonly pathname: string;
  /** `URL.search` запроса: пустая строка либо строка с ведущим `?`. */
  readonly search: string;
  /** Путь админки Payload — результат {@link adminRoutePrefix}. */
  readonly adminPath: string;
}

/**
 * Повторный слеш, то есть пустой сегмент. Проверяется по пути, у которого
 * ведущие разделители уже схлопнуты, а завершающие убраны, — поэтому любое
 * совпадение здесь означает пустой сегмент ВНУТРИ пути.
 */
const DUPLICATE_SLASHES = /\/{2,}/;

/**
 * Путь админки Payload из окружения. Значения по умолчанию нет намеренно:
 * захардкоженный `/admin` при нестандартном `PAYLOAD_ADMIN_PATH` означал бы, что
 * Astro нормализует и уводит редиректом чужие маршруты, а настоящую админку
 * пропускает.
 *
 * Разбор значения не повторяется: он живёт в `parseAdminPath` из
 * `@otkritka/shared` — том же, которым пользуется `apps/cms` и реестр
 * зарезервированных маршрутов. Две копии этого разбора однажды уже разошлись.
 *
 * @throws Error если `PAYLOAD_ADMIN_PATH` не задан или задан некорректно.
 */
export function adminRoutePrefix(env: SharedEnv = currentEnv()): string {
  return parseAdminPath(env.PAYLOAD_ADMIN_PATH);
}

/**
 * Схлопывает ведущие разделители до одного.
 *
 * Зачем это здесь, если `@otkritka/shared` такой вход намеренно ОТКЛОНЯЕТ: там
 * правило про ИСХОДЯЩИЙ адрес, который мы строим сами (canonical, sitemap,
 * редирект по данным CMS) — схлопывание превратило бы чужой хост в первый
 * сегмент пути и спрятало бы подмену. Здесь вход другой: это `pathname`
 * запроса, хост в котором уже разобран браузером, а `//evil/x` — просто путь из
 * сегментов `evil` и `x` на НАШЕМ хосте. Схлопывание обязательно ровно потому,
 * что иначе в `Location` попал бы адрес, начинающийся с `//`, — то есть открытый
 * редирект на чужой хост.
 *
 * Обратный слеш учитывается наравне с прямым: парсер URL приводит `\` к `/`,
 * поэтому распознавание отдано предикату из общего пакета, а не локальному
 * регулярному выражению.
 */
function collapseLeadingSeparators(pathname: string): string {
  if (!isProtocolRelativeUrl(pathname)) {
    return pathname;
  }
  return pathname.replace(/^[/\\]+/, '/');
}

/**
 * Убирает ВСЕ завершающие слеши. Ровно эту форму даёт и Astro при
 * `trailingSlash: 'never'`, поэтому расхождения (то есть второго редиректа) не
 * возникает: `/a/` → `/a`, `/a///` → `/a`, `/` → `/`.
 */
function stripTrailingSlashes(pathname: string): string {
  const stripped = pathname.replace(/\/+$/, '');
  return stripped === '' ? '/' : stripped;
}

/** Путь равен префиксу или лежит под ним. `/administrator` под `/admin` не лежит. */
function isUnder(path: string, prefix: string): boolean {
  return path === prefix || path.startsWith(`${prefix}/`);
}

/**
 * Единственное место, где решается судьба входящего пути.
 *
 * Порядок проверок значим и зафиксирован тестами:
 *
 *   1. ведущие разделители схлопываются — иначе `Location` мог бы начаться с
 *      `//` и увести на чужой хост;
 *   2. админка Payload — раньше всего остального: её маршруты Astro не
 *      обслуживает вовсе (их отдаёт `apps/cms` на своём порту), поэтому
 *      нормализовать их означало бы выдать редирект на чужом роутере. Сравнение
 *      идёт по канонической форме, чтобы `/admin/` и `/admin//` тоже попадали
 *      под правило;
 *   3. URL файла (`/robots.txt`, `/sitemap.xml`, `/media/...`) — как есть:
 *      правило слеша к файлам не применяется, у файлового URL нет второй формы.
 *      Предикат — `isPageRoute` из общего пакета, локальной копии нет.
 *      Проверка стоит ДО нормализации хвоста намеренно, и у неё есть одно
 *      односторонее расхождение с Astro: `/robots.txt/` мы не трогаем, а Astro
 *      отдаст на него 301 (в ветке `never` он расширение не смотрит).
 *      Расхождение безопасно, потому что оно в сторону «мы делаем меньше»:
 *      второго редиректа не появляется, отвечает один Astro;
 *   4. завершающие слеши убираются одним 301 — это и есть решение Ч-21;
 *   5. путь с ПУСТЫМ сегментом внутри (`/podborki//prazdniki`) — 404, а не
 *      редирект. Причина не в эстетике: Astro уже отдал 301 на форму без
 *      хвостового слеша, и наш редирект на схлопнутую форму стал бы вторым
 *      шагом — цепочкой, которая запрещена. 404 закрывает и вторую опасность:
 *      маршрут с rest-параметром способен сматчить путь с пустым сегментом и
 *      отдать 200 по второму адресу той же страницы, то есть дубль. Ни одна
 *      наша ссылка такой путь не порождает (`canonicalizePath` такой формы не
 *      выдаёт), а обратный прокси в production склеивает повторные слеши сам
 *      (`merge_slashes on` — поведение nginx по умолчанию), поэтому цена
 *      строгости здесь нулевая;
 *   6. остальное — рендер.
 *
 * Цепочки редиректов не бывает по построению: цель редиректа — результат
 * {@link stripTrailingSlashes}, а он идемпотентен, поэтому повторный прогон цели
 * даёт `render` или `not-found`, но не второй `redirect`. Это проверяется тестом
 * на каждом случае, а не подразумевается.
 */
export function decideRequestPath(input: PathPolicyInput): PathDecision {
  const pathname = collapseLeadingSeparators(input.pathname);

  if (isUnder(canonicalizePath(pathname), input.adminPath)) {
    return {
      action: 'not-served',
      reason:
        `«${input.pathname}» лежит в маршрутах админки Payload (${input.adminPath} из ` +
        'PAYLOAD_ADMIN_PATH). Их обслуживает apps/cms на своём порту, поэтому Astro ни ' +
        'рендерит их, ни нормализует: редирект здесь был бы вмешательством в чужой роутер.',
    };
  }

  if (!isPageRoute(pathname)) {
    return { action: 'render' };
  }

  const withoutTrailingSlash = stripTrailingSlashes(pathname);

  if (withoutTrailingSlash !== pathname) {
    return {
      action: 'redirect',
      status: PERMANENT_REDIRECT_STATUS,
      location: `${withoutTrailingSlash}${input.search}`,
    };
  }

  if (DUPLICATE_SLASHES.test(withoutTrailingSlash)) {
    return {
      action: 'not-found',
      reason:
        `«${input.pathname}» содержит пустой сегмент. Адресом страницы такой путь не ` +
        'является, и редирект на схлопнутую форму здесь запрещён: Astro уже отдал 301 на ' +
        'форму без завершающего слеша, второй шаг был бы цепочкой редиректов.',
    };
  }

  return { action: 'render' };
}
