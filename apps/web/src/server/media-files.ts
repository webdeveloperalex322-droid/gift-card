/**
 * Отдача производных изображений по `/media/<ключ>` (задача Э2-04b).
 *
 * ## Зачем этот файл существует
 *
 * Решение Ч-03: S3 отложен, производные лежат на локальной ФС и отдаются с
 * СОБСТВЕННОГО домена по пути `/media/...` с `Cache-Control: public,
 * max-age=31536000, immutable`. Раскладку файлов и контракт заголовков даёт
 * `apps/cms` (`src/images/storage.ts`), маршрут — наш: CMS про HTTP-отдачу не
 * знает и знать не должна, иначе при переезде на S3 менялся бы не только origin.
 *
 * ## Три правила, которые здесь держатся, и почему они здесь, а не рядом
 *
 *   1. **Заголовки не переписываются.** `Cache-Control` и `Content-Type` берутся
 *      из `derivativeCacheHeaders` — той же функции, которой пользуется CMS
 *      (после переезда контракта она живёт в `@otkritka/images/media`). Второе
 *      написание заголовка расходится молча, а кеш выдан на год: ошибку нельзя
 *      будет отозвать.
 *   2. **Проверки обхода каталога здесь НЕТ.** Их ровно две на весь сервер и обе
 *      уже написаны: форму цели запроса (`%2F`, dot-сегменты, обратный слеш,
 *      управляющие символы, пустые сегменты) отклоняет политика пути
 *      `../routing/path-policy.ts` ДО этого модуля, а «остались ли мы внутри
 *      корня» проверяет `./static-files.ts` при разрешении файла. Третья
 *      проверка того же самого — это третий ответ на один вопрос, и расходиться
 *      они будут именно в тот момент, когда одну из них ослабят.
 *   3. **Форма ключа — не наше правило.** Её проверяет
 *      `derivativeKeyFromPublicPath` из общего пакета, парная сборке пути. Иначе
 *      достаточно одной правки раскладки файлов, чтобы отдача перестала
 *      совпадать с хранилищем.
 *
 * ## Чего этот слой не делает
 *
 * Не отдаёт каталоги — ни списком, ни индексным файлом: `/media` до него не
 * доходит вовсе (это маршрут страницы, у него нет ключа), а `/media/<каталог>`
 * не проходит форму ключа, потому что у последнего сегмента нет расширения.
 *
 * Отсюда замеренное следствие (`url-guard`, 2026-08-28), оставленное КАК ЕСТЬ:
 * `/media/` отвечает 301 на `/media`, а тот — 404. Оба ответа даёт общее правило
 * слеша (Ч-21), потому что `/media/` формально является маршрутом страницы.
 * Отдельного правила «404 сразу» здесь нет намеренно: адреса `/media` не
 * существует ни у одного файла (URL файлов слешем не заканчиваются и правилом
 * слеша не нормализуются), терять нечего, а исключение из общего правила формы
 * адреса стоило бы дороже одного лишнего перехода на несуществующий путь.
 * Не знает пути оригиналов: корень оригиналов лежит ВНЕ корня производных
 * (условие C4 решения Ч-03), обратной функции «по публичному пути найти
 * оригинал» нет ни здесь, ни в контракте хранилища.
 */

import path from 'node:path';

import { derivativeCacheHeaders, derivativeKeyFromPublicPath } from '@otkritka/images/media';

/**
 * Корень ПУБЛИЧНЫХ производных. Имя переменной совпадает с тем, по которому
 * пишет файлы `apps/cms` (`src/images/storage-env.ts`): одно дерево, один
 * параметр. Дефолта нет намеренно — см. {@link resolveMediaRoot}.
 */
export const MEDIA_ROOT_ENV_KEY = 'IMAGE_STORAGE_DERIVATIVES_ROOT';

export type MediaDecision =
  /** Путь не адресован этому слою: решают статика и приложение Astro. */
  | { readonly action: 'not-media' }
  /** Путь под `/media/`, но адресом производной не является. Ответ — 404. */
  | { readonly action: 'not-found'; readonly reason: string }
  /** Адрес производной: какой ключ читать и с какими заголовками отдавать. */
  | {
      readonly action: 'file';
      readonly key: string;
      readonly headers: Readonly<Record<string, string>>;
    };

/** Префикс, ниже которого запрос принадлежит этому слою. */
const MEDIA_PREFIX = '/media/';

/**
 * Решение по каноническому пути запроса. Чистая функция: файловой системы не
 * касается, поэтому проверяется юнит-тестом, а не поднятым сервером.
 *
 * Почему «не наш путь» и «не найдено» — разные ответы: первый обязан уйти дальше
 * (страницы, `robots.txt`, статика сборки), второй обязан остановиться здесь.
 * Если бы неверный ключ уходил приложению Astro, `/media/<мусор>` попадал бы в
 * маршрутизацию страниц, а адрес файла и адрес страницы — разные пространства.
 */
export function decideMediaRequest(pathname: string): MediaDecision {
  if (!pathname.startsWith(MEDIA_PREFIX)) {
    return { action: 'not-media' };
  }

  const key = derivativeKeyFromPublicPath(pathname);
  if (key === null) {
    return {
      action: 'not-found',
      reason:
        `«${pathname}» не является адресом производной: ключ обязан иметь вид ` +
        '«<префикс>/<сегменты>/<имя>.<расширение>» из символов [a-z0-9-]. Каталог по этому ' +
        'пути не отдаётся ни списком, ни индексным файлом, а форма ключа не «исправляется»: ' +
        'путь файла постоянен, и второй его формы не существует.',
    };
  }

  let headers: Readonly<Record<string, string>>;
  try {
    headers = derivativeCacheHeaders(key);
  } catch (error) {
    // Единственная причина отказа здесь — расширение вне набора вывода
    // пайплайна. Это 404, а не 500: в публичном пространстве лежат только файлы
    // пайплайна, поэтому такого адреса просто нет.
    return {
      action: 'not-found',
      reason: `«${pathname}»: ${error instanceof Error ? error.message : String(error)}`,
    };
  }

  return { action: 'file', headers, key };
}

/**
 * Абсолютный путь корня отдачи из окружения.
 *
 * Значения по умолчанию нет, и это то же правило, что в `apps/cms`
 * (`src/images/storage-env.ts`): подставленный корень означал бы либо отдачу
 * пустого дерева (все изображения битые), либо — если угадать каталогом выше —
 * оригиналы под раздачей, что прямо запрещено ТЗ §6.1. Обе ошибки
 * обнаруживаются не при развёртывании, а по факту.
 *
 * Относительное значение разрешается от корня монорепозитория, а не от рабочего
 * каталога процесса: у `apps/web` и `apps/cms` рабочие каталоги разные, а дерево
 * файлов одно — иначе CMS писала бы файлы в один каталог, а сервер отдавал из
 * другого.
 *
 * @param env срез окружения; аргумент, а не чтение `process.env` внутри, чтобы
 *   тест проверял несколько значений без мутации глобального окружения.
 * @param workspaceRoot корень монорепозитория.
 * @throws Error если переменная не задана или пуста.
 */
export function resolveMediaRoot(
  env: Readonly<Record<string, string | undefined>>,
  workspaceRoot: string,
): string {
  const raw = env[MEDIA_ROOT_ENV_KEY];
  if (typeof raw !== 'string' || raw.trim() === '') {
    throw new Error(
      `Переменная окружения ${MEDIA_ROOT_ENV_KEY} не задана, поэтому корень публичных ` +
        'производных неизвестен и отдавать по /media нечего. Значения по умолчанию у корня ' +
        'нет намеренно: дефолт означал бы либо битые изображения на всех страницах, либо ' +
        'каталог оригиналов под раздачей (ТЗ §6.1). Тот же параметр читает apps/cms, когда ' +
        'ПИШЕТ эти файлы, — значение обязано быть одним. Заполните .env по шаблону ' +
        '.env.example.',
    );
  }
  const value = raw.trim();
  return path.isAbsolute(value) ? path.resolve(value) : path.resolve(workspaceRoot, value);
}
