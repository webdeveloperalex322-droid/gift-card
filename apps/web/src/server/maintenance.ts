/**
 * Режим обслуживания: любой адрес отвечает 503 с заголовком `Retry-After`
 * (задача Э3-11).
 *
 * Норма: `CLAUDE.md`, раздел «HTTP-статусы» — «Сервис недоступен → 503 +
 * Retry-After». Требование не декоративное: 503 с `Retry-After` — единственный
 * ответ, при котором поисковая система понимает «страница жива, приходите
 * позже» и НЕ выбрасывает адрес из индекса. Всё остальное (200 с текстом «ведём
 * работы», 302 на страницу-заглушку, 404) означает для краулера, что материала
 * больше нет, и стоит это переиндексации всего сайта.
 *
 * ## Почему тело страницы — константа в этом файле
 *
 * Требование задачи: «страница 503 сама не должна зависеть от БД, иначе в аварии
 * она не отрендерится». Отсюда и решение: ни чтения глобала настроек, ни разбора
 * lexical, ни рендера Astro. Строка ниже отвечает даже тогда, когда приложение
 * Astro не собралось и когда PostgreSQL недоступен, — то есть ровно в тех
 * состояниях, для которых режим и включают.
 *
 * Вариант «заранее отрендеренная страница `503.astro`» рассмотрен и отклонён: у
 * неё было бы ДВА источника (файл в `dist/client` и резерв на случай его
 * отсутствия), а два источника одного ответа расходятся — так уже случилось со
 * страницей 404, где расхождение пришлось закрывать отдельным условием (`404.astro`
 * обязана быть пререндеренной, тогда файл читают оба пути). У 503 источник один,
 * и разойтись ему не с чем.
 *
 * ## Порядок: проверка стоит ПЕРЕД политикой пути
 *
 * Во время обслуживания `/otkrytki/` не получает 301 на `/otkrytki`, а получает
 * 503 — как и всё остальное, включая файлы `/media/...`. Так сделано намеренно:
 * редирект — это утверждение о канонической форме адреса, и делать такие
 * утверждения из сервиса, который сам себя объявил недоступным, незачем; а
 * половина открывшегося сайта (страницы 503, картинки 200) хуже честной
 * недоступности.
 *
 * Модуль ЧИСТЫЙ: входит в composite-проект `../../tsconfig.node.json`, зовут его
 * и входной сервер (`./front-door.ts`), и middleware (`../middleware.ts`) — то
 * есть правило одно и для собранного сервера, и для `astro dev`.
 */

import type { SharedEnv } from '@otkritka/shared';

/** Имя параметра окружения — выключателя режима. */
export const MAINTENANCE_ENV_KEY = 'MAINTENANCE_MODE';

/** Имя параметра окружения со значением заголовка `Retry-After`, в секундах. */
export const MAINTENANCE_RETRY_AFTER_ENV_KEY = 'MAINTENANCE_RETRY_AFTER';

/**
 * Значение `Retry-After` по умолчанию — 5 минут.
 *
 * Значение по умолчанию здесь ДОПУСТИМО, в отличие от `SITE_URL`, и разница
 * принципиальная: молча подставленный ХОСТ уезжает в canonical и sitemap, то есть
 * портит данные, которые потом придётся исправлять редиректом всего сайта. А
 * заголовок `Retry-After` обязателен при 503 — без него ответ хуже; поэтому
 * разумный дефолт лучше отказа отвечать. Пять минут — типичная длительность
 * перезапуска сервиса: краулер вернётся, а не отложит визит на сутки.
 */
export const DEFAULT_RETRY_AFTER_SECONDS = 300;

/** Значения выключателя, включающие режим. Набор закрыт (см. {@link maintenanceMode}). */
const ON_VALUES: readonly string[] = ['on', '1', 'true', 'yes'];

/** Значения выключателя, оставляющие сайт работать. */
const OFF_VALUES: readonly string[] = ['off', '0', 'false', 'no'];

/** Тело страницы 503 — единственный источник этого ответа. */
export const MAINTENANCE_HTML = [
  '<!doctype html>',
  '<html lang="ru">',
  '<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">',
  '<title>Сайт на техническом обслуживании</title>',
  // `noindex` здесь И заголовок 503: директива относится к ЭТОМУ ответу, а не к
  // адресу. Без неё краулер, который всё-таки разобрал тело, увидел бы страницу
  // без директивы — а правило проекта требует директиву на каждой странице.
  '<meta name="robots" content="noindex,nofollow"></head>',
  '<body><h1>Сайт на техническом обслуживании</h1>',
  '<p>Идут работы. Страницы сайта временно недоступны — зайдите, пожалуйста, позже:',
  'адреса не изменились, ничего искать заново не нужно.</p>',
  '</body></html>',
  '',
].join('\n');

/** Что отвечать: режим включён или сайт работает. */
export type MaintenanceDecision =
  | { readonly action: 'serve-site' }
  | {
      readonly action: 'unavailable';
      readonly status: 503;
      /** Значение заголовка `Retry-After` в секундах. */
      readonly retryAfterSeconds: number;
      readonly body: string;
    };

function readSeconds(raw: string | undefined): number {
  const value = (raw ?? '').trim();
  if (value === '') {
    return DEFAULT_RETRY_AFTER_SECONDS;
  }
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw new Error(
      `${MAINTENANCE_RETRY_AFTER_ENV_KEY}=«${value}» не является числом секунд (целое > 0). ` +
        'Молча подставить дефолт нельзя: тот, кто настраивал окно обслуживания, обязан узнать, ' +
        'что его значение не применилось, — иначе краулер вернётся не тогда, когда ожидалось.',
    );
  }
  return parsed;
}

/**
 * Решение по режиму обслуживания.
 *
 * ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ, и «по умолчанию» здесь означает буквально: незаданный и
 * пустой параметр оставляют сайт работать. Значения «включено» по умолчанию быть
 * не может — иначе первый же запуск без настроенного окружения закрыл бы сайт.
 *
 * НЕПОНЯТНОЕ ЗНАЧЕНИЕ — ОТКАЗ, а не «считаем, что выключено». Опасное направление
 * ошибки здесь именно это: администратор написал `MAINTENANCE_MODE=enabled`,
 * считает сайт закрытым и правит базу, а сайт продолжает отвечать 200 из
 * полуобновлённых данных. Пусть лучше не поднимется сервер — это заметно сразу.
 *
 * @throws Error если значение выключателя не распознано либо `Retry-After` задан
 *   мусором.
 */
export function maintenanceMode(env: SharedEnv): MaintenanceDecision {
  const raw = (env[MAINTENANCE_ENV_KEY] ?? '').trim().toLowerCase();
  if (raw === '' || OFF_VALUES.includes(raw)) {
    return { action: 'serve-site' };
  }
  if (!ON_VALUES.includes(raw)) {
    throw new Error(
      `${MAINTENANCE_ENV_KEY}=«${raw}» — непонятное значение. Включают режим ` +
        `${ON_VALUES.join(', ')}; выключают ${OFF_VALUES.join(', ')} или пустое значение. ` +
        'Трактовать непонятное как «выключено» нельзя: тогда администратор, считающий сайт ' +
        'закрытым, правил бы базу под открытым сайтом.',
    );
  }

  return {
    action: 'unavailable',
    body: MAINTENANCE_HTML,
    retryAfterSeconds: readSeconds(env[MAINTENANCE_RETRY_AFTER_ENV_KEY]),
    status: 503,
  };
}
