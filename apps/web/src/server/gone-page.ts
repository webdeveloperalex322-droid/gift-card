/**
 * Тело ответа 410 «страница удалена» (задача Э4-02).
 *
 * Норма: `CLAUDE.md`, «HTTP-статусы» — «Удалено без замены → 404/410»; п. 23 —
 * страница ошибки содержит навигацию, а массовый редирект удалённых страниц на
 * главную запрещён.
 *
 * ## Почему это константа, а не страница Astro
 *
 * У 410 не может быть маршрута. Маршрут — это адрес, а адреса у ответа «этой
 * страницы больше нет» не существует: он приходит по адресу УДАЛЁННОГО
 * материала, как 404 приходит по любому несуществующему. Ровно по этой причине
 * у страницы 404 своего адреса тоже нет (`../routing/path-policy.ts`,
 * `NOT_FOUND_PAGE_PATH`), и заводить `410.astro` значило бы создать страницу с
 * собственным URL, отвечающую 200, — то есть soft 404, который потом пришлось бы
 * отдельным правилом исключать из sitemap.
 *
 * Второй довод — тот же, что у 503 (`./maintenance.ts`): ответ не должен
 * зависеть от рендера и от базы. 410 отдаётся из middleware ДО рендеринга (ТЗ
 * §7.5), и звать ради него слой данных означало бы обращаться в базу за
 * страницей, которой нет.
 *
 * ## Почему не отдать вместо этого тело 404
 *
 * Тела совпадать не должны. 404 говорит «такого адреса нет — возможно, опечатка»
 * (и именно так написана `../pages/404.astro`), а 410 — «адрес был, материал
 * удалён, возвращаться незачем». Для посетителя, пришедшего по старой ссылке,
 * это разные ответы; для краулера разницу несёт статус, и она уже есть.
 *
 * Навигация в теле обязательна (п. 23) и берётся из {@link SITE_NAV} — того же
 * источника, что печатает меню на каждой странице. Своего списка ссылок здесь
 * нет: он разошёлся бы с меню и однажды повёл бы на несуществующий раздел.
 *
 * Модуль ЧИСТЫЙ: входит в composite-проект `../../tsconfig.node.json`.
 */

import { SITE_NAV } from '../seo/catalog-pages.js';

/** Экранирование текста для HTML. Ссылки собираются из констант, но правило одно. */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const NAV_ITEMS = SITE_NAV.map(
  (link) => `<li><a href="${escapeHtml(link.path)}">${escapeHtml(link.label)}</a></li>`,
).join('\n');

/**
 * Единственный источник тела ответа 410.
 *
 * `noindex,follow` в теле стоит рядом со статусом 410 намеренно: директива
 * относится к ЭТОМУ ответу, а правило проекта требует директиву на каждой
 * странице. `follow` — потому что ссылки в теле ведут на живые разделы.
 */
export const GONE_PAGE_HTML = [
  '<!doctype html>',
  '<html lang="ru">',
  '<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">',
  '<title>Страница удалена</title>',
  '<meta name="robots" content="noindex,follow"></head>',
  '<body><h1>Страница удалена</h1>',
  '<p>Эта страница была на сайте, но её убрали, и замены у неё нет. Ссылка не сломалась —',
  'материала больше не существует, поэтому возвращаться по ней незачем.</p>',
  '<p>Откуда можно продолжить:</p>',
  '<ul>',
  NAV_ITEMS,
  '</ul>',
  '</body></html>',
  '',
].join('\n');
