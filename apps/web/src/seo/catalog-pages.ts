/**
 * Каталоги разделов `/otkrytki` и `/podborki` и навигация сайта (задача Э3-08).
 *
 * Норма: `CLAUDE.md` — «Правила URL» (пространства имён разведены: карточки под
 * `/otkrytki`, подборки под `/podborki`; оба пути — КОНТЕЙНЕРЫ реестра
 * зарезервированных маршрутов), «Рендеринг» (title, H1, canonical, крошки,
 * ссылки — в HTML-ответе сервера; навигация только `<a href>`), «Правила
 * индексации» (в `index,follow` страницу открывает человек), ТЗ §7.6 (крошки), а
 * также следствие Ч-04-5: требование «≤ 4 перехода от главной» держится на
 * прямых ссылках из меню и с главной на группирующие узлы.
 *
 * ## Почему тексты каталогов живут в коде
 *
 * Каталоги — МАРШРУТЫ Astro, а не записи CMS: у них нет ни slug, ни родителя, ни
 * статуса, и создать запись с таким итоговым путём нельзя — реестр помечает оба
 * пути контейнерами. Значит, их title, H1, описание и вводный абзац обязаны
 * где-то лежать, и код — единственное место, где они проверяются тестом. Второй
 * копии этих строк в шаблонах нет: одно значение уходит и в `<h1>`, и в крошку, и
 * в пункт меню — именно поэтому крошка не может разойтись с заголовком страницы,
 * на которую ведёт.
 *
 * ## Чего здесь нет намеренно
 *
 *   - **правила «пустой каталог не отдаёт 200».** Оно живёт в маршруте: решение
 *     принимается по данным (есть ли открытки, есть ли подборки), а этот модуль
 *     данных не читает;
 *   - **ссылок на группирующие узлы таксономии** (`/podborki/prazdniki`,
 *     `/podborki/adresaty`). Это ДАННЫЕ, а не маршруты: узел может быть не
 *     опубликован, и статическая ссылка на него была бы ссылкой на 404. Меню
 *     ведёт на контейнеры, а список групп печатает сам каталог `/podborki` — он
 *     читает записи и выводит только опубликованные. Отсюда и глубина: главная →
 *     `/podborki` → группирующий узел → пара «праздник × адресат» → карточка;
 *   - **`index,follow`.** Оба каталога отдают `noindex,follow`: открыть их в
 *     индекс может только человек с ролью `admin` (п. 7.1 и п. 23 ТЗ), и
 *     значение в этом файле — это ровно то, что страница отдаёт СЕЙЧАС.
 *
 * Модуль ЧИСТЫЙ: без Astro, без Payload, без чтения `process.env`. Входит в
 * composite-проект `../../tsconfig.node.json`, проверяется юнит-тестом
 * `tests/unit/web-catalog-pages.test.ts`.
 */

