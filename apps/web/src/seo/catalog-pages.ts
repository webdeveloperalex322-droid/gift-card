/** Голова документа и директива робота для страницы каталога. */
export interface CatalogPageView {
  /** Self-canonical страницы: у страницы пагинации — ОНА САМА. */
  readonly canonicalPath: string;
  readonly heading: string;
  readonly title: string;
  /** `null` — тега description нет вовсе, а не пустой тег. */
  readonly metaDescription: string | null;
  /** Директива робота, посчитанная единственным разрешателем (задача Э4-01). */
  readonly robots: PageRobots;
}

/**
 * Директива робота каталога на первой странице.
 *
 * Значение фиксировано `noindex,follow`, и это не перестраховка: условия п. 5.1
 * ТЗ каталог не выполняет по пункту «подтверждённый спрос» (данных нет, решение
 * Ч-04-1), а открыть страницу в индекс может только человек. Правка этой
 * константы агентом — нарушение границы автоматизации.
 */
const CATALOG_ROBOTS: RobotsDirective = 'noindex,follow';

/**
 * Голова документа страницы каталога — первой или страницы пагинации.
 *
 * Что здесь закодировано:
 *   - **self-canonical указывает на САМУ СЕБЯ.** У `/otkrytki/page/3` это
 *     `/otkrytki/page/3`, а не первая страница: canonical на первую страницу
 *     означал бы «этой страницы не существует», тогда как она отвечает 200 и
 *     содержит другие открытки;
 *   - **`noindex,follow` на страницах 2+** (решение Ч-01b) — через
 *     `resolvePageRobots`, то есть тем же правилом и тем же кодом, что у списка
 *     подборки, карточки и служебной страницы (задача Э4-01);
 *   - **описание только на первой странице.** Повторить его на всех страницах
 *     значило бы выдать одинаковый description на разных адресах (п. 22.1), а
 *     дописать в него номер — сочинить шаблонный текст. Пусто → тега нет.
 *     Разрешателю передаётся ТО ЖЕ значение, которое пойдёт в тег: отсутствие
 *     описания закрывает страницу от индексации, и расхождение здесь означало бы
 *     индексируемую страницу без description.
 *
 * @throws Error если номер страницы не целое ≥ 1.
 */
export function catalogPageView(key: CatalogKey, page: number): CatalogPageView {
  const facts = CATALOGS[key];
  const metaDescription = page === 1 ? facts.description : null;
  return {
    canonicalPath: paginationPathFor(facts.path, page),
    heading: paginationTitle(facts.heading, page),
    metaDescription,
    robots: resolvePageRobots({
      declared: CATALOG_ROBOTS,
      description: metaDescription,
      listPage: page,
    }).robots,
    title: paginationTitle(facts.title, page),
  };
}

/**
 * Крошки каталога: главная → каталог (→ номер страницы).
 *
 * Текст звена каталога — это его {@link CatalogFacts.heading}, то есть буквально
 * тот же H1, который посетитель увидит на целевой странице: одно значение, а не
 * два совпадающих.
 *
 * На странице пагинации каталог становится ССЫЛКОЙ, а текущим звеном — номер
 * страницы. Так у второй страницы есть путь назад к базовому URL списка, и он
 * ведёт на базовый URL, а не на `/page/1` (которого не существует).
 */
export function catalogBreadcrumbTrail(key: CatalogKey, page: number): BreadcrumbTrail {
  const facts = CATALOGS[key];
  if (page === 1) {
    return buildBreadcrumbTrail({
      ancestors: [],
      current: { label: facts.heading, path: facts.path },
    });
  }
  return buildBreadcrumbTrail({
    ancestors: [{ label: facts.heading, path: facts.path }],
    current: {
      label: paginationCrumbLabel(page),
      path: paginationPathFor(facts.path, page),
    },
  });
}
