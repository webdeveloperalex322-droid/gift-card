  readonly fieldLabel: string;
  /** Текст кнопки отправки формы. */
  readonly submitLabel: string;
  /** Подсказка внутри поля. */
  readonly placeholder: string;
  /** Текст при пустой выдаче. */
  readonly nothingFound: string;
  /** Текст при слишком коротком запросе. */
  readonly tooShort: string;
  /** Текст, когда результатов больше предела. */
  readonly tooMany: string;
  /** Подпись списка найденных открыток. */
  readonly cardsLabel: string;
  /** Подпись списка найденных подборок. */
