/** Голова документа страницы поиска. */
export interface SearchPageView {
  /** ВСЕГДА чистый `/search`: параметры в canonical не попадают (ТЗ §6.5). */
  readonly canonicalPath: string;
  readonly heading: string;
  readonly title: string;
  readonly metaDescription: string;
  /** Директива робота, посчитанная единственным разрешателем (задача Э4-01). */
  readonly robots: PageRobots;
  /** Нормализованный запрос либо `null` — форма показана, поиск не выполнялся. */
  readonly query: string | null;
}

/**
 * Голова документа страницы поиска.
 *
 * @param query уже нормализованный запрос ({@link normalizeSearchQuery}) либо
 *   `null`. Ни на один элемент головы он не влияет — и в этом смысл функции:
 *   набор параметров не меняет ни адрес страницы, ни её заголовок, ни директиву.
 */
export function searchPageView(query: string | null): SearchPageView {
  return {
    canonicalPath: SEARCH_PATH,
    heading: SEARCH_PAGE.heading,
    metaDescription: SEARCH_PAGE.description,
    query,
    // Директива проходит через единственный разрешатель, хотя закрыта уже в
    // объявлении: так у страницы поиска нет СВОЕГО пути к тегу robots. Иначе
    // «источник директивы один» держалось бы на том, что здесь стоит правильная
    // константа, — а это снова дисциплина, а не построение.
    robots: resolvePageRobots({
      declared: SEARCH_ROBOTS,
      description: SEARCH_PAGE.description,
    }).robots,
    title: SEARCH_PAGE.title,
  };
}

/**
 * Нормализованный поисковый запрос либо `null`.
 *
 * `null` означает «поиск не выполнялся»: пустое поле, пробелы или строка короче
 * {@link SEARCH_MIN_QUERY_LENGTH}. Разделять «не искали» и «не нашли» обязательно
 * — иначе первый заход на `/search` показывал бы «ничего не найдено» по
 * несуществующему запросу.
 *
 * Внутренние пробелы схлопываются, края обрезаются, длина ограничена
 * {@link SEARCH_MAX_QUERY_LENGTH}. Подстановочные символы `%` и `_` не
 * вычищаются: значение уходит в запрос ПАРАМЕТРОМ (подстановки строк в SQL нет),
 * а более широкий поиск по ним — поведение поиска, а не дыра.
 */
export function normalizeSearchQuery(raw: string | null | undefined): string | null {
  const collapsed = (raw ?? '').replace(/\s+/gu, ' ').trim();
  if (collapsed.length < SEARCH_MIN_QUERY_LENGTH) {
    return null;
  }
  return collapsed.slice(0, SEARCH_MAX_QUERY_LENGTH);
}

/**
 * Крошки страницы поиска: главная → поиск.
 *
 * Крошки у служебной страницы есть по той же причине, что у информационных
 * (ТЗ §7.6: на всех страницах глубже главной): это путь назад, а не элемент
 * оптимизации. Текущее звено ссылкой не является.
 */
export function searchBreadcrumbTrail(): BreadcrumbTrail {
  return buildBreadcrumbTrail({
    ancestors: [],
    current: { label: SEARCH_PAGE.heading, path: SEARCH_PATH },
  });
}
