/**
 * Общая часть разметки JSON-LD: тип документа и текст для тела `<script>`.
 *
 * Модуль появился на задаче Э3-05, когда разметку понадобилось выводить не
 * только крошками: до этого сериализация жила в `./breadcrumbs.ts` и была
 * типизирована `BreadcrumbListJsonLd`. Второй копии экранирования в проекте быть
 * не должно — забытое экранирование в одной из копий означает закрытый тег
 * `</script>` в заголовке записи, то есть страницу, где остаток разметки
 * оказался в HTML как текст.
 *
 * Модуль ЧИСТЫЙ: ни запросов, ни `process.env`, ни импортов Astro и Payload.
 * Поэтому он входит в composite-проект `../../tsconfig.node.json` и проверяется
 * юнит-тестами из `tests/unit/`.
 */

/**
 * Любой документ JSON-LD этого сайта.
 *
 * Единственное требование — наличие `@context`: без него блок не является
 * связанными данными вовсе, и потребитель прочитает его как обычный JSON. Тип
 * структурный, поэтому конкретные документы (`BreadcrumbList`, `WebPage`,
 * `CollectionPage`) описываются своими интерфейсами и подходят сюда сами, без
 * приведения.
 */
export interface JsonLdDocument {
  readonly '@context': 'https://schema.org';
}

/**
 * Текст для тела `<script type="application/ld+json">`.
 *
 * Экранируются `<`, `>` и `&`: заголовок записи, подпись и описание — это текст,
 * введённый человеком, и последовательность `</script>` внутри строки закрыла бы
 * тег. Экранирование выполняется в JSON-строке (`<`), поэтому смысл
 * значения не меняется — распарсенный результат тождественно равен исходному
 * объекту, что проверяется тестом.
 */
export function jsonLdScriptText(value: JsonLdDocument): string {
  return JSON.stringify(value)
    .replace(/</gu, '\\u003c')
    .replace(/>/gu, '\\u003e')
    .replace(/&/gu, '\\u0026');
}
