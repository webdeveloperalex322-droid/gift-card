/**
 * Видимый заголовок записи: H1 страницы и текст ссылки на неё (задача Э3-05).
 *
 * Правило одно на весь сайт и записано в схеме обеих контентных коллекций
 * («H1 страницы. Пустой — совпадает с title», ТЗ §8.1). Функция существует
 * ровно для того, чтобы трактовка этого правила была ОДНА: до Э3-05 она жила
 * приватной функцией в `../data/breadcrumbs.ts`, и вторая копия в шаблоне
 * карточки означала бы, что текст крошки и H1 страницы, на которую она ведёт,
 * могут разойтись — а крошка обязана совпадать с заголовком, который посетитель
 * там увидит.
 *
 * Модуль ЧИСТЫЙ (без Astro и без типов Payload), поэтому входит в
 * composite-проект `../../tsconfig.node.json` и проверяется юнит-тестом.
 */

/**
 * Поля записи, из которых получается заголовок. Структурный тип, а не `Pick` от
 * сгенерированного типа Payload: модуль обязан грузиться без типов CMS. Мостом
 * к схеме служит слой данных, где тот же объект приходит из `Card` и
 * `Collection`.
 */
export interface HeadingSource {
  readonly title: string;
  readonly h1?: string | null;
}

/**
 * Заголовок записи: H1, а при пустом H1 — title.
 *
 * @throws Error если пусты оба поля. Подставлять вместо заголовка путь, slug или
 *   слово-заглушку нельзя: это единственный H1 страницы и одновременно текст
 *   крошки, а страница без H1 не проходит приёмку (п. 22.2), причём падение
 *   рендера показывает причину сразу, тогда как пустой `<h1></h1>` выглядит
 *   исправной разметкой.
 */
export function recordHeading(record: HeadingSource): string {
  const heading = record.h1?.trim() ?? '';
  if (heading !== '') {
    return heading;
  }
  const title = record.title.trim();
  if (title === '') {
    throw new Error(
      'У записи пусты и H1, и title, поэтому видимого заголовка у страницы нет. Правило ' +
        '«пустой H1 совпадает с title» (ТЗ §8.1) требует, чтобы хотя бы одно из полей было ' +
        'заполнено; подставить вместо заголовка slug или слово-заглушку нельзя — это H1 ' +
        'страницы и текст ссылки на неё одновременно.',
    );
  }
  return title;
}
