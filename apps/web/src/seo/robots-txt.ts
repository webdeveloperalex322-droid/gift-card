/**
 * Содержимое `robots.txt` (задача Э4-03).
 *
 * Норма: решение Ч-22 (2026-08-21) и `CLAUDE.md`, раздел «Sitemap и robots»:
 *
 *   - `Disallow` пишется БЕЗ завершающего слеша — `Disallow: /search`. Форма
 *     префиксная, поэтому покрывает и `/search`, и `/search/`, тогда как форма
 *     со слешем не покрыла бы голый `/search`, который краулер запрашивает
 *     первым;
 *   - **путь админки не публикуется.** Публикация только подсказывает адрес
 *     админки; закрывается она авторизацией и заголовком `X-Robots-Tag`
 *     (`apps/cms`), а на нашей стороне маршруты админки Astro не обслуживает
 *     вовсе (`../routing/path-policy.ts`, решение `not-served`);
 *   - CSS, JS и изображения не блокируются;
 *   - указана абсолютная ссылка на sitemap-индекс.
 *
 * Модуль ЧИСТЫЙ: без Astro, без Payload, без чтения `process.env` (окружение —
 * аргумент). Входит в composite-проект `../../tsconfig.node.json`, проверяется
 * `tests/unit/web-robots-txt.test.ts`.
 *
 * ## Откуда берётся СОСТАВ и откуда ФОРМА
 *
 * Состав закрытых путей — из реестра `@otkritka/shared`: он единственный
 * машинный источник маршрутов сайта, и там же у каждого маршрута записан доступ
 * для обхода (`crawl`). Переписать этот состав здесь списком строк значило бы
 * завести второй реестр: новый служебный маршрут появился бы в коде и не появился
 * бы в `robots.txt` — молча.
 *
 * Форма директив из реестра НЕ выводится и выводиться не может: реестр хранит
 * пути, а «без завершающего слеша», «одна группа `User-agent: *`» и «путь админки
 * не печатаем» — это решение Ч-22. Поэтому оно записано здесь, рядом с генерацией
 * текста, и нигде больше.
 *
 * ## Почему печатаются только записи наполнения реестра
 *
 * Отбор идёт по паре «`crawl === 'closed'` И `source === 'registry'`»:
 *
 *   - `crawl` отвечает на вопрос «закрыт ли маршрут» — свойство самого маршрута;
 *   - `source` отвечает на вопрос «можно ли назвать его вслух». Путь админки
 *     (`admin-env`) закрыт, но приходит из окружения установки и не публикуется
 *     (Ч-22). Производные записи реестра (`extensionless`, `root-segment`) — это
 *     защита имён от путаницы, а не маршруты: страницы по ним нет, и `Disallow`
 *     на них либо не значил бы ничего, либо (`/sitemap`, `/generator`) закрыл бы
 *     префиксной формой больше, чем решено.
 *
 * Пара условий важна именно как пара: по одному `crawl` в файл попал бы путь
 * админки, по одному `source` — весь каталог сайта.
 */

import {
  buildAbsoluteUrl,
  currentEnv,
  reservedRoutes,
  type SharedEnv,
} from '@otkritka/shared';

import { SITEMAP_INDEX_PATH } from './sitemap.js';

/** Тип содержимого ответа. Текст, а не HTML: файл читают роботы. */
export const ROBOTS_TXT_CONTENT_TYPE = 'text/plain; charset=utf-8';

/**
 * Пути, закрытые для обхода, — как их видит реестр.
 *
 * Включает и путь админки: он ЗАКРЫТ, просто не публикуется. Разделение нужно
 * ровно затем, чтобы «закрыт» и «назван в robots.txt» нельзя было перепутать.
 *
 * @throws Error если `PAYLOAD_ADMIN_PATH` не задан или некорректен: реестр без
 *   пути админки неполон, и собирать по нему публичный файл нельзя.
 */
export function crawlerClosedPaths(env: SharedEnv = currentEnv()): readonly string[] {
  return reservedRoutes(env)
    .filter((route) => route.crawl === 'closed')
    .map((route) => route.path);
}

/**
 * Пути, которые ПЕЧАТАЮТСЯ директивой `Disallow`.
 *
 * Порядок — порядок наполнения реестра: он осмысленный (сначала разделы сайта,
 * потом служебные маршруты) и устойчивый, поэтому файл не меняется от запроса к
 * запросу.
 */
export function robotsDisallowPaths(env: SharedEnv = currentEnv()): readonly string[] {
  return reservedRoutes(env)
    .filter((route) => route.crawl === 'closed' && route.source === 'registry')
    .map((route) => route.path);
}

/**
 * Текст `robots.txt`.
 *
 * @throws Error если `SITE_URL` не задан или некорректен (ссылка на карту сайта
 *   абсолютная и собирается единственным хелпером над `SITE_URL`), а также если
 *   не задан `PAYLOAD_ADMIN_PATH`.
 */
export function buildRobotsTxt(env: SharedEnv = currentEnv()): string {
  const disallow = robotsDisallowPaths(env);

  return [
    // Группа одна и общая: разных правил для разных роботов у сайта нет — ни
    // Яндекс, ни Google не получают ничего сверх общего набора. Отдельная группа
    // появилась бы только вместе с правилом, которое к ней относится.
    'User-agent: *',
    ...disallow.map((path) => `Disallow: ${path}`),
    '',
    `Sitemap: ${buildAbsoluteUrl(SITEMAP_INDEX_PATH, env)}`,
    '',
  ].join('\n');
}
