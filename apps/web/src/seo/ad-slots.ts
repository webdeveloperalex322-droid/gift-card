/**
 * Рекламные места: ряд блоков и резерв места под них (задача Э3-12).
 *
 * Норма: решение Ч-11 («два ряда по три блока: под H1 (над сеткой) и после
 * пагинации. Заглушка, размеры и параметры — из настроек в админке; место
 * резервируется по этим значениям»), ТЗ §5.7 («зарезервированные контейнеры
 * фиксированных размеров — реклама не вызывает сдвигов макета, CLS < 0,1; первый
 * экран не занят рекламой полностью; рекламный код загружается отложенно и не
 * блокирует LCP»), ТЗ §10 (резервирование размеров рекламных контейнеров).
 *
 * Модуль ЧИСТЫЙ: без Astro, без Payload, без чтения `process.env`. Входит в
 * composite-проект `../../tsconfig.node.json`, проверяется юнит-тестом
 * `tests/unit/web-ad-slots.test.ts`.
 *
 * ## Что здесь есть и чего здесь нет
 *
 * Есть: превращение настроек ряда в модель разметки — размеры, пропорция,
 * строка стиля, предел на число блоков в ряду.
 *
 * Нет — и это главное:
 *
 *   - **своей трактовки «выводить ли блок».** Она одна на монорепозиторий и
 *     живёт в `@otkritka/shared` (`isAdSlotRenderable`, `renderableAdSlots`):
 *     блок выводится только включённым, с известной позицией и с ОБОИМИ
 *     размерами целыми пикселями. Вторая трактовка означала бы блок, который
 *     админка считает выключенным, а страница печатает;
 *   - **кода рекламной сети.** Сети нет и параметров подключения нет — эта часть
 *     Ч-11 человеком не закрыта. Пока стоит ЗАГЛУШКА с зарезервированным местом:
 *     ни внешнего `<script>`, ни `<iframe>`, ни одного запроса в чужой домен;
 *   - **решения, на каких страницах ряды печатать.** Позиции Ч-11 привязаны к
 *     странице списка (под H1 над сеткой и после пагинации), и ставит их шаблон
 *     такой страницы.
 *
 * ## Почему место резервируется пропорцией, а не жёсткой высотой
 *
 * Ширина колонки контента на телефоне — около 360 px, а типовой блок сети бывает
 * 728×90. Жёсткая высота на узком экране дала бы либо горизонтальную прокрутку,
 * либо полосу пустоты не той высоты — то есть тот же сдвиг макета, только
 * заранее. Пара `max-width` + `aspect-ratio` сжимает коробку вместе с колонкой,
 * поэтому зарезервированное место совпадает с занятым при любой ширине, и
 * значение CLS от ширины экрана не зависит.
 */

import {
  type AdSlotFacts,
  type AdSlotPosition,
  MAX_AD_SLOTS_PER_POSITION,
  type RenderableAdSlot,
  renderableAdSlots,
} from '@otkritka/shared';

/** Видимые подписи рядов. Ряд помечен как рекламный — это требование честности. */
export const AD_ROW_LABELS: Readonly<Record<AdSlotPosition, string>> = {
  'after-pagination': 'Реклама после списка',
  'under-h1': 'Реклама',
};

/**
 * Подпись самой заглушки.
 *
 * Пока сети нет, на месте блока стоит именно заглушка, и она говорит об этом
 * словами. Пустая серая коробка выглядела бы как незагрузившееся содержимое
 * сайта, а не как зарезервированное место.
 */
export const AD_PLACEHOLDER_TEXT = 'Место для рекламы';

/** Рекламное место, готовое к выводу. */
export interface AdPlaceholder extends RenderableAdSlot {
  /** Значение `aspect-ratio` в CSS: `300 / 250`. */
  readonly aspectRatio: string;
  /**
   * Строка `style` контейнера: предельная ширина и пропорция.
   *
   * Строкой, а не двумя атрибутами: размеры приходят из админки, то есть в CSS
   * их можно передать только инлайном — файл стилей о них не знает и знать не
   * может.
   */
  readonly style: string;
}

/**
 * Ряд рекламных мест для позиции.
 *
 * Отбор («выводить или промолчать») делает предикат из `@otkritka/shared`;
 * здесь — предел на число блоков и модель резерва.
 *
 * Предел — ПОСТУСЛОВИЕ, а не второй источник правила: сохранить четвёртый блок в
 * ряду админка не даёт (`validateAdSlotRows`). Но правило появилось позже
 * возможности сохранить настройки, и шаблон обязан оставаться в рамках Ч-11 на
 * любых данных. Отбрасывается ХВОСТ ряда: порядок задаёт редактор, значит первые
 * блоки — его выбор.
 */
export function adRow(
  slots: readonly (AdSlotFacts | null)[] | null | undefined,
  position: AdSlotPosition,
): readonly AdPlaceholder[] {
  return renderableAdSlots(slots, position)
    .slice(0, MAX_AD_SLOTS_PER_POSITION)
    .map((slot) => {
      const aspectRatio = `${String(slot.width)} / ${String(slot.height)}`;
      return {
        ...slot,
        aspectRatio,
        style: `--ad-width: ${String(slot.width)}px; --ad-ratio: ${aspectRatio};`,
      };
    });
}

/**
 * Высота, которую ряд резервирует на широком экране, в пикселях.
 *
 * Это МАКСИМУМ по блокам, а не сумма, и в этом весь смысл горизонтального ряда:
 * три блока по 250 px, поставленные в столбик, съели бы 750 px первого экрана,
 * то есть заняли бы его целиком — прямой запрет ТЗ §5.7. На узком экране
 * фактическая высота ещё меньше: блоки сжимаются пропорцией.
 */
export function adRowReservedHeight(row: readonly AdPlaceholder[]): number {
  return row.reduce((tallest, slot) => Math.max(tallest, slot.height), 0);
}

/** Оба ряда сразу: столько же вызовов, сколько позиций у Ч-11. */
export interface AdRows {
  /** Под H1, над сеткой. */
  readonly underH1: readonly AdPlaceholder[];
  /** После пагинации. */
  readonly afterPagination: readonly AdPlaceholder[];
}

/**
 * Ряды рекламных мест страницы списка.
 *
 * Функция существует, чтобы места страницы приходили ОДНИМ значением: шаблон,
 * собирающий ряды по одному, однажды выведет один и забудет второй — и
 * обнаружится это не сборкой, а отсутствием блока на половине страниц.
 */
export function adRows(
  slots: readonly (AdSlotFacts | null)[] | null | undefined,
): AdRows {
  return {
    afterPagination: adRow(slots, 'after-pagination'),
    underH1: adRow(slots, 'under-h1'),
  };
}
