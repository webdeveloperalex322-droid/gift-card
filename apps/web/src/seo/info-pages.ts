/**
 * Служебные информационные страницы `/o-proekte`, `/usloviya`, `/kontakty`
 * (задача Э3-11).
 *
 * Норма: ТЗ §5.6, решения Ч-19 (тексты правятся в админке) и Ч-23 (именованное
 * исключение: эти три страницы получают `index,follow`, self-canonical и место в
 * sitemap — при условии, что наполнены реальным текстом), `CLAUDE.md` — разделы
 * «Рендеринг», «Правила индексации», «Sitemap и robots».
 *
 * ## Что здесь есть и чего здесь нет
 *
 * Есть: имена страниц, сборка головы документа, крошки, состав ссылок в подвале.
 * Модуль ЧИСТЫЙ — без Astro, без Payload, без чтения `process.env`; входит в
 * composite-проект `../../tsconfig.node.json` и проверяется юнит-тестом
 * `tests/unit/web-info-pages.test.ts`.
 *
 * Нет — и это главное: СВОЕЙ трактовки условия «наполнена реальным текстом».
 * Предикат живёт в `@otkritka/shared` (`isInfoPageIndexable`,
 * `infoPageIndexation`), потому что то же условие решает и судьбу страницы в
 * sitemap (этап 4), и подсказку редактору в админке. Две трактовки одного
 * условия разошлись бы, и расхождение проявилось бы не ошибкой сборки, а
 * страницей-заглушкой в индексе.
 *
 * ## Почему `index,follow` вообще может появиться в коде агента
 *
 * Директива не выставляется здесь литералом и не выводится из заполненности
 * полей. Она — результат КОНЪЮНКЦИИ, где первый множитель это явно включённый
 * человеком выключатель `allowIndexing` (поле доступно только роли `admin`,
 * дефолт закрывающий). То есть код не принимает решение об индексации, а
 * исполняет уже принятое; агент, который вписал бы `'index,follow'` строкой,
 * нарушил бы границу автоматизации (п. 7.1 и п. 23 ТЗ), а агент, который
 * отказался бы читать выключатель, сделал бы решение человека молча
 * недействующим.
 *
 * ## Почему незаполненная страница отдаёт 200, а не 404
 *
 * Решение Ч-23 сформулировано словами «пока стоят заглушки, остаются `noindex` и
 * вне sitemap» — то есть заглушка по этому адресу СУЩЕСТВУЕТ и отвечает. Три
 * довода, по которым это не спор с правилом «пустая или слабая страница не
 * отдаёт 200 как полноценная посадочная»:
 *
 *   1. правило охраняет ПОСАДОЧНЫЕ страницы — те, что претендуют на запрос.
 *      Незаполненная служебная страница закрыта директивой `noindex`, вне
 *      sitemap и в поиске не участвует вовсе, поэтому soft 404 в индексе из неё
 *      не получается;
 *   2. на `/usloviya` ссылается разметка карточки — свойства `license` и
 *      `acquireLicensePage` объекта `ImageObject` (решение Ч-10). Лицензионная
 *      ссылка, ведущая на 404, хуже заглушки: это юридическая отсылка, и её
 *      обрыв виден и человеку, и потребителю разметки;
 *   3. заглушка честная. Она не изображает наполненную страницу: видимым
 *      текстом сказано, что текст ещё не заполнен ({@link INFO_PAGE_STUB_NOTICE}),
 *      и там же ссылка на главную. Обманкой был бы заголовок над пустотой — как
 *      у каталога с пустой сеткой, который поэтому и отдаёт 404
 *      (`../data/catalog.ts`).
 */

import {
  INFO_PAGE_KEYS,
  INFO_PAGE_PATHS,
  type InfoPageFacts,
  type InfoPageIndexation,
  infoPageIndexation,
  type InfoPageKey,
} from '@otkritka/shared';

import type { RobotsDirective } from '../routing/pagination.js';
import { type BreadcrumbTrail, buildBreadcrumbTrail } from './breadcrumbs.js';
import type { NavLink } from './catalog-pages.js';

/**
 * Названия страниц — резерв для `<title>` и `<h1>`, когда поля глобала пусты, и
 * текст ссылки в подвале.
 *
 * Написаны по одной на страницу, а не по заготовке с подстановкой: это имена
 * разделов, и они видны посетителю. Значение здесь НЕ подменяет заполненный
 * `title` — оно нужно ровно затем, чтобы у заглушки был непустой и уникальный
 * `<title>`: пустой `<title>` не является ни допустимой разметкой, ни
 * осмысленным ответом.
 */
export const INFO_PAGE_NAMES: Readonly<Record<InfoPageKey, string>> = {
  about: 'О проекте',
  contacts: 'Контакты',
  terms: 'Условия использования',
};

/**
 * Видимый текст незаполненной служебной страницы.
 *
 * ОДИН на все три страницы, и это не шаблонный SEO-текст (запрет п. 23.4): текст
 * появляется ТОЛЬКО там, где условия Ч-23 не выполнены, то есть на странице с
 * `noindex` и вне sitemap — она не участвует в поиске и ни на какой запрос не
 * претендует. Как только редактор напишет настоящий текст, эта строка со
 * страницы исчезает. Сочинить вместо неё три разных «вводных абзаца» значило бы
 * ровно то, что запрещено, — сгенерировать содержание вместо содержания.
 */
export const INFO_PAGE_STUB_NOTICE =
  'Текст этой страницы ещё не заполнен. Раздел появится здесь после того, как редактор ' +
  'напишет его в админке; до этого страница закрыта от индексации и не входит в карту сайта.';

/** Голова документа и директива робота служебной страницы. */
export interface InfoPageView {
  /** Канонический путь — он же адрес маршрута (решение Ч-21, без слеша). */
  readonly path: string;
  /** Единственный H1 страницы. */
  readonly heading: string;
  /** `<title>`. Отдельно от H1: у страницы это разные роли (ТЗ §8.1). */
  readonly title: string;
  /** `<meta name="description">`. `null` — тега нет вовсе, а не пустой тег. */
  readonly metaDescription: string | null;
  /** Директива робота: результат конъюнкции Ч-23, а не литерал (см. шапку). */
  readonly robots: RobotsDirective;
  /** Тело страницы: lexical-документ из глобала. Разбирает `../seo/rich-text.ts`. */
  readonly body: unknown;
  /**
   * Страница показывает заглушку вместо текста.
   *
   * Отдельным полем, а не выводом из `indexation.gaps`: шаблону нужен ответ на
   * вопрос «печатать ли предупреждение», и он не совпадает с вопросом «можно ли
   * индексировать». Заполненная страница с выключенным выключателем — не
   * заглушка, но и не индексируемая.
   */
  readonly stub: boolean;
  /** Полный разбор условий Ч-23 — для диагностики и для sitemap (этап 4). */
  readonly indexation: InfoPageIndexation;
}

/**
 * Голова документа служебной страницы по содержимому глобала.
 *
 * @param key какая из трёх страниц.
 * @param facts группа `infoPages.<key>` глобала настроек; пустой объект —
 *   нормальное состояние (человек ещё не заполнял).
 */
export function infoPageView(key: InfoPageKey, facts: InfoPageFacts): InfoPageView {
  const indexation = infoPageIndexation(facts);
  const name = INFO_PAGE_NAMES[key];
  const filled = (value: string | null | undefined): string | null => {
    const text = value?.trim() ?? '';
    return text === '' ? null : text;
  };

  const title = filled(facts.title) ?? name;
  // H1 при пустом поле совпадает с title — то же правило, что у контентных
  // коллекций (ТЗ §8.1). Поэтому `h1` и не входит в условия индексации.
  const heading = filled(facts.h1) ?? title;
  // Заглушка — это отсутствие ТЕЛА, а не отсутствие решения об индексации:
  // страница с текстом и выключенным выключателем печатает свой текст.
  const stub = indexation.gaps.includes('body');

  return {
    body: facts.body,
    heading,
    indexation,
    // Директива — результат предиката Ч-23. Литерала `index,follow` в этом файле
    // нет: значение приходит из решения человека (выключатель `allowIndexing`) в
    // конъюнкции с наполненностью.
    robots: indexation.indexable ? 'index,follow' : 'noindex,follow',
    metaDescription: filled(facts.metaDescription),
    path: INFO_PAGE_PATHS[key],
    stub,
    title,
  };
}

/**
 * Крошки служебной страницы: главная → страница.
 *
 * Текст текущего звена — H1 страницы, то есть буквально то, что посетитель видит
 * заголовком: одно значение, а не два совпадающих.
 */
export function infoPageBreadcrumbTrail(view: InfoPageView): BreadcrumbTrail {
  return buildBreadcrumbTrail({
    ancestors: [],
    current: { label: view.heading, path: view.path },
  });
}

/**
 * Ссылки на служебные страницы — ряд в подвале сайта.
 *
 * Почему подвал, а не главное меню. Требование «страница входит в навигацию» —
 * одно из условий п. 5.1, и выполнить его нужно на КАЖДОЙ странице; при этом
 * место этих трёх ссылок в верхнем меню отняло бы его у каталогов, ради которых
 * меню и существует. Подвал печатается тем же layout'ом на каждой странице, то
 * есть условие выполнено так же строго.
 *
 * Ссылки ведут на 200 всегда: служебная страница отвечает 200 и с заглушкой (см.
 * шапку модуля). Это и отличает их от пунктов, ведущих на записи CMS, которых в
 * постоянной навигации нет вовсе.
 *
 * Текст ссылки — {@link INFO_PAGE_NAMES}, а не `title` из глобала: подвал
 * печатается на каждой странице, и читать ради него глобал в каждом шаблоне
 * значило бы добавить обращение к БД к каждому ответу. Расхождение с заголовком
 * целевой страницы при этом возможно — редактор вправе назвать её иначе, — и оно
 * допустимо: имя раздела в навигации и заголовок страницы это разные роли.
 */
export const INFO_PAGE_NAV: readonly NavLink[] = INFO_PAGE_KEYS.map((key) => ({
  label: INFO_PAGE_NAMES[key],
  path: INFO_PAGE_PATHS[key],
}));
