/**
 * Общая память процесса под собранную карту сайта (задача Э4-04, правка по
 * вердикту `reviewer` от 2026-08-28).
 *
 * ## Зачем она появилась
 *
 * Карта сайта собирается НА ЗАПРОСЕ и состоит из четырёх маршрутов:
 * `/sitemap.xml`, `/sitemap-sections.xml`, `/sitemap-cards-N.xml`,
 * `/sitemap-images-N.xml`. Каждый звал сборку модели независимо, общей памяти не
 * было — то есть один проход краулера означал ЧЕТЫРЕ полных обхода каталога
 * (все опубликованные карточки пачками плюс предикат «непуст» на каждый узел
 * таксономии). Адреса публичные, без авторизации и ограничения частоты, и прямо
 * названы в `robots.txt`: повторный запрос — дешёвое усиление нагрузки на базу.
 *
 * Прежняя граница пересмотра («десятки тысяч карточек») закрывала рост ОБЪЁМА и
 * не закрывала множитель «файлов × обход».
 *
 * ## Почему срок ровно такой
 *
 * Срок памяти задаётся снаружи и равен `max-age` заголовка `Cache-Control` тех
 * же файлов — той же константе `SITEMAP_CACHE_SECONDS` (`./sitemap.ts`), а не
 * своему числу. Довод: окно устаревания у карты сайта УЖЕ объявлено этим
 * заголовком — ответ разрешено держать в кеше клиента и посредника ровно
 * столько. Память на тот же срок окна не расширяет, а вторая константа
 * разошлась бы с заголовком молча, и карта отдавалась бы старее, чем обещано.
 *
 * ## Три свойства, которые здесь важны
 *
 *   1. **запоминается ОБЕЩАНИЕ, а не результат.** Четыре одновременных запроса
 *      (обычное поведение краулера) получают один и тот же незавершённый обход,
 *      а не четыре начатых;
 *   2. **отказ не запоминается.** Иначе одна недоступность базы закрывала бы
 *      карту сайта на весь срок памяти, отвечая ошибкой вместо пустоты;
 *   3. **секция одна.** Ключ на сайте один (хост из `SITE_URL`), поэтому
 *      словарь по ключам дал бы только неограниченный рост памяти, а выигрыша
 *      не дал бы. Смена ключа просто строит модель заново.
 *
 * Модуль ЧИСТЫЙ: без Astro, без Payload, без чтения часов по умолчанию только
 * там, где часы не переданы. Входит в composite-проект `../../tsconfig.node.json`,
 * проверяется юнит-тестом `tests/unit/web-sitemap-memo.test.ts`.
 */

/** Память на один срок: отдаёт запомненное либо строит заново. */
export interface SitemapMemo<T> {
  /**
   * Значение по ключу: запомненное, если оно построено этим же ключом и срок не
   * истёк, иначе — результат {@link load}.
   *
   * @param key что различает модели между собой. Практически это хост из
   *   `SITE_URL`: от него зависят все абсолютные адреса карты.
   * @param load сборка модели. Зовётся только когда запомненного нет.
   */
  get(key: string, load: () => Promise<T>): Promise<T>;
}

interface MemoSlot<T> {
  readonly key: string;
  readonly builtAt: number;
  readonly value: Promise<T>;
}

/**
 * @param ttlSeconds срок памяти в секундах. Передаётся снаружи намеренно: он
 *   обязан быть тем же числом, из которого собран заголовок `Cache-Control`
 *   файлов карты сайта (см. шапку модуля).
 * @param now часы. Аргумент, а не `Date.now` внутри, чтобы истечение срока
 *   проверялось тестом, а не пережидалось им.
 */
export function createSitemapMemo<T>(
  ttlSeconds: number,
  now: () => number = () => Date.now(),
): SitemapMemo<T> {
  if (!Number.isFinite(ttlSeconds) || ttlSeconds <= 0) {
    throw new Error(
      `Срок памяти карты сайта «${String(ttlSeconds)}» недопустим: нужно положительное число ` +
        'секунд. Ноль означал бы отсутствие памяти (четыре обхода каталога на один проход ' +
        'краулера), а отрицательное значение — что срок истёк раньше, чем начался.',
    );
  }

  const ttlMs = ttlSeconds * 1000;
  let slot: MemoSlot<T> | null = null;

  return {
    get(key: string, load: () => Promise<T>): Promise<T> {
      const remembered = slot;
      if (remembered !== null && remembered.key === key && now() - remembered.builtAt < ttlMs) {
        return remembered.value;
      }

      const value = load();
      const fresh: MemoSlot<T> = { builtAt: now(), key, value };
      slot = fresh;

      // Отказ забывается сразу, но ОТДАЁТСЯ вызывающему: обработка здесь только
      // очищает память. `void` — потому что эта ветка ничего не возвращает; сам
      // отказ уходит наружу вместе с `value`.
      void value.catch(() => {
        if (slot === fresh) {
          slot = null;
        }
      });

      return value;
    },
  };
}
