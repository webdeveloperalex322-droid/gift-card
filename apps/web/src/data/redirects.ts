/**
 * Чтение таблицы редиректов публичным рендером (задача Э4-02).
 *
 * Одна функция: строка по пути-источнику. Правил здесь нет — они в чистом
 * разрешателе `../routing/redirects.ts`; здесь только запрос.
 *
 * ## Почему по одной строке, а не таблицей целиком
 *
 * Таблица переносов растёт с каждым переездом URL и не убывает никогда: каждый
 * когда-либо изменённый адрес обязан отвечать 301 вечно. Читать её целиком на
 * запрос значило бы линейно расти во времени ответа; держать в памяти —
 * отвечать по устаревшей копии сразу после того, как администратор создал
 * правило в админке (процессы web и cms разные). Поле `from` уникально и
 * проиндексировано, поэтому один точечный запрос дешевле обоих вариантов.
 *
 * Кеша здесь нет намеренно. Он потребовал бы инвалидации из `apps/cms` — то
 * есть второго механизма, который расходится с данными молча. Если запрос на
 * каждый ответ окажется дорогим, кеш появится вместе с инвалидацией, а не
 * вместо неё.
 *
 * ## Права
 *
 * Область чтения — общая (`PUBLIC_READ_SCOPE`): `overrideAccess: false`, без
 * пользователя. Коллекция `redirects` открыта анонимно СОЗНАТЕЛЬНО
 * (`apps/cms/src/collections/redirects.ts`): карта переносов и так наблюдаема
 * извне — она буквально проявляется в ответах 301, — а middleware обязано
 * разрешать редирект на каждом подходящем запросе. Внутренняя заметка редактора
 * (`comment`) при этом закрыта доступом к полю и сюда не приходит; она и не
 * нужна.
 */

import type { Redirect } from '@otkritka/cms/types';
import { canonicalizePath } from '@otkritka/shared';

import type { RedirectRule } from '../routing/redirects.js';
import { payloadClient } from './payload-client.js';
import { PUBLIC_READ_SCOPE } from './read-scope.js';

/**
 * Правило с этого пути либо `null`.
 *
 * Путь приводится к канонической форме перед поиском: в таблице он хранится
 * нормализованным (`normalizeRedirectPath` в CMS), и искать по сырому значению
 * значило бы промахиваться на хвостовом слеше.
 *
 * Годной для {@link RedirectRule} тут считается только полностью заполненная
 * строка: пустой `from` или отсутствующий `code` означают повреждённую запись, и
 * разбираться с ней — дело разрешателя, а не запроса. Поэтому значения
 * передаются как есть, без «починки» и без подстановки умолчаний.
 */
export async function findRedirectFrom(path: string): Promise<RedirectRule | null> {
  const payload = await payloadClient();
  const found = await payload.find({
    ...PUBLIC_READ_SCOPE,
    collection: 'redirects',
    limit: 1,
    pagination: false,
    where: { from: { equals: canonicalizePath(path) } },
  });

  const doc: Redirect | undefined = found.docs[0];
  if (doc === undefined) {
    return null;
  }
  return { code: doc.code, from: doc.from, to: doc.to ?? null };
}
