/**
 * Область чтения публичного рендера (задача Э3-02).
 *
 * ## Главное решение и его цена
 *
 * Все чтения из `apps/web` идут через Local API Payload с `overrideAccess` в
 * значении **false** и БЕЗ пользователя. Тогда ограничение «только `published`»
 * ставит access control CMS (`apps/cms/src/access/policies.ts`,
 * `contentReadAccess` возвращает `Where`, а не логическое значение), а не
 * повторяет `apps/web`.
 *
 * Почему это важнее удобства: правило «черновик публично не существует» —
 * защитное, и второй его экземпляр в шаблонах разошёлся бы с первым молча.
 * Расхождение обнаруживается страницей-черновиком в индексе, а это необратимо в
 * пределах цикла переобхода. Поэтому:
 *
 *   - `overrideAccess` включённым не бывает НИ В ОДНОМ вызове (проверяется
 *     текстовым тестом по всему `apps/web`): включение снимает и фильтр
 *     коллекции, и проверки доступа к полям — то есть отдало бы и черновики, и
 *     служебные поля вроде `storageId` оригинала;
 *   - пользователь не передаётся вовсе. Любой пользователь — это роль, а обе
 *     роли проекта (`admin`, `ai-editor`) черновики видят: сервисный ключ в
 *     публичном рендере означал бы, что страница отдаёт то, что человек ещё не
 *     опубликовал.
 *
 * ## Почему глубина населения связей нулевая
 *
 * `depth: 0` — связь приходит идентификатором, а связанные записи читаются
 * отдельными запросами той же области чтения. При `depth > 0` Payload населяет
 * связь только если её РАЗРЕШЕНО читать, а иначе подставляет идентификатор
 * (`payload/dist/fields/hooks/afterRead/relationshipPopulationPromise.js`:
 * «ids are visible regardless of access controls»). То есть тип значения зависел
 * бы от статуса чужой записи: шаблон получал бы то объект, то число. Явные
 * запросы дают то же самое, но предсказуемо — и заодно неопубликованный узел
 * просто не попадает в перелинковку, а не превращается в ссылку в никуда.
 */

import type { ContentStatus } from '@otkritka/shared';

/**
 * Параметры области чтения, общие для всех запросов публичного рендера.
 *
 * Литеральные типы (`false`, `0`) намеренно: значение — часть контракта, а не
 * настройка. Изменить его «на месте вызова» нельзя, не переписав этот объект.
 */
export const PUBLIC_READ_SCOPE = {
  depth: 0,
  overrideAccess: false,
} as const satisfies { readonly depth: 0; readonly overrideAccess: false };

/**
 * Сколько карточек на странице списка.
 *
 * ПРОВЕНАНС ЗНАЧЕНИЯ: выбор агента, не решение человека — кандидат в реестр
 * решений вместе с числом карточек на странице подборки. Ориентиры, из которых
 * оно взято: минимум 20 открыток на тему (решение Ч-06) — то есть первая
 * страница эталонной темы обязана вмещать всю тему, иначе пагинация появляется
 * на минимально допустимом объёме; и ряд рекламы из трёх блоков (Ч-11) — сетка
 * кратна трём. Значение — параметр функции, а не константа в шаблоне: менять его
 * будет человек, и менять в одном месте.
 */
export const DEFAULT_CARDS_PER_PAGE = 24;

/** Статус, при котором запись существует публично. */
const PUBLIC_STATUS: ContentStatus = 'published';

/**
 * Постусловие чтения: запись, дошедшая до шаблона, опубликована.
 *
 * Это НЕ второй фильтр по статусу — фильтра здесь нет вовсе, есть отказ. Фильтр
 * ставит access control CMS; если запись со статусом `draft` или `review` всё же
 * пришла, значит правило доступа сломано, и узнать об этом надо падением
 * рендера, а не страницей в индексе. Сообщение называет и запись, и статус:
 * ошибка такого класса разбирается по логу, а не воспроизведением.
 *
 * @throws Error если статус не `published` или отсутствует.
 */
export function assertPublicallyReadable<T extends { id: number | string; status?: unknown }>(
  doc: T,
  subject: string,
): T {
  if (doc.status !== PUBLIC_STATUS) {
    throw new Error(
      `Публичный рендер получил ${subject} #${String(doc.id)} со status=«${String(doc.status)}», ` +
        `а публично существует только «${PUBLIC_STATUS}». Запрос уходит с overrideAccess в ` +
        'значении false и без пользователя, поэтому такой ответ означает, что access control ' +
        'коллекции в apps/cms перестал ограничивать анонимное чтение. Рендер прекращён ' +
        'намеренно: отдать эту страницу значит опубликовать то, чего человек не публиковал.',
    );
  }
  return doc;
}

/**
 * Проверяет номер страницы пагинации.
 *
 * Первая страница любого списка живёт по базовому URL, а `/page/1` не существует
 * ни на одном уровне (решение Ч-05). Разбор адреса и ответ 404 — дело маршрута;
 * здесь отказ означает ошибку вызывающего, поэтому он громкий.
 *
 * @throws Error если номер не целое число ≥ 1.
 */
export function assertPageNumber(page: number): number {
  if (!Number.isInteger(page) || page < 1) {
    throw new Error(
      `Номер страницы «${String(page)}» недопустим: ожидается целое число от 1. Первая ` +
        'страница списка живёт по базовому URL, /page/1 не существует (решение Ч-05), поэтому ' +
        'адрес с некорректным номером обязан отвечать 404 в маршруте, а не превращаться в ' +
        'пустой список.',
    );
  }
  return page;
}
