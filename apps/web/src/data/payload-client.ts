/**
 * Единственная точка подключения `apps/web` к Payload (задача Э3-02).
 *
 * ## Почему Local API, а не HTTP к CMS
 *
 * Выбран Local API (`getPayload` + конфиг из `apps/cms`), а не серверный `fetch`
 * к `http://127.0.0.1:3010/api/...`. Три причины, по убыванию веса:
 *
 *   1. **аутентификация не нужна и вредна.** По HTTP публичный рендер ходил бы
 *      либо анонимно (тогда это лишний сетевой хоп ради того же результата),
 *      либо под API-ключом — а ключ принадлежит пользователю и наследует его
 *      роль, то есть `ai-editor` увидел бы черновики. Local API с
 *      `overrideAccess` в значении false и без пользователя даёт ровно права
 *      анонима, без ключа;
 *   2. **меньше движущихся частей в рантайме.** Страницам нужен PostgreSQL, а не
 *      второй HTTP-сервер: при отдаче страниц процесс CMS перестаёт быть
 *      обязательным;
 *   3. **один экземпляр правил.** Хуки, access control и сборка путей исполняются
 *      тем же кодом, что в админке, — в одном процессе, без сериализации.
 *
 * ## Что для этого потребовалось от `apps/cms` (чужая зона, отмечено в отчёте)
 *
 * Экспорт `@otkritka/cms/config` — одна строка в `apps/cms/package.json`.
 * Конфиг сам по себе Next не тянет: в его импортах только `payload`,
 * `@payloadcms/db-postgres`, `@payloadcms/richtext-lexical` и собственные
 * коллекции. Поэтому он загружается и в Vite (шаблоны Astro), и в tsx (смоук).
 *
 * ВАЖНО про место жизни этого модуля: он и всё, что его импортирует, работают
 * ТОЛЬКО внутри сборки Astro (Vite), потому что конфиг — это `.ts` из другого
 * пакета. Входной сервер `apps/web` (`src/server/*`) компилируется в настоящий
 * Node ESM и такой импорт выполнить не сможет — оттуда обращаться сюда нельзя.
 *
 * ## Почему экземпляр один на процесс
 *
 * `getPayload` инициализирует пул подключений к PostgreSQL. Второй экземпляр —
 * второй пул: при SSR-рендере это означало бы новый пул на запрос. Обещание
 * запоминается ДО его разрешения, поэтому параллельные запросы, пришедшие в
 * момент инициализации, ждут одну и ту же инициализацию, а не запускают свою.
 */

import { getPayload, type Payload } from 'payload';

import config from '@otkritka/cms/config';

let initialization: Promise<Payload> | null = null;

/**
 * Экземпляр Payload для чтения контента.
 *
 * Права здесь НЕ задаются — они задаются в каждом запросе (`PUBLIC_READ_SCOPE`).
 * Отдельного «читающего пользователя» у этого клиента нет намеренно: не бывает
 * роли, которой публичный рендер представляется, — он аноним.
 */
export function payloadClient(): Promise<Payload> {
  initialization ??= getPayload({ config });
  return initialization;
}
