/**
 * Изображение карточки из записи CMS: адаптеры «запись → модель разметки»
 * (задача Э3-04).
 *
 * Разделение с `../images/card-image.ts` — по зависимостям, а не по вкусу. Там
 * живут ПРАВИЛА разметки (порядок форматов, дескриптор `w`, резервный файл,
 * `sizes`, безопасный дефолт ленивой загрузки) — чистые функции без типов CMS.
 * Здесь живёт ЧТЕНИЕ ЗАПИСИ: какие поля карточки становятся источниками и
 * описанием. Модуль импортирует сгенерированные типы Payload, поэтому в
 * composite-проект `../../tsconfig.node.json` войти не может, и его тест лежит
 * рядом (`./card-image.test.ts`) — так же и по той же причине, что у
 * `./breadcrumbs.ts`.
 *
 * ## Зачем этот слой существует, если это три строки
 *
 * Он МОСТ ТИПОВ. `../images/card-image.ts` описывает вариант структурно
 * (`ImageVariant`), потому что грузиться без типов CMS обязан. Здесь тот же
 * вариант приходит из `Card['derivative']`, то есть из сгенерированного типа:
 * если в схеме появится ещё один формат вывода или изменится форма зеркала,
 * ошибка вылезет в `pnpm check` ЗДЕСЬ — а не в шаблоне страницы на этапе 3, и
 * не в разметке на проде.
 *
 * Второе назначение: связка «источники и описание — из ОДНОЙ записи». Если бы
 * шаблон передавал в компонент `variants` и `alt` отдельными пропсами, alt одной
 * открытки при вариантах другой был бы выразим — и на странице оказалось бы
 * описание не той картинки.
 *
 * ## Откуда берётся зеркало и почему только оно
 *
 * `card.derivative.variants[]` — поле САМОЙ карточки, которое заполняет хук CMS.
 * Читать связь `card.image` публичный рендер не может: у коллекции
 * `card-images` доступ на чтение — `authenticatedAccess`, а рендер работает
 * правами анонима, поэтому связь пришла бы идентификатором. Отсюда правило: ни
 * `keyBase`, ни `nameStem`, ни `nameSuffix`, ни `revision` для сборки адресов
 * НЕ используются — авторитетен `variant.key`. Те поля служат постоянству пути
 * внутри пайплайна, а не разметке.
 */

import type { Card } from '@otkritka/cms/types';

import {
  buildPictureModel,
  describedImage,
  type ImageAlt,
  type ImageLayout,
  type ImageVariant,
  type PictureModel,
} from '../images/card-image.js';

/**
 * Поля карточки, из которых получается разметка изображения.
 *
 * `Pick` от сгенерированного типа, а не своя копия структуры: новое поле в схеме
 * не должно требовать правки здесь, а исчезнувшее обязано ломать сборку. `slug`
 * входит только ради сообщений об ошибках — по нему человек находит запись.
 */
export type CardImageSource = Pick<Card, 'alt' | 'derivative' | 'slug'>;

/**
 * Варианты производных из зеркала. Пустой массив — законное состояние: у
 * карточки может не быть загруженного изображения (черновик), и тогда разметка
 * не выводится вовсе.
 *
 * Оба уровня опциональны (`derivative?` и `variants?`), поэтому оба покрыты
 * `??`: у записи, сохранённой до появления зеркала, группы может не быть совсем.
 */
export function cardImageVariants(card: Pick<Card, 'derivative'>): readonly ImageVariant[] {
  return card.derivative?.variants ?? [];
}

/**
 * Описание изображения для атрибута `alt` — поле `alt` записи.
 *
 * Пустое значение здесь ОТКАЗ, а не пустой `alt`: открытка не декоративный
 * элемент, её содержание обязано быть описано словами. CMS требует заполненный
 * alt до перевода в `review` (проверка полноты, задача Э1-08), поэтому у
 * опубликованной карточки он есть; пустота означает, что запись попала на
 * страницу в обход статусной модели.
 *
 * Почему отказ, а не тихий пропуск изображения: страница карточки без открытки —
 * это 200 на странице без содержания, то есть ровно то, что запрещает п. 5.1 ТЗ.
 * Отказ виден в журнале сразу; молчаливая деградация видна по трафику через
 * месяц. Тот же выбор и по той же причине сделан у пустого текста звена крошек
 * (`../seo/breadcrumbs.ts`).
 *
 * @throws Error если `alt` записи пуст.
 */
export function cardImageAlt(card: Pick<Card, 'alt' | 'slug'>): ImageAlt {
  try {
    return describedImage(card.alt ?? '');
  } catch (cause) {
    throw new Error(
      `У карточки «${card.slug}» не заполнено описание изображения (поле alt). ` +
        'Подставить вместо него заголовок или пустую строку нельзя: заголовок — не ' +
        'описание картинки, а пустой alt означал бы «изображение декоративное».',
      { cause },
    );
  }
}

export interface CardPictureInput {
  readonly card: CardImageSource;
  readonly layout: ImageLayout;
  /**
   * Первое крупное изображение страницы — решение ШАБЛОНА (см.
   * `../images/card-image.ts`, `PictureModelInput.priority`). Значение по
   * умолчанию задаётся там же и только там.
   */
  readonly priority?: boolean | undefined;
}

/**
 * Модель разметки изображения карточки либо `null`, если производных нет.
 *
 * Порядок проверок значим: при пустом наборе вариантов функция выходит ДО
 * чтения `alt`. Иначе черновик без изображения падал бы с жалобой на описание —
 * то есть с сообщением не о той причине.
 */
export function cardPictureModel(input: CardPictureInput): PictureModel | null {
  const variants = cardImageVariants(input.card);
  if (variants.length === 0) {
    return null;
  }

  return buildPictureModel({
    variants,
    alt: cardImageAlt(input.card),
    layout: input.layout,
    priority: input.priority,
  });
}
