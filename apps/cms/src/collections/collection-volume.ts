/**
 * Наполненность подборки: две ГРАНИЦЫ, а не одна (решения Ч-06, Ч-23, ТЗ п. 5.1).
 * Чистое ядро правил, без Payload и без базы.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ГРАНИЦ ДВЕ. До этой правки ни одно условие
 * п. 5.1 не проверялось в коде вовсе (находка ревизии Э3-05/Э3-06). Но условия
 * эти разные, и валить их в одну проверку неверно:
 *
 *   1. **`published` — «совсем пусто»** ({@link assertNotEmptyForPublish}).
 *      Публичный шаблон подборки отдаёт 404, когда у узла нет ни одной
 *      опубликованной открытки и ни одного опубликованного дочернего узла
 *      (`apps/web/src/data/page-data.ts`, `collectionPageContent` → `null`):
 *      пустая сетка под заголовком — это soft 404. Значит, опубликованный
 *      пустой узел даёт битую внутреннюю ссылку из родительской подборки:
 *      ссылка есть, адрес отвечает 404 (замер `seo-auditor`, вето V5). Условие
 *      здесь ТОЧНО повторяет условие шаблона — иначе «опубликовано» опять
 *      перестало бы означать «отвечает 200».
 *   2. **`index,follow` — порог объёма** ({@link assertEnoughCardsForIndex}).
 *      Ориентир 20–40 открыток на широкую тему из п. 5.1 (решение Ч-06 → 20) —
 *      это условие ОТКРЫТИЯ В ИНДЕКС, а не условие публикации. Опубликованная
 *      страница с пятью открытками в `noindex,follow` законна: человек вправе
 *      держать её открытой для людей и закрытой для поиска. Поэтому порог стоит
 *      на переходе robots в индексируемое значение.
 *
 * ПОЧЕМУ ОТКАЗ, А НЕ ПРЕДУПРЕЖДЕНИЕ. Предупреждение в админке не действует на
 * внешний AI-редактор через REST и GraphQL и не действует на человека, который
 * его пролистал. Условие п. 5.1 либо выполнено, либо нет; невыполненное условие
 * — это отказ.
 *
 * ЧЕГО ЭТИ ПРАВИЛА НЕ ДЕЛАЮТ И НЕ МОГУТ ДЕЛАТЬ. Они не публикуют, не снимают с
 * публикации и не переключают `index/noindex` — ни одна из функций модуля ничего
 * не возвращает и ничего не пишет, её единственный исход это исключение. Решение
 * «опубликовать» и «открыть в индекс» остаётся за человеком (п. 7.1, п. 23):
 * машина здесь только отказывает в невыполненном условии.
 *
 * ГРУППИРУЮЩИЙ УЗЕЛ. У узла вида `group` («Праздники», «Адресаты») собственных
 * открыток нет — его содержание это дочерние узлы. Поэтому порог индексации
 * считается по ПОДДЕРЕВУ ({@link VOLUME_SCOPE}): иначе группа не смогла бы
 * попасть в индекс никогда, сколько бы открыток ни было под ней. Граница «совсем
 * пусто» при этом у всех видов узла одна и та же — та, что у шаблона.
 *
 * ПОРОГ — ПАРАМЕТР, А НЕ КОНСТАНТА. Значение 20 — решение человека (Ч-06), и
 * пересматривает его человек, поэтому оно живёт в
 * {@link MIN_PUBLISHED_CARDS_ENV_KEY} с дефолтом
 * {@link DEFAULT_MIN_PUBLISHED_CARDS}. Мусорное значение — ошибка, а не
 * молчаливый возврат к дефолту: настроивший порог обязан узнать, что настройка
 * не применилась. Ноль запрещён: нулевой порог отменял бы условие п. 5.1, а это
 * решение принимается не переменной окружения.
 */
import { type SharedEnv, currentEnv } from '@otkritka/shared';

import type { CollectionNodeKind } from './collection-path';
import { ContentRuleError } from './status-model';

export const MIN_PUBLISHED_CARDS_ENV_KEY = 'COLLECTION_MIN_PUBLISHED_CARDS';

/** Минимум открыток на теме для индексации — 20 (решение Ч-06, 2026-08-21). */
export const DEFAULT_MIN_PUBLISHED_CARDS = 20;

/**
 * Где искать открытки узла при проверке ПОРОГА ИНДЕКСАЦИИ: у себя или во всём
 * поддереве.
 *
 * Таблица, а не условие в теле хука: вид узла — закрытый набор, и новый вид
 * обязан получить здесь явную строку, а не унаследовать чужое поведение молча.
 */
export const VOLUME_SCOPE: Readonly<Record<CollectionNodeKind, 'own' | 'subtree'>> = {
  group: 'subtree',
  occasion: 'own',
  recipient: 'own',
};

/** Что есть у узла прямо сейчас — в тех же терминах, в которых считает шаблон. */
export interface NodeContent {
  /** Итоговый путь узла — для текста отказа. */
  readonly path: string | null;
  /** Опубликованные открытки, привязанные К ЭТОМУ узлу (плитки шаблона). */
  readonly publishedCards: number;
  /** Опубликованные дочерние узлы (блок «Разделы подборки»). */
  readonly publishedChildren: number;
}

export interface IndexVolume {
  readonly nodeKind: CollectionNodeKind;
  readonly path: string | null;
  /** Опубликованные открытки в области подсчёта ({@link VOLUME_SCOPE}). */
  readonly publishedCards: number;
  readonly threshold: number;
}

/**
 * Порог из окружения, иначе — утверждённое значение
 * {@link DEFAULT_MIN_PUBLISHED_CARDS}.
 *
 * @throws Error если значение задано и не является целым числом больше нуля.
 */
export function resolveMinPublishedCards(env: SharedEnv = currentEnv()): number {
  const raw = env[MIN_PUBLISHED_CARDS_ENV_KEY]?.trim() ?? '';
  if (raw === '') {
    return DEFAULT_MIN_PUBLISHED_CARDS;
  }

  const parsed = Number(raw);
  if (!Number.isInteger(parsed) || parsed < 1) {
    throw new Error(
      `${MIN_PUBLISHED_CARDS_ENV_KEY} должен быть целым числом от 1, получено: «${raw}». ` +
        `Утверждённое значение — ${String(DEFAULT_MIN_PUBLISHED_CARDS)} (решение Ч-06); ` +
        'некорректная настройка не подменяется им молча. Ноль недопустим: он отменил бы ' +
        'условие п. 5.1 «достаточно открыток», а это решение человека, а не настройка.',
    );
  }
  return parsed;
}

function describe(path: string | null): string {
  return path === null ? 'этой подборки' : `подборки «${path}»`;
}

/**
 * Первая граница: узел без содержания не публикуется.
 *
 * Условие повторяет условие шаблона: ни одной опубликованной открытки И ни
 * одного опубликованного дочернего узла. Не «или» — именно так решает `apps/web`,
 * а расхождение здесь означало бы либо опубликованную страницу с 404, либо
 * отказ публиковать узел, который на самом деле отдал бы 200.
 *
 * Граница СТОРОЖИТ ТОЛЬКО ПЕРЕХОД ВПЕРЁД: снятие с публикации последней открытки
 * или последнего дочернего узла оставляет узел опубликованным и пустым. Это
 * принятый риск Э3-13-A (`docs/otkrytye-voprosy.md`) с ценой и с условием, при
 * котором он снимается, — а не свойство, на которое можно опираться.
 *
 * @throws ContentRuleError с кодом `empty-for-publish`
 */
export function assertNotEmptyForPublish(content: NodeContent): void {
  if (content.publishedCards > 0 || content.publishedChildren > 0) {
    return;
  }

  throw new ContentRuleError(
    'empty-for-publish',
    `Опубликовать нельзя: у ${describe(content.path)} нет ни одной опубликованной открытки ` +
      'и ни одного опубликованного дочернего узла. Публичная страница такого узла отдаёт ' +
      '404 — пустая сетка под заголовком это soft 404, — поэтому опубликованный пустой узел ' +
      'даёт битую внутреннюю ссылку из родительской подборки. Требование ТЗ: пустая или ' +
      'слабая страница не отдаёт 200 как полноценная посадочная. Сначала опубликуйте ' +
      'открытки (можно пакетом) или дочерний узел, потом этот.',
  );
}

/**
 * Вторая граница: открыть в `index,follow` можно только при выполненном условии
 * п. 5.1 «достаточно открыток».
 *
 * Отказ, а не понижение robots: понижение было бы решением машины об индексации,
 * а его в проекте не бывает (п. 7.1, п. 23). Отказ оставляет решение человеку —
 * наполнить тему или оставить страницу вне индекса.
 *
 * @throws ContentRuleError с кодом `thin-content-for-index`
 */
export function assertEnoughCardsForIndex(volume: IndexVolume): void {
  if (volume.publishedCards >= volume.threshold) {
    return;
  }

  const scope =
    VOLUME_SCOPE[volume.nodeKind] === 'subtree'
      ? 'во всём поддереве узла (у группирующего узла собственных открыток нет — его ' +
        'содержание это дочерние узлы)'
      : 'в этой подборке';

  throw new ContentRuleError(
    'thin-content-for-index',
    `Открыть в index,follow нельзя: ${scope} опубликованных открыток ` +
      `${String(volume.publishedCards)}, а условие п. 5.1 SEO ТЗ требует минимум ` +
      `${String(volume.threshold)} (ориентир 20–40 для широкой темы, решение Ч-06). ` +
      `Публикация ${describe(volume.path)} при этом законна: опубликованная страница с ` +
      'меньшим содержанием остаётся noindex,follow, потому что в индекс её пускает не ' +
      'публикация, а отдельное решение человека — и только при выполненном условии. ' +
      `Порог настраивается параметром ${MIN_PUBLISHED_CARDS_ENV_KEY}.`,
  );
}
