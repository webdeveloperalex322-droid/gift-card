import type { CollectionConfig } from 'payload';

import { authenticatedAccess, systemFieldAccess } from '../access/policies';

/**
 * Реестр занятых имён файлов (задача Э2-05, суффикс `-N`).
 *
 * Зачем отдельная коллекция, если имя уже лежит в записи изображения. Требование
 * человека (блок 5 п. 3, 2026-08-21): `N` присваивается ОДИН раз при загрузке и
 * **после удаления не переиспользуется**. Вычислять `N` по существующим
 * изображениям нельзя ровно поэтому: удаление ранней записи освободило бы номер,
 * следующая загрузка получила бы тот же путь, а `immutable`-кеш и уже
 * проиндексированный URL продолжали бы указывать на прежний файл. Реестр —
 * единственное место, где занятость имени живёт ДОЛЬШЕ, чем сама запись.
 *
 * Отсюда все решения по правам:
 *
 *   - **записи реестра не удаляются никем, включая `admin`** (`delete: false`).
 *     Удаление строки означало бы освобождение номера, то есть ровно тот сценарий,
 *     от которого реестр защищает. Строка занимает несколько десятков байт —
 *     это дешевле любого «наведения порядка»;
 *   - **создаются только серверным хуком.** `create` закрыт для всех: хук
 *     загрузки работает через Local API с `overrideAccess: true`, а внешний
 *     клиент (REST/GraphQL, форма админки) занять имя вручную не может — иначе
 *     он мог бы зарезервировать чужое имя или, наоборот, вписать уже занятое;
 *   - **не редактируются** (`update: false`): имя в строке — факт о выданном
 *     пути, а не настройка.
 *
 * Уникальность `stem` обеспечивает индекс БАЗЫ, а не запрос перед вставкой:
 * проверка «свободно ли имя» отдельным запросом проигрывает гонке двух
 * одновременных загрузок через API, и обе получили бы один путь.
 */
export const ImageNameClaims: CollectionConfig = {
  slug: 'image-name-claims',
  labels: {
    singular: 'Занятое имя файла',
    plural: 'Занятые имена файлов',
  },
  admin: {
    defaultColumns: ['stem', 'suffix', 'claimedAt'],
    description:
      'Служебный реестр: имена файлов изображений, которые когда-либо были выданы. ' +
      'Строки не удаляются — иначе номер -N достался бы другому изображению, и путь, ' +
      'уже известный поисковику, указывал бы на другой файл.',
    useAsTitle: 'stem',
  },
  access: {
    // Создаёт только хук загрузки (Local API, overrideAccess).
    create: () => false,
    // Не удаляется никем: см. докстринг коллекции.
    delete: () => false,
    // Читать полезно и админу, и сервисному аккаунту: по реестру видно, почему
    // очередное изображение получило суффикс.
    read: authenticatedAccess,
    update: () => false,
  },
  fields: [
    {
      name: 'stem',
      type: 'text',
      required: true,
      unique: true,
      index: true,
      access: { create: systemFieldAccess, update: systemFieldAccess },
      admin: {
        description:
          'Имя файла без расширения вместе с суффиксом (например otkrytka-mame-2). ' +
          'Уникальность держит индекс базы: гонка двух загрузок иначе выдала бы один путь.',
        readOnly: true,
      },
    },
    {
      name: 'suffix',
      type: 'number',
      min: 2,
      access: { create: systemFieldAccess, update: systemFieldAccess },
      admin: {
        description:
          'Число N в суффиксе -N. Пусто у первого имени: у него суффикса нет вовсе, ' +
          'иначе у одного изображения было бы два законных пути («имя» и «имя-1»).',
        readOnly: true,
      },
    },
    {
      name: 'description',
      type: 'text',
      access: { create: systemFieldAccess, update: systemFieldAccess },
      admin: {
        description: 'Описание, из которого имя построено. Нужно для разбора «почему -N».',
        readOnly: true,
      },
    },
    {
      name: 'claimedAt',
      type: 'date',
      access: { create: systemFieldAccess, update: systemFieldAccess },
      admin: { description: 'Когда имя занято.', readOnly: true },
    },
  ],
};
