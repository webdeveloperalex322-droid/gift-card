/**
 * Сериализация CSV для выгрузки SEO-инвентаря (задача Э5-05, ТЗ §8.5).
 *
 * Отдельный модуль, потому что «склеить через запятую» — самая частая причина
 * битой выгрузки: заголовок открытки с запятой или кавычкой рвёт строку, и файл
 * либо не открывается, либо открывается СО СДВИГОМ столбцов. Сдвиг хуже отказа:
 * значения выглядят правдоподобно, только относятся к другим колонкам.
 *
 * Формат — RFC 4180: разделитель `,`, перевод строки `CRLF`, кавычки удваиваются
 * внутри поля. Файл начинается с BOM (U+FEFF) — без него Excel читает UTF-8 как
 * однобайтовую кодировку и кириллица превращается в мусор.
 *
 * ЗАЩИТА ОТ ФОРМУЛ. Значения приходят из полей записей, а записи заполняет в том
 * числе внешний AI-редактор через API. Ячейка, начинающаяся с `=`, `+`, `-` или
 * `@`, в Excel и LibreOffice трактуется как ФОРМУЛА, и открытие выгрузки
 * становится выполнением кода на машине редактора. Поэтому такие значения
 * получают ведущий апостроф. Это видимая правка данных, и она сознательная:
 * выгрузка — отчёт для человека, а не канал переноса значений обратно в базу.
 */

/** BOM: без него Excel открывает UTF-8 как ANSI и вместо кириллицы даёт мусор. */
export const CSV_BOM = '﻿';

/** Разделитель строк RFC 4180. */
export const CSV_EOL = '\r\n';

/**
 * Что вообще может быть ячейкой.
 *
 * Тип узкий намеренно: `unknown` заставил бы `String(...)` превращать объект в
 * «[object Object]» — то есть в правдоподобно выглядящий мусор внутри отчёта.
 * Приведение к строке — обязанность вызывающего, который знает, что у него за
 * значение.
 */
export type CsvValue = boolean | number | string | null | undefined;

/** Символы, с которых начинается формула в табличном редакторе. */
const FORMULA_STARTERS = ['=', '+', '-', '@', '\t', '\r'];

/**
 * Одно поле CSV: экранирование кавычек, обрамление при необходимости и
 * нейтрализация формул.
 */
export function csvField(value: CsvValue): string {
  const raw = value === null || value === undefined ? '' : String(value);
  const safe = FORMULA_STARTERS.some((start) => raw.startsWith(start)) ? `'${raw}` : raw;
  if (!/[",\r\n]/.test(safe)) {
    return safe;
  }
  return `"${safe.replaceAll('"', '""')}"`;
}

/** Одна строка CSV без завершающего перевода. */
export function csvRow(values: readonly CsvValue[]): string {
  return values.map((value) => csvField(value)).join(',');
}

/**
 * Готовый документ CSV: BOM, строка заголовков, строки данных, завершающий CRLF.
 *
 * Завершающий перевод строки есть намеренно: без него часть инструментов теряет
 * последнюю строку файла.
 */
export function csvDocument(
  headers: readonly string[],
  rows: readonly (readonly CsvValue[])[],
): string {
  const lines = [csvRow(headers), ...rows.map((row) => csvRow(row))];
  return `${CSV_BOM}${lines.join(CSV_EOL)}${CSV_EOL}`;
}
