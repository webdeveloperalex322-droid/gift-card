/**
 * Завершение смоука на живой базе честным кодом выхода.
 *
 * Смоуки запускаются через `payload run`, а его bin после скрипта БЕЗУСЛОВНО
 * вызывает `process.exit(0)` (`payload/dist/bin/index.js`: `await
 * runBinScript(...)`, затем `payload.destroy()`, затем `process.exit(0)`).
 * Выставленный скриптом `process.exitCode` при этом затирается, и красный смоук
 * докладывал бы успех — то есть единственная проверка защит против живого ядра
 * считалась бы пройденной без доказательства. Поэтому код выхода выставляется не
 * полем, а немедленным `process.exit` — до возврата управления в bin.
 *
 * Перед выходом очередь stdout сливается принудительно: запись в конвейер (а на
 * Windows перехваченный вывод — всегда конвейер) асинхронна, и `process.exit` её
 * не дожидается. Без слива терялись бы именно итоговые строки — те, ради которых
 * смоук и печатает вывод.
 *
 * Возврата из функции не бывает: тип `Promise<never>` — часть контракта, чтобы
 * вызывающий код не дописывал за ней недостижимые ветки.
 */
export async function finishSmoke(failedCount: number): Promise<never> {
  await new Promise<void>((resolve) => {
    // Пустая запись встаёт в конец очереди stdout: колбэк вызывается, когда всё
    // напечатанное раньше уже ушло в поток.
    process.stdout.write('', () => {
      resolve();
    });
  });
  process.exit(failedCount > 0 ? 1 : 0);
}
