/**
 * Ограничение частоты запросов: чистое ядро (задача Э6-03, решение Ч-14).
 *
 * ЧТО ВЫБРАНО И ПОЧЕМУ ИМЕННО ЭТО. Ч-14 задаёт три числа: «60 запросов в минуту
 * на ключ, всплеск 120, скользящее окно 60 с». Формально им соответствуют два
 * разных механизма, и разница между ними видна не в норме, а на границе:
 *
 *   - **счётчик фиксированного окна** («не больше N за календарную минуту»)
 *     отвергается. У него всплеск не параметр, а неустранимый побочный эффект:
 *     клиент, сделавший 60 запросов в последнюю секунду окна и ещё 60 в первую
 *     секунду следующего, проходит 120 запросов за две секунды, и отличить это
 *     от «всплеска 120» нечем. То есть два числа Ч-14 перестают быть двумя
 *     разными настройками;
 *   - **токен-бакет** (выбран). Ёмкость — это всплеск (120), скорость
 *     пополнения — устойчивая частота (60 токенов за окно в 60 с, то есть один
 *     токен в секунду). Момента общего сброса у него нет вовсе: пополнение
 *     непрерывно, и «окно» здесь — период, за который выдаётся квота, а не
 *     отрезок календаря. Это и есть свойство «скользящее» из Ч-14, выраженное
 *     состоянием, а не хранением списка отметок времени.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни `Date.now()`, ни HTTP, ни Payload: время приходит
 * аргументом. Иначе утверждение «за минуту пополняется ровно 60» проверялось бы
 * ожиданием длиной в минуту — такой тест либо не пишут вовсе, либо он делает
 * `pnpm verify` неприемлемо долгим. Точка применения (обёртка над маршрутами
 * REST и GraphQL) и разбор окружения живут в `./api-rate-limit.ts`.
 *
 * РАСПРЕДЕЛЁННОГО СЧЁТА НЕТ СОЗНАТЕЛЬНО. Хранилище — в памяти процесса. При
 * нескольких экземплярах CMS каждый считает свою долю, то есть фактический
 * предел умножается на число экземпляров. Для этого проекта (одна CMS, один
 * сервисный аккаунт) это точность, которой достаточно; внешнее хранилище
 * счётчиков стоило бы дороже задачи, которую решает.
 */

/** Настройки бакета. Значения приходят из окружения (см. `./api-rate-limit.ts`). */
export interface TokenBucketSettings {
  /** Ёмкость бакета — всплеск. Ч-14: 120. */
  readonly capacity: number;
  /** Сколько токенов выдаётся за окно. Ч-14: 60. */
  readonly refillTokens: number;
  /** Длительность окна выдачи в миллисекундах. Ч-14: 60 000. */
  readonly refillWindowMs: number;
}

/**
 * Состояние одного бакета.
 *
 * `limited` хранится вместе с токенами, чтобы отличать НАЧАЛО эпизода отказов от
 * его продолжения. Нужно это ровно для журнала: писать строку на каждый
 * отклонённый запрос — значит превращать всплеск в 120 строк лога, то есть
 * усиливать ту самую нагрузку, от которой стоит ограничение.
 */
export interface BucketState {
  readonly limited: boolean;
  readonly tokens: number;
  readonly updatedAtMs: number;
}

/**
 * Решение по одному запросу.
 *
 * ОСТАТКА ТОКЕНОВ ЗДЕСЬ НЕТ, И ЭТО ВЫБОР. Поле `remaining` в интерфейсе было и
 * считалось, но ни один потребитель его не читал: наружу оно не уходило (Ч-14
 * требует `429` и `Retry-After`, заголовков семейства `X-RateLimit-*` — нет), а
 * отдавать его клиенту означало бы дописывать заголовок в ЧУЖОЙ ответ Payload на
 * каждом успешном запросе — новый публичный контракт ради значения, которого
 * никто не просил. Поле убрано: обещание интерфейса без потребителя однажды
 * прочитают как «остаток уже отдаётся клиенту», и проверять это будет нечем.
 * Если остаток понадобится (например, чтобы обёртка MCP сама держала темп) —
 * это отдельное решение с заголовком и тестом на него, а не поле, которое
 * «уже есть».
 */
export interface RateLimitDecision {
  readonly allowed: boolean;
  /** Первый отказ в эпизоде: только по нему пишется предупреждение в журнал. */
  readonly firstDenial: boolean;
  /** Целые секунды до следующего токена; 0, когда запрос разрешён. */
  readonly retryAfterSeconds: number;
}

/** Новый бакет всегда полный: неизвестный ключ не наказывается за незнание. */
export function fullBucket(settings: TokenBucketSettings, nowMs: number): BucketState {
  return { limited: false, tokens: settings.capacity, updatedAtMs: nowMs };
}

/**
 * Пополняет бакет за прошедшее время.
 *
 * Два ограничения, и оба обязательны:
 *
 *   1. **потолок в `capacity`.** Без него долгое молчание копило бы токены без
 *      предела, и первый же всплеск после паузы прошёл бы целиком — ограничение
 *      исчезало бы ровно для того, кто дольше всех ждал;
 *   2. **прошедшее время не бывает отрицательным.** Часы уходят назад (перевод
 *      времени, синхронизация NTP). Отрицательное приращение вычитало бы токены,
 *      а сохранённая отметка «из будущего» заморозила бы пополнение на всю
 *      длительность прыжка. Отметка всегда переставляется на текущий момент:
 *      цена прыжка назад — один непополненный шаг, а не блокировка ключа.
 */
export function refillBucket(
  state: BucketState,
  settings: TokenBucketSettings,
  nowMs: number,
): BucketState {
  const elapsedMs = Math.max(0, nowMs - state.updatedAtMs);
  const gained = (elapsedMs * settings.refillTokens) / settings.refillWindowMs;
  const tokens = Math.min(settings.capacity, state.tokens + gained);
  return { limited: state.limited, tokens, updatedAtMs: nowMs };
}

/** Полный бакет неотличим от отсутствующего — по этому признаку его и убирают. */
export function isFull(state: BucketState, settings: TokenBucketSettings): boolean {
  return state.tokens >= settings.capacity;
}

/**
 * Сколько целых секунд ждать до следующего токена.
 *
 * Округление ВВЕРХ и минимум в одну секунду. `Retry-After: 0` означает «повторяй
 * немедленно» — то есть предлагает клиенту ровно то поведение, из-за которого он
 * и получил отказ.
 */
function retryAfterSeconds(tokens: number, settings: TokenBucketSettings): number {
  const missing = Math.max(0, 1 - tokens);
  const waitMs = (missing * settings.refillWindowMs) / settings.refillTokens;
  return Math.max(1, Math.ceil(waitMs / 1000));
}

/**
 * Решение по одному запросу: пополнить, попробовать снять токен, вернуть новое
 * состояние. Функция ничего не хранит — состояние передаётся и возвращается.
 */
export function consumeToken(
  state: BucketState,
  settings: TokenBucketSettings,
  nowMs: number,
): { readonly decision: RateLimitDecision; readonly next: BucketState } {
  const refilled = refillBucket(state, settings, nowMs);

  if (refilled.tokens < 1) {
    return {
      decision: {
        allowed: false,
        firstDenial: !refilled.limited,
        retryAfterSeconds: retryAfterSeconds(refilled.tokens, settings),
      },
      next: { ...refilled, limited: true },
    };
  }

  const next: BucketState = { ...refilled, limited: false, tokens: refilled.tokens - 1 };
  return {
    decision: { allowed: true, firstDenial: false, retryAfterSeconds: 0 },
    next,
  };
}

