/**
 * Сколько бакетов просматривается за один запрос при уборке и вытеснении.
 *
 * Константа, а не параметр: это компромисс между качеством выбора жертвы и
 * стоимостью запроса, а не решение о поведении системы. Просмотр идёт от самых
 * давних записей (порядок обхода `Map` — порядок вставки, а каждое обращение
 * переставляет запись в конец), поэтому выборка почти всегда состоит из бакетов,
 * успевших пополниться.
 */
const SCAN_LIMIT = 8;

export interface RateLimitStore {
  /** Решение по ключу. Ключ — отпечаток, не сам API-ключ (см. `./api-rate-limit.ts`). */
  readonly consume: (key: string, nowMs: number) => RateLimitDecision;
  /** Сколько бакетов сейчас в памяти. Существует для теста об ограниченности. */
  readonly size: () => number;
}

/**
 * Хранилище с ОГРАНИЧЕННЫМ размером.
 *
 * Зачем ограничение. Бакет заводится по отпечатку ПРЕДЪЯВЛЕННОГО ключа, не
 * дожидаясь ответа базы «такой ключ есть» (см. `./api-rate-limit.ts`: иначе
 * перебор ключей ходил бы в базу свободно, и ограничение защищало бы всё, кроме
 * самого дорогого). Значит, поток случайных ключей заводит по бакету на каждый —
 * то есть неограниченная карта стала бы ровно тем каналом отказа, который
 * ограничение и закрывает.
 *
 * Две дисциплины освобождения, и они разные:
 *
 *   1. **уборка полных.** Полный бакет неотличим от отсутствующего: удалить его
 *      — не потеря, а освобождение памяти без последствий;
 *   2. **вытеснение при переполнении.** Когда убирать нечего, удаляется САМЫЙ
 *      ПОЛНЫЙ бакет из просмотренной выборки, а не самый давний. Это
 *      принципиально: вытеснение бакета выдаёт его владельцу новую полную
 *      ёмкость, поэтому выбирать надо того, кому и так почти всё пополнилось.
 *      При дисциплине «самый давний» нарушитель, чей бакет пуст, вытеснялся бы
 *      потоком посторонних ключей — и снимал бы с себя ограничение ровно тем
 *      способом, от которого оно поставлено.
 */
export function createRateLimitStore(args: {
  /** Предел числа бакетов в памяти. */
  readonly maxKeys: number;
  readonly settings: TokenBucketSettings;
}): RateLimitStore {
  const { maxKeys, settings } = args;
  const buckets = new Map<string, BucketState>();

  /**
   * Убирает полные бакеты из головы карты и возвращает ключ кандидата на
   * вытеснение — самого полного среди просмотренных.
   *
   * Удаление во время обхода `Map` безопасно: итератор его учитывает.
   */
  const sweep = (nowMs: number): string | null => {
    let victimKey: string | null = null;
    let victimTokens = -1;
    let scanned = 0;

    for (const [key, state] of buckets) {
      if (scanned >= SCAN_LIMIT) {
        break;
      }
      scanned += 1;
      const refilled = refillBucket(state, settings, nowMs);
      if (isFull(refilled, settings)) {
        buckets.delete(key);
        continue;
      }
      if (refilled.tokens > victimTokens) {
        victimTokens = refilled.tokens;
        victimKey = key;
      }
    }

    return victimKey;
  };

  return {
    consume: (key, nowMs) => {
      const victim = sweep(nowMs);
      const stored = buckets.get(key);

      if (stored === undefined && buckets.size >= maxKeys && victim !== null) {
        buckets.delete(victim);
      }

      const { decision, next } = consumeToken(stored ?? fullBucket(settings, nowMs), settings, nowMs);

      // delete + set переставляет запись в конец: порядок обхода `Map` — порядок
      // вставки, и без перестановки «голова карты» перестала бы означать «давно
      // не трогали».
      buckets.delete(key);
      buckets.set(key, next);

      return decision;
    },
    size: () => buckets.size,
  };
}
