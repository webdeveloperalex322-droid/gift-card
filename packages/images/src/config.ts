/**
 * Параметры пайплайна изображений.
 *
 * Все решения человека по этим числам закрыты 2026-08-21 (`docs/etap-0-resheniya.md`,
 * `docs/otkrytye-voprosy.md`), поэтому здесь различаются два вида значений — и
 * различие принципиально:
 *
 *   - **утверждённая норма, из окружения НЕ читается**: набор ширин
 *     {@link IMAGE_WIDTHS} (Ч-09) и минимальная ширина исходника
 *     {@link MIN_SOURCE_IMAGE_WIDTH} (Ч-09 и блок 5 п. 2). Переменной окружения
 *     для набора ширин нет НАМЕРЕННО: набор объявлен окончательным, а
 *     переопределяемый набор нечем удержать — запрет «добавление запрещено»
 *     проверялся бы только словами в комментарии.
 *   - **настраиваемое значение с утверждённым дефолтом**: порог pHash
 *     `PHASH_DISTANCE_THRESHOLD` (Ч-08 → 14) и качество кодирования
 *     `IMAGE_ENCODE_QUALITY` (Ч-29 → avif 50 / webp 80 / jpeg 82). Оба
 *     пересматриваются после замеров на реальных открытках и на эталонной
 *     выборке (Ч-06), поэтому меняются настройкой, а не правкой кода. Мусорное
 *     значение в обоих случаях — ошибка, а не молчаливый возврат к дефолту:
 *     опечатка не должна тихо менять ни вердикт «дубль», ни вес производных.
 *
 * Настраиваемые числа есть и вне этого файла: `DEFAULT_IMAGE_NAME_MAX_LENGTH` в
 * `naming.ts` — параметр вызова, а не переменная окружения (Ч-26), потому что
 * влияет на постоянный URL файла.
 */

import { assertOutputFormat, OUTPUT_FORMATS, type OutputFormat } from './formats.js';

/** Срез окружения: то, что нужно пайплайну, без завязки на `process.env`. */
export type ImagesEnv = Readonly<Record<string, string | undefined>>;

export const PHASH_DISTANCE_THRESHOLD_ENV_KEY = 'PHASH_DISTANCE_THRESHOLD';
export const IMAGE_ENCODE_QUALITY_ENV_KEY = 'IMAGE_ENCODE_QUALITY';

/**
 * Набор ширин производных — **окончательный** (решение Ч-09, 2026-08-21).
 *
 * Добавление ширины запрещено, и запрет не стилистический: новая ширина ниже
 * уже опубликованных отменяет fallback в натуральную ширину и делает уже
 * выданный ключ производной невоспроизводимым (это было условие C7 плана).
 * Убрать ширину после публикации тоже нельзя — исчезают URL производных
 * (ТЗ §6.3).
 *
 * Поэтому набор живёт в коде и НЕ читается из окружения: переменная
 * `IMAGE_WIDTHS` снята вместе с закрытием Ч-09. Единственная форма изменения —
 * правка этой константы вместе с решением человека и планом миграции URL.
 */
export const IMAGE_WIDTHS: readonly number[] = Object.freeze([320, 640, 960, 1280, 1920]);

/**
 * Минимальная ширина исходного изображения при загрузке — 640 px (решение Ч-09
 * и блока 5 п. 2, 2026-08-21).
 *
 * Изображение уже отклоняется и в пайплайн не идёт. Следствие, на котором стоит
 * условие C8: минимальная ширина любого допустимого набора не превышает этого
 * порога (см. {@link resolveDerivativeWidths}), поэтому хотя бы одна ширина
 * всегда подходит и `nativeWidthFallback` недостижим.
 */
export const MIN_SOURCE_IMAGE_WIDTH = 640;

/** Длина pHash в битах: задаёт диапазон допустимых значений порога. */
export const PHASH_BITS = 64;

/**
 * Порог расстояния Хэмминга, при котором изображения считаются похожими —
 * **14** (решение Ч-08, 2026-08-21; делегировано агенту и принято человеком).
 *
 * Почему 14, а не «поменьше для надёжности»: порог — подсказка редактору, а не
 * автоблокировка (дедупликация предупреждает человека и ничего не удаляет),
 * поэтому ложное срабатывание дешевле пропущенного дубля. Замеры этапа 2 дают
 * вилку `12 ≤ порог < 24`: на композиции «кольца» обычное перекодирование в
 * JPEG q80 даёт уже 12, а другая композиция — 24. 14 лежит выше «легитимных» 12
 * и ниже 24.
 *
 * Пересматривается после прогона на эталонной выборке (Ч-06) — настройкой
 * `PHASH_DISTANCE_THRESHOLD`, без правки кода.
 *
 * Ограничение алгоритма, которое порогом не лечится: DCT-pHash не инвариантен к
 * повороту (180° — 28, 90° — 36), поэтому повёрнутый дубль редактору не покажут
 * ни при каком значении.
 */
export const DEFAULT_PHASH_DISTANCE_THRESHOLD = 14;

/**
 * Качество кодирования по формату — avif 50 / webp 80 / jpeg 82 (решение Ч-29,
 * 2026-08-21).
 *
 * Значения утверждены как настраиваемые: они пересматриваются после замера веса
 * страницы и артефактов на реальных открытках (ТЗ §10), поэтому
 * переопределяются через `IMAGE_ENCODE_QUALITY` и опцию `quality`, а не правкой
 * кода.
 */
export const DEFAULT_ENCODE_QUALITY: Readonly<Record<OutputFormat, number>> = Object.freeze({
  avif: 50,
  webp: 80,
  jpeg: 82,
});

function currentEnv(): ImagesEnv {
  return process.env;
}

/**
 * Ширины производных: весь окончательный набор либо его подмножество.
 *
 * Что здесь разрешено и почему именно так:
 *   - **расширение запрещено** — ширины вне {@link IMAGE_WIDTHS} отклоняются.
 *     Это и есть машинная форма решения Ч-09: добавленная ширина ломает
 *     воспроизводимость уже выданных ключей (условие C7);
 *   - **сужение разрешено** — оно нужно тестам и разовым прогонам и ключей не
 *     ломает: любой ключ, полученный на подмножестве, получается и на полном
 *     наборе (ширина в имени берётся из фактической ширины файла, а не из
 *     состава набора). Продуктовый путь (Э2-04/Э2-05) параметр не передаёт и
 *     работает на полном наборе;
 *   - **но сужение не поднимает минимум выше {@link MIN_SOURCE_IMAGE_WIDTH}** —
 *     иначе допустимый по порогу исходник 640 px снова не попадал бы ни в одну
 *     ширину, включался бы `nativeWidthFallback`, и ключ снова зависел бы от
 *     состава настроек. Именно этим сужение остаётся безопасным.
 */
export function resolveDerivativeWidths(widths?: readonly number[]): readonly number[] {
  if (widths === undefined) {
    return [...IMAGE_WIDTHS];
  }

  const normalized = [...new Set(widths)].sort((left, right) => left - right);

  if (normalized.length === 0) {
    throw new Error(
      'Набор ширин производных пуст. Допустимо либо не передавать набор совсем (тогда ' +
        `берётся окончательный ${IMAGE_WIDTHS.join(', ')}), либо передать его подмножество.`,
    );
  }

  const extra = normalized.filter((width) => !IMAGE_WIDTHS.includes(width));
  if (extra.length > 0) {
    throw new Error(
      `Ширины ${extra.join(', ')} не входят в окончательный набор ` +
        `${IMAGE_WIDTHS.join(', ')}: добавление ширин запрещено решением Ч-09. Новая ширина ` +
        'отменяет fallback в натуральную ширину и делает уже выданный ключ производной ' +
        'невоспроизводимым (ТЗ §6.3). Допустимо только сужение до подмножества.',
    );
  }

  const smallest = normalized[0] ?? 0;
  if (smallest > MIN_SOURCE_IMAGE_WIDTH) {
    throw new Error(
      `Минимальная ширина набора ${String(smallest)} превышает порог исходника ` +
        `${String(MIN_SOURCE_IMAGE_WIDTH)} px: при таком сужении исходник у порога не попал бы ` +
        'ни в одну ширину, включился бы nativeWidthFallback и ключ производной снова зависел бы ' +
        'от настроек. Оставьте в наборе ширину не больше порога.',
    );
  }

  return normalized;
}

/**
 * Порог расстояния pHash: из окружения, иначе — утверждённое значение
 * {@link DEFAULT_PHASH_DISTANCE_THRESHOLD}.
 *
 * Пустое значение переменной означает «не сконфигурировано» (соглашение
 * `.env.example`) и даёт дефолт. Непустое, но некорректное — ошибка: опечатка в
 * пороге не должна тихо вернуться к дефолту, потому что тогда редактор считает,
 * что настроил одно, а дубли ищутся по другому.
 */
export function resolvePhashDistanceThreshold(env: ImagesEnv = currentEnv()): number {
  const raw = env[PHASH_DISTANCE_THRESHOLD_ENV_KEY]?.trim() ?? '';
  if (raw === '') {
    return DEFAULT_PHASH_DISTANCE_THRESHOLD;
  }

  const parsed = Number(raw);
  if (!Number.isInteger(parsed) || parsed < 0 || parsed > PHASH_BITS) {
    throw new Error(
      `${PHASH_DISTANCE_THRESHOLD_ENV_KEY} должен быть целым числом от 0 до ${String(PHASH_BITS)} ` +
        `(расстояние Хэмминга по ${String(PHASH_BITS)} битам), получено: «${raw}». ` +
        `Утверждённое значение — ${String(DEFAULT_PHASH_DISTANCE_THRESHOLD)} (Ч-08); ` +
        'некорректная настройка не подменяется им молча.',
    );
  }

  return parsed;
}

/**
 * Качество кодирования: утверждённые значения (Ч-29), поверх которых
 * накладывается `IMAGE_ENCODE_QUALITY` в форме `avif=45,webp=78,jpeg=80`.
 *
 * Указывать можно любое подмножество форматов — остальные остаются на дефолте.
 * Непустое, но некорректное значение — ошибка: опечатка не должна тихо вернуть
 * вес производных к другому компромиссу.
 */
export function resolveEncodeQuality(
  env: ImagesEnv = currentEnv(),
): Readonly<Record<OutputFormat, number>> {
  const quality: Record<OutputFormat, number> = { ...DEFAULT_ENCODE_QUALITY };
  const raw = env[IMAGE_ENCODE_QUALITY_ENV_KEY]?.trim() ?? '';
  if (raw === '') {
    return quality;
  }

  for (const pair of raw.split(',')) {
    const trimmed = pair.trim();
    if (trimmed === '') {
      continue;
    }
    const [rawFormat = '', rawValue = '', ...rest] = trimmed.split('=');
    const value = Number(rawValue.trim());
    if (
      rest.length > 0 ||
      rawValue.trim() === '' ||
      !Number.isInteger(value) ||
      value < 1 ||
      value > 100
    ) {
      throw new Error(
        `${IMAGE_ENCODE_QUALITY_ENV_KEY} должен быть списком «формат=качество» через запятую ` +
          `(форматы: ${OUTPUT_FORMATS.join(', ')}; качество — целое 1..100), ` +
          `получено: «${raw}».`,
      );
    }
    try {
      quality[assertOutputFormat(rawFormat.trim())] = value;
    } catch (cause) {
      throw new Error(
        `${IMAGE_ENCODE_QUALITY_ENV_KEY}: неизвестный формат в «${trimmed}». ` +
          `Допустимы только ${OUTPUT_FORMATS.join(', ')}.`,
        { cause },
      );
    }
  }

  return quality;
}
