/**
 * Имена файлов и раскладка объектов в хранилище — ТЗ §6.1, §6.3, §6.7, §11.
 *
 * Три правила, которые здесь закодированы, и цена их нарушения:
 *
 *   1. Имя строится ТОЛЬКО через `slugify` из `@otkritka/shared`. Своей
 *      таблицы транслитерации в этом пакете нет и быть не должно: второе
 *      правило означало бы два разных имени для одного заголовка, а имя файла —
 *      это URL, который после публикации не меняется.
 *   2. Функции возвращают ТОЛЬКО относительный ключ объекта — без схемы, без
 *      хоста, без ведущего слеша. Абсолютный URL собирается вне пакета:
 *      `CLAUDE.md` требует единственного хелпера над `SITE_URL`, а решение Ч-03
 *      вводит отдельный `IMAGES_CDN_ORIGIN` для домена изображений, и совпадают
 *      ли эти домены — открытый вопрос человеку. Поэтому хост здесь не
 *      появляется даже как параметр с дефолтом.
 *   3. Пространства оригиналов и производных разделены, и путь оригинала НЕ
 *      выводится из публичного пути производной. Оригинал лежит под
 *      непредсказуемым идентификатором, описательного имени в его пути нет.
 *      Обратной функции («по публичному пути получить оригинал») в API нет
 *      намеренно: она и была бы той самой дырой, которую запрещает ТЗ §6.1.
 *
 * Значения префиксов, бакетов и CDN — решение Ч-03, человеком не принятое.
 * Пакет их не знает: префиксы приходят параметрами, дефолтов у них нет.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: разведения коллизий. Два изображения с одинаковым
 * описательным именем И одинаковой ревизией дадут один ключ — это прямое
 * следствие контракта постоянства (§6.3): тот же вход обязан давать тот же
 * путь, а счётчик или суффикс «-2» сделали бы путь зависимым от состояния
 * хранилища. Уникальность обеспечивает вызывающий код (Э2-05), выдавая
 * уникальную ревизию либо требуя у редактора другое имя.
 */
import { isValidSlug, slugify } from '@otkritka/shared';
import { randomBytes } from 'node:crypto';
import { assertOutputFormat, type OutputFormat } from './formats.js';

/**
 * Максимальная длина описательного имени файла. Вопрос реестра **Ч-26**.
 *
 * ВНИМАНИЕ: это **не решение человека**. Ни ТЗ, ни SEO ТЗ длину имени файла не
 * нормируют. Значение выбрано так, чтобы вместе с суффиксом `-1920.webp`
 * итоговый сегмент оставался в пределах нормы slug из `packages/shared`
 * (`DEFAULT_SLUG_MAX_LENGTH`), и вынесено в параметр именно потому, что
 * подлежит замене без правки логики. Норму задаёт человек.
 *
 * Из окружения НЕ читается: это параметр вызова, а не переменная окружения, —
 * длина влияет на постоянный URL файла, и менять её задним числом равносильно
 * смене URL (ТЗ §6.3).
 */
export const DEFAULT_IMAGE_NAME_MAX_LENGTH = 68;

/**
 * Расширение файла по формату вывода.
 *
 * Норма проекта: JPEG — **только `.jpg`**, написание `.jpeg` не используется
 * нигде. Причина не стилистическая: URL файла постоянный, а два написания для
 * одного содержимого — это два URL одной картинки, то есть ровно та
 * неоднозначность, которую запрещает правило «один материал — один путь».
 */
export const FILE_EXTENSION_BY_FORMAT: Readonly<Record<OutputFormat, string>> = Object.freeze({
  avif: 'avif',
  webp: 'webp',
  jpeg: 'jpg',
});

/**
 * Длина непредсказуемого идентификатора оригинала в байтах.
 *
 * КОНТРАКТ (а не параметр): идентификатор оригинала выдаёт только
 * {@link createOpaqueImageStorageId} этого пакета, и проверка формы —
 * следствие того же числа, а не второе независимое правило.
 *
 * Почему не «любой внешний идентификатор»: чужие идентификаторы записей
 * предсказуемы — последовательный int в Postgres перечисляется подряд, ObjectId
 * упорядочен по времени. По такому пути оригиналы обходятся перебором, а ТЗ
 * §6.1 и §11 требуют обратного. Проверить «непредсказуемость» строки
 * программно нельзя, поэтому проверяется происхождение через форму. Если Ч-03
 * потребует другую схему ключей — это правка контракта с решением человека, а
 * не расширение регулярного выражения.
 */
const STORAGE_ID_BYTES = 16;
const STORAGE_ID_PATTERN = new RegExp(`^[0-9a-f]{${String(STORAGE_ID_BYTES * 2)}}$`);

/** Форма расширения файла оригинала: короткая последовательность из букв и цифр. */
const EXTENSION_PATTERN = /^[a-z0-9]{2,5}$/;

export interface ImageNameOptions {
  /** Максимальная длина имени. По умолчанию {@link DEFAULT_IMAGE_NAME_MAX_LENGTH}. */
  readonly maxLength?: number;
}

/**
 * Короткое описательное имя файла на транслите — без расширения и без пути.
 *
 * Чистая функция: результат зависит только от заголовка и лимита длины. Ни ID,
 * ни даты, ни счётчика на входе нет — имя файла не должно от них зависеть, как
 * и slug страницы.
 *
 * Бросает исключение, если после транслитерации не осталось ни одного символа:
 * путь с пустым сегментом (`.../-640.webp`) хуже явной ошибки, а решение
 * «попросить у редактора латинское имя» принимает вызывающий код.
 */
export function buildImageFileStem(description: string, options?: ImageNameOptions): string {
  const maxLength = options?.maxLength ?? DEFAULT_IMAGE_NAME_MAX_LENGTH;
  const stem = slugify(description, { maxLength });

  if (stem === '' || !isValidSlug(stem, { maxLength })) {
    throw new Error(
      `Не удалось построить имя файла из «${description}»: ${explainEmptyStem(description)} ` +
        'Пустой сегмент в пути недопустим — имя должен задать редактор.',
    );
  }

  return stem;
}

/**
 * Почему `slugify` не дал имени. Причины две, и подсказка редактору у них
 * разная, поэтому они разведены:
 *
 *   - во входе вообще нет букв и цифр (пусто, пунктуация, эмодзи) — нужно
 *     осмысленное название;
 *   - буквы и цифры есть, но правила транслитерации в `packages/shared` их не
 *     поддерживают (нерусская кириллица, армянский, грузинский, CJK и прочее).
 *     Тогда дело не в «нет символов», а в конкретных литерах: они либо
 *     выброшены, либо дали пустую строку. Формулировка верна и после
 *     расширения отказа на стороне shared — она не утверждает, что вход был
 *     пуст, а указывает на неподдерживаемые литеры.
 */
function explainEmptyStem(description: string): string {
  const hasLetterOrDigit = /[\p{L}\p{N}]/u.test(description);
  if (!hasLetterOrDigit) {
    return 'во входе нет ни букв, ни цифр — транслитерировать нечего.';
  }
  return (
    'буквы или цифры во входе есть, но правила транслитерации из packages/shared ' +
    'их не поддерживают (например нерусская кириллица или другая письменность) — ' +
    'допустимого имени из них не получается.'
  );
}

/**
 * Префикс пространства в хранилище: относительный, из валидных сегментов.
 * Обрамляющие слеши нормализуются, состав не меняется.
 */
function normalizePrefix(prefix: string): string {
  const trimmed = prefix.trim().replace(/^\/+|\/+$/g, '');
  const segments = trimmed === '' ? [] : trimmed.split('/');

  if (segments.length === 0 || !segments.every((segment) => isValidSlug(segment))) {
    throw new Error(
      `Префикс пространства «${prefix}» недопустим: ожидаются сегменты пути из [a-z0-9-] ` +
        'без схемы, хоста и пустых сегментов. Значение приходит из конфигурации (Ч-03), ' +
        'дефолта у него нет.',
    );
  }

  return segments.join('/');
}

function assertRevision(revision: string): string {
  if (!isValidSlug(revision)) {
    throw new Error(
      `Ревизия изображения «${revision}» недопустима: ожидается один сегмент из [a-z0-9-]. ` +
        'Ревизия меняется только при замене изображения (ТЗ §6.7) — при неизменном ' +
        'изображении путь производной постоянен.',
    );
  }
  return revision;
}

function assertWidth(width: number): number {
  if (!Number.isInteger(width) || width <= 0) {
    throw new Error(
      `Ширина производной должна быть целым положительным числом, получено: ${String(width)}.`,
    );
  }
  return width;
}



export interface DerivativeObjectKeyInput {
  /** Префикс ПУБЛИЧНОГО пространства производных. Приходит из конфигурации (Ч-03). */
  readonly prefix: string;
  /**
   * Ревизия изображения: один валидный сегмент. Меняется только при замене
   * изображения — тогда меняются и URL производных при неизменном URL карточки
   * (ТЗ §6.7). Значение выдаёт вызывающий код, а не этот пакет: иначе путь
   * перестал бы быть постоянным для того же входа.
   *
   * Сам механизм версионирования ТЗ дословно не задаёт — вопрос реестра
   * **Ч-28**. Пока он открыт, ревизия обязательна: без неё immutable-кеш после
   * замены изображения отдавал бы старый файл по тому же URL.
   */
  readonly revision: string;
  /** Описательный заголовок изображения: прогоняется через `slugify` из shared. */
  readonly description: string;
  /**
   * Формат производной. Тип — `string`: границу пакета зовут из Payload и через
   * внешний API, где типы не проверяются, поэтому сужение делается в рантайме.
   */
  readonly format: string;
  /**
   * Ширина производной. Берётся ТОЛЬКО из `ImageDerivative.width` — фактической
   * ширины готового файла (условие C8), и из того же поля обязан собираться
   * дескриптор `w` в `srcset`. Диагностическое `targetWidth` сюда передавать
   * нельзя: в режиме `nativeWidthFallback` оно совпадает, а в остальных
   * случаях может обещать в URL ширину, которой в файле нет.
   *
   * Тестом это НЕ закреплено и внутри пакета закреплено быть не может: сюда
   * приходит просто число, и чьё оно — не видно. Проверяется на Э2-05/Э3-04,
   * где ключ и разметка собираются из записи.
   */
  readonly width: number;
  readonly maxLength?: number;
}

/**
 * Относительный ключ объекта производной:
 * `<prefix>/<revision>/<имя>-<ширина>.<расширение>`.
 *
 * Формат и ширина закодированы в имени однозначно, расширение соответствует
 * формату. Ни хоста, ни схемы, ни ведущего слеша в результате нет.
 */
export function buildDerivativeObjectKey(input: DerivativeObjectKeyInput): string {
  const prefix = normalizePrefix(input.prefix);
  const revision = assertRevision(input.revision);
  const format = assertOutputFormat(input.format);
  const width = assertWidth(input.width);
  const stem = buildImageFileStem(
    input.description,
    input.maxLength === undefined ? undefined : { maxLength: input.maxLength },
  );

  return `${prefix}/${revision}/${stem}-${String(width)}.${FILE_EXTENSION_BY_FORMAT[format]}`;
}

export interface OriginalObjectKeyInput {
  /**
   * Префикс НЕПУБЛИЧНОГО пространства оригиналов. Отдельный параметр — чтобы
   * оригиналы физически лежали не там, где производные (ТЗ §6.1, §11).
   */
  readonly prefix: string;
  /** Непредсказуемый идентификатор: {@link createOpaqueImageStorageId}. */
  readonly storageId: string;
  /** Расширение исходного файла без точки; регистр приводится к нижнему. */
  readonly extension: string;
}

/**
 * Относительный ключ объекта оригинала: `<prefix>/<storageId>.<расширение>`.
 *
 * Описательного имени в пути НЕТ намеренно: по опубликованному имени файла
 * оригинал не должен угадываться. Связь «карточка → оригинал» хранится в
 * записи CMS, а не в структуре пути, и обратной функции для неё здесь нет.
 */
export function buildOriginalObjectKey(input: OriginalObjectKeyInput): string {
  const prefix = normalizePrefix(input.prefix);

  if (!isOpaqueImageStorageId(input.storageId)) {
    throw new Error(
      `Идентификатор оригинала «${input.storageId}» недопустим: ожидаются ` +
        `${String(STORAGE_ID_BYTES * 2)} шестнадцатеричных символов в нижнем регистре, ` +
        'выданных createOpaqueImageStorageId. Идентификаторы записей (int, ObjectId, UUID) ' +
        'не принимаются: они предсказуемы, а путь оригинала не должен угадываться ' +
        '(ТЗ §6.1, §11).',
    );
  }

  const extension = input.extension.trim().toLowerCase().replace(/^\.+/, '');
  if (!EXTENSION_PATTERN.test(extension)) {
    throw new Error(
      `Расширение оригинала «${input.extension}» недопустимо: ожидаются 2–5 символов [a-z0-9].`,
    );
  }

  return `${prefix}/${input.storageId}.${extension}`;
}

/**
 * Новый непредсказуемый идентификатор оригинала: 128 бит из криптографического
 * источника.
 *
 * Единственная функция пакета, которая НЕ детерминирована, и это её смысл:
 * идентификатор не выводится ни из имени файла, ни из заголовка, ни из ID
 * записи. Вызывается один раз при загрузке; значение сохраняется в записи CMS,
 * потому что восстановить его вычислением нельзя.
 */
export function createOpaqueImageStorageId(): string {
  return randomBytes(STORAGE_ID_BYTES).toString('hex');
}

/**
 * Проверка происхождения идентификатора оригинала: выдан ли он
 * {@link createOpaqueImageStorageId}. Нужна Э2-05, чтобы отклонить попытку
 * положить оригинал под предсказуемым ключом до обращения к хранилищу.
 */
export function isOpaqueImageStorageId(value: string): boolean {
  return STORAGE_ID_PATTERN.test(value);
}
