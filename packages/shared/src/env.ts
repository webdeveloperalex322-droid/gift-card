/**
 * Срез окружения для утилит пакета.
 *
 * Зачем тип, а если бы функции читали `process.env` напрямую: параметры,
 * из которых собираются внешние URL, обязаны проверяться тестом на нескольких
 * значениях (задано / пусто / мусор), а мутация глобального `process.env` в
 * тестах — источник взаимного влияния тестов. Поэтому окружение всегда
 * аргумент с дефолтом, ровно как в `packages/images`.
 */
export type SharedEnv = Readonly<Record<string, string | undefined>>;

/** Реальное окружение процесса. Единственное место, где пакет его читает. */
export function currentEnv(): SharedEnv {
  return process.env;
}
