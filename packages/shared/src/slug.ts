/**
 * Транслитерация заголовка в slug и валидатор slug.
 *
 * Задача Э1-01a (узкий слайс Э1-01). Единственный источник правил slug на весь
 * монорепозиторий: `apps/cms` (хуки Payload), `apps/web` (маршруты) и
 * `packages/images` (имена файлов производных, задача Э2-02) обязаны звать
 * `slugify`/`isValidSlug` отсюда и НЕ заводить вторую таблицу транслитерации.
 *
 * Правила взяты из `CLAUDE.md`, раздел «Правила URL — нарушать запрещено»:
 * нижний регистр, транслитерация, дефисы между словами; без кириллицы,
 * пробелов, подчёркиваний, параметров; slug не зависит от ID, даты публикации и
 * позиции в меню; смена заголовка URL не меняет (это обеспечивает не эта
 * функция, а хук неизменяемости slug — задача Э1-09).
 *
 * ЧТО СЮДА НЕ ВХОДИТ (граница контракта, зафиксирована намеренно):
 *   - реестр зарезервированных маршрутов и запрет сегмента `page` — остаток
 *     задачи Э1-01, этап 1. `isValidSlug('page')` возвращает `true`: форма
 *     сегмента корректна, а занятость пути проверяет реестр;
 *   - сборка абсолютного canonical из `SITE_URL` — там же;
 *   - предикат `isPageRoute()` — там же;
 *   - склейка иерархического пути подборки из цепочки родителей (Э1-05).
 *     Валидируется каждый сегмент по отдельности: `isValidSlug` отклоняет `/`.
 *
 * ПУБЛИЧНЫЙ КОНТРАКТ (окончательный; расширяется только по согласованию, потому
 * что от него зависят и web, и cms):
 *   - `slugify(source, options?) => string` — чистая, детерминированная,
 *     идемпотентная функция. Никогда не бросает исключение на входной строке
 *     (бросает только на некорректной `maxLength`). На вход не принимает и
 *     физически не может принять ID, дату или позицию: аргумент один — строка,
 *     а в опциях есть единственное поле `maxLength`.
 *     Отказ выражается пустой строкой: она не проходит `isValidSlug`, и
 *     вызывающий код (хук Payload, имя файла в `packages/images`) обязан на неё
 *     ответить внятной ошибкой. Пустую строку возвращает и вход, из которого
 *     нечего транслитерировать, и вход, где есть литера любой письменности, не
 *     давшая ни одного допустимого символа (см. ниже про Ч-25) — во втором
 *     случае это осознанный отказ, а не потеря буквы.
 *   - `isValidSlug(value, options?) => boolean` — проверка формы ОДНОГО
 *     сегмента пути.
 *   - `SLUG_PATTERN`, `DEFAULT_SLUG_MAX_LENGTH` — данные того же контракта.
 *   - `SlugOptions` — тип опций.
 * Таблица транслитерации сознательно НЕ экспортируется: единственный способ её
 * применить — `slugify`, иначе появится второе расходящееся правило.
 *
 * Открытые вопросы, на которые опирается этот модуль: Ч-24 (образец имени файла
 * в `CLAUDE.md` — `...-s-tulpanami.webp` — расходится с таблицей: `ю` → `yu`
 * даёт `...-s-tyulpanami`; спецправила под образец здесь НЕТ), Ч-25 (алфавиты
 * СНГ), Ч-26 (максимальная длина slug и имени файла), Ч-27 (числовой slug).
 */

/**
 * Таблица транслитерации кириллицы. Норма проекта — практика BGN/PCGN
 * («яндексовское» написание русских slug), с явно принятыми решениями:
 *
 * | Буква | Передача | Почему так, а не иначе |
 * |---|---|---|
 * | `ё`  | `e`      | Заголовок «Ёлка» и «Елка» обязаны давать один slug: редакторы пишут `ё` через `е` непредсказуемо, а расхождение здесь = два URL и лишний 301 |
 * | `й`  | `y`      | Отсюда «ый» → `yy` (`novyy-god`) — сумма `ы`+`й`, без спецправила на окончание: спецправило нарушило бы посимвольный детерминизм |
 * | `ы`  | `y`      | Совпадает с `й`; неоднозначность обратного разбора для URL безвредна |
 * | `х`  | `kh`     | Вариант `h` склеивает «сх» с «ш»: «Пасха» и «Паша» дали бы один slug `pasha` — коллизия URL двух разных материалов |
 * | `ц`  | `ts`     | Вариант `c` неотличим от `к` в латинице; `ts` даёт `maslenitsa`, `ofitsialnye`, `s-tsvetami` |
 * | `щ`  | `shch`   | Общепринятое; подтверждено черновиком (`godovshchina-svadby`, `zhenshchine`) |
 * | `я`  | `ya`     | Подтверждено черновиком (`23-fevralya`, `den-rozhdeniya`) |
 * | `ю`  | `yu`     | Там же (`uchitelyu`) |
 * | `ь`  | (пусто)  | «Свадьба» → `svadba`, «День» → `den`; подтверждено черновиком |
 * | `ъ`  | (пусто)  | Симметрично `ь`: «Подъезд» → `podezd`. Вариант `ie`/`y` даёт нечитаемые slug |
 * | `э`  | `e`      | Совпадает с `е`; отдельного написания правила не требуют |
 *
 * Таблица покрывает русский алфавит и только его. Правил для остальных
 * письменностей нет ни в `CLAUDE.md`, ни в SEO ТЗ, а догадка здесь необратима
 * после первой публикации (открытый вопрос Ч-25).
 *
 * ПРАВИЛО ОТКАЗА (критерий — не письменность, а результат): литера, которая
 * после таблицы и снятия диакритики не дала НИ ОДНОГО допустимого символа,
 * обрывает `slugify` — возвращается пустая строка, которую `isValidSlug`
 * отклоняет. Отказывает вся строка, а не одна литера.
 *
 * Почему не разделитель и не пропуск буквы: такой slug выходит правдоподобным и
 * потому не будет замечен. Реальные примеры из географии проекта (ТЗ §16,
 * «Россия и СНГ») — все они проходили проверку формы, пока критерий был привязан
 * к письменности: `Київ` → `ki-v`, `Гүлдер` → `g-lder`, «Открытка ў садзе» →
 * `otkrytka-sadze`, `Bakı` → `bak`, «Ənvər açıq» → `nv-r-ac-q`,
 * «открытки Ənvər» → `otkrytki-nv-r`, «Բարև открытки» → `otkrytki`,
 * «გილოცავ открытки» → `otkrytki`, «Καλά открытки» → `otkrytki`. Slug заполняет
 * сервисный аккаунт `ai-editor`, поэтому правдоподобно-неверный slug опаснее
 * явного отказа.
 *
 * Что отказом НЕ задевается: `ь`/`ъ` (пустая передача задана таблицей намеренно),
 * латиница с диакритикой (`Café` → `cafe` — литера дала символ), одиночные
 * комбинирующие метки (`İstanbul` → `istanbul`: метка отброшена, слово цело),
 * апострофы и кавычки (`oʼbrien` → `obrien`), цифры, дефисы, пробелы, прочая
 * пунктуация и эмодзи (не литеры — работают как разделитель).
 */
const CYRILLIC_TO_LATIN = new Map<string, string>([
  ['а', 'a'],
  ['б', 'b'],
  ['в', 'v'],
  ['г', 'g'],
  ['д', 'd'],
  ['е', 'e'],
  ['ё', 'e'],
  ['ж', 'zh'],
  ['з', 'z'],
  ['и', 'i'],
  ['й', 'y'],
  ['к', 'k'],
  ['л', 'l'],
  ['м', 'm'],
  ['н', 'n'],
  ['о', 'o'],
  ['п', 'p'],
  ['р', 'r'],
  ['с', 's'],
  ['т', 't'],
  ['у', 'u'],
  ['ф', 'f'],
  ['х', 'kh'],
  ['ц', 'ts'],
  ['ч', 'ch'],
  ['ш', 'sh'],
  ['щ', 'shch'],
  ['ъ', ''],
  ['ы', 'y'],
  ['ь', ''],
  ['э', 'e'],
  ['ю', 'yu'],
  ['я', 'ya'],
]);

/**
 * Символы, которые выбрасываются, а не превращаются в разделитель: они стоят
 * внутри слова или обрамляют его, и дефис на их месте рвал бы слово.
 */
const DROPPED_CHARS = new Set<string>([
  "'",
  '’', // ’
  '‘', // ‘
  'ʼ', // ʼ
  '`',
  '"',
  '“', // “
  '”', // ”
  '«', // «
  '»', // »
]);

/** Разделитель слов в slug — дефис, по правилам URL из `CLAUDE.md`. */
const SEPARATOR = '-';

const ALLOWED_CHAR = /^[a-z0-9]$/;
const ALLOWED_RUN = /^[a-z0-9]+$/;
const COMBINING_MARKS = /\p{M}/gu;
/**
 * Одиночная комбинирующая метка: у поддерживаемой латиницы она снимается вместе
 * с базовой литерой (`é` → `e`), а сама по себе встречается там, где составной
 * формы не существует, — `i` + U+0307 из `İ`, знак ударения в русском тексте.
 */
const STANDALONE_MARK = /^\p{M}+$/u;
/**
 * Любая литера любой письменности. Критерий отказа привязан НЕ к письменности, а
 * к результату: литера, не давшая после таблицы и снятия диакритики ни одного
 * допустимого символа, обрывает slugify.
 */
const ANY_LETTER = /\p{L}/u;
const SEPARATOR_RUN = /-{2,}/g;
const EDGE_SEPARATORS = /^-+|-+$/g;

/**
 * Максимальная длина slug по умолчанию.
 *
 * ВНИМАНИЕ: это **не решение человека**. Ни `CLAUDE.md`, ни SEO ТЗ длину slug не
 * нормируют. Значение выбрано как рабочий ориентир (читаемый URL, запас под
 * префикс пути `/podborki/<tema>/<utochnenie>/` и под имя файла изображения из
 * задачи Э2-02) и вынесено в параметр именно потому, что подлежит замене без
 * правки логики. Норму задаёт человек — открытый вопрос Ч-26.
 */
export const DEFAULT_SLUG_MAX_LENGTH = 80;

/**
 * Форма валидного slug: один сегмент пути из групп `[a-z0-9]`, разделённых
 * одиночными дефисами. Отсюда автоматически следует отказ на пустой строке,
 * ведущем и хвостовом дефисе, двойном дефисе, верхнем регистре, кириллице,
 * пробеле, подчёркивании, слеше, точке и любом символе параметров (`?`, `&`,
 * `=`, `#`, `%`).
 *
 * Без флага `g`: у глобального регулярного выражения `test` двигает `lastIndex`,
 * и повторная проверка той же строки вернула бы другой результат.
 */
export const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** Опции slug-функций. Единственное поле — по нему видно, что ID/даты на вход не идут. */
export interface SlugOptions {
  /** Максимальная длина результата. По умолчанию {@link DEFAULT_SLUG_MAX_LENGTH}. */
  readonly maxLength?: number;
}

function resolveMaxLength(options: SlugOptions | undefined): number {
  const value = options?.maxLength ?? DEFAULT_SLUG_MAX_LENGTH;
  if (!Number.isSafeInteger(value) || value < 1) {
    throw new RangeError(
      `maxLength должна быть целым числом >= 1, получено: ${String(value)}`,
    );
  }
  return value;
}

function normalizeSeparators(value: string): string {
  return value.replace(SEPARATOR_RUN, SEPARATOR).replace(EDGE_SEPARATORS, '');
}

/**
 * Обрезка по границе слова: если разрез попал внутрь слова, отбрасывается
 * незаконченное слово целиком. Одно слово длиннее лимита обрезается жёстко —
 * иначе результат был бы пустым.
 */
function truncateToWordBoundary(slug: string, maxLength: number): string {
  if (slug.length <= maxLength) {
    return slug;
  }
  const hardCut = slug.slice(0, maxLength);
  if (slug[maxLength] === SEPARATOR) {
    return normalizeSeparators(hardCut);
  }
  const lastSeparator = hardCut.lastIndexOf(SEPARATOR);
  if (lastSeparator > 0) {
    return normalizeSeparators(hardCut.slice(0, lastSeparator));
  }
  return normalizeSeparators(hardCut);
}

/**
 * Превращает заголовок в slug.
 *
 * Свойства, на которые опираются потребители и тесты:
 *   - детерминизм: результат зависит только от `source` и `maxLength`, ни от
 *     времени, ни от счётчиков, ни от состояния модуля;
 *   - идемпотентность: `slugify(slugify(x)) === slugify(x)`;
 *   - результат либо пустая строка, либо строка, проходящая {@link isValidSlug}.
 *     Пустой результат — не исключение: решение, что делать (запросить slug у
 *     редактора, отклонить сохранение), принимает вызывающий код, потому что оно
 *     зависит от коллекции;
 *   - пустая строка возвращается в двух случаях: транслитерировать нечего
 *     (пунктуация, эмодзи, пустой вход) ИЛИ во входе есть литера, не давшая ни
 *     одного допустимого символа — кириллица вне русского алфавита (`і`, `ї`,
 *     `є`, `ґ`, `ў`, `ә`, `ү`), азербайджанские `ı`/`ə`, армянская, грузинская,
 *     греческая и любая другая письменность без таблицы. Второй случай — явный
 *     отказ вместо правдоподобного slug: см. комментарий к таблице и Ч-25.
 *     Достаточно одной такой литеры в любом месте строки — частичный результат
 *     не возвращается, иначе буква молча пропала бы из середины слова.
 *
 * @param source произвольный заголовок (кириллица, латиница, цифры, пунктуация)
 * @param options см. {@link SlugOptions}
 */
export function slugify(source: string, options?: SlugOptions): string {
  const maxLength = resolveMaxLength(options);
  // NFC до toLowerCase: составные `й`/`ё` должны быть одним code point, иначе
  // они распались бы на базовую букву и диакритику и потеряли `y`/`e`.
  const lowered = source.normalize('NFC').toLowerCase();

  let transliterated = '';
  for (const char of lowered) {
    const mapped = CYRILLIC_TO_LATIN.get(char);
    if (mapped !== undefined) {
      transliterated += mapped;
      continue;
    }
    if (ALLOWED_CHAR.test(char)) {
      transliterated += char;
      continue;
    }
    if (DROPPED_CHARS.has(char)) {
      continue;
    }
    if (STANDALONE_MARK.test(char)) {
      // Одиночная комбинирующая метка — та же логика, что у DROPPED_CHARS: сама
      // по себе она не несёт слова, поэтому отбрасывается, а не превращается в
      // дефис. Иначе `İstanbul` (U+0130 после toLowerCase = `i` + U+0307;
      // составной строчной формы у него не существует, NFC не помогает) дал бы
      // `i-stanbul`, а «по́здравления» со знаком ударения — `po-zdravleniya`.
      // Отказ здесь тоже неуместен: базовая литера допустимый символ дала.
      continue;
    }
    // Латиница с диакритикой: `é` → `e`, а не разделитель и не отказ.
    const stripped = char.normalize('NFD').replace(COMBINING_MARKS, '');
    if (ALLOWED_RUN.test(stripped)) {
      transliterated += stripped;
      continue;
    }
    if (ANY_LETTER.test(char)) {
      // Литера, не давшая НИ ОДНОГО допустимого символа: ни таблицы, ни
      // диакритики. Отказ всей строки, а не разделитель и не пропуск буквы —
      // иначе `открытки Ənvər` дал бы правдоподобный `otkrytki-nv-r`, а
      // «Բարև открытки» — `otkrytki`, и после публикации это необратимо (Ч-25).
      return '';
    }
    transliterated += SEPARATOR;
  }

  return truncateToWordBoundary(normalizeSeparators(transliterated), maxLength);
}

/**
 * Проверяет форму ОДНОГО сегмента пути.
 *
 * Возвращает `false` на кириллице, пробеле, подчёркивании, верхнем регистре,
 * символах параметров, ведущем/хвостовом/двойном дефисе, пустой строке, слеше и
 * точке, а также на превышении `maxLength`.
 *
 * Занятость пути (зарезервированные маршруты, сегмент `page`) здесь НЕ
 * проверяется — это реестр маршрутов из остатка задачи Э1-01. Иерархический
 * путь проверяется посегментно.
 *
 * Slug из одних цифр (`2027`, `8`) сейчас принимается: формального запрета в
 * `CLAUDE.md` и SEO ТЗ нет, а отличить год от осмысленного числа по форме
 * невозможно. Ждёт ответа по Ч-27.
 */
export function isValidSlug(value: string, options?: SlugOptions): boolean {
  const maxLength = resolveMaxLength(options);
  return value.length <= maxLength && SLUG_PATTERN.test(value);
}
