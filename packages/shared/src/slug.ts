/**
 * Границы диапазона, в котором четырёхзначное число считается ГОДОМ.
 *
 * Значения **2000 и 2099** — выбор агента (провенанс: агент, не решение
 * человека; кандидат в реестр решений вместе с MAX_BATCH_SELECTION и пределом
 * поиска дублей). Норма, которую они реализуют, задана человеком:
 * `CLAUDE.md` → «Правила URL» → «Год не добавляется в URL ежегодных
 * праздников»; `docs/plan-etapov.md` называет год в URL ежегодного праздника
 * прямым критерием провала вето V1.
 *
 * Почему диапазон, а не «любые четыре цифры»: адрес открытки законно содержит
 * числа — `8-marta`, `1-sentyabrya`, `otkrytka-1920x1080`. Проверка «четыре
 * цифры подряд» отклонила бы формат `1920x1080` как год, а проверка «есть
 * цифры» — все даты праздников. Нижняя граница 2000 выбрана так, чтобы
 * типичные размеры в пикселях (`1080`, `1920`) под правило не попадали, а
 * верхняя 2099 покрывает любой год, который редактор может написать в этом
 * веке. Известное следствие, принятое сознательно: `2048` (размер в пикселях)
 * будет отклонён как год — размеры производных живут в связанной записи
 * изображения, а не в адресе страницы.
 */
export const YEAR_IN_SLUG_MIN = 2000;

/** См. {@link YEAR_IN_SLUG_MIN}. */
export const YEAR_IN_SLUG_MAX = 2099;

/** Четырёхзначное число, не склеенное с более длинным числом. */
const FOUR_DIGIT_RUN = /(?<![0-9])[0-9]{4}(?![0-9])/g;

/**
 * Ищет год в slug или в ЦЕЛОМ пути.
 *
 * Возвращает найденный год строкой (чтобы вызывающий назвал его в тексте
 * отказа) или `null`. Вход не обязан быть валидным slug: правило проверяется по
 * итоговому адресу записи, а он собирается из сегментов.
 *
 * Чего функция НЕ делает: не решает, ЗАПРЕЩЁН ли год этой записи. Область
 * применения — дело вызывающего (у ежегодного праздника и у карточки запрещён,
 * см. `apps/cms/src/collections/collection-path.ts` и
 * `apps/cms/src/seo/paths.ts`), потому что `isValidSlug` зовут и
 * `packages/images` для технических сегментов, где год бессмыслен как понятие.
 */
export function findYearInSlug(value: string): string | null {
  // Без общего состояния: у регулярного выражения с флагом `g` `exec` двигает
  // `lastIndex`, поэтому матчи собираются через matchAll на копии.
  for (const match of value.matchAll(FOUR_DIGIT_RUN)) {
    const year = Number(match[0]);
    if (year >= YEAR_IN_SLUG_MIN && year <= YEAR_IN_SLUG_MAX) {
      return match[0];
    }
  }
  return null;
}

/** Короткая форма {@link findYearInSlug} для условий. */
export function hasYearInSlug(value: string): boolean {
  return findYearInSlug(value) !== null;
}
