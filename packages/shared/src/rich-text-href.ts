/**
 * Адреса, которые публичный рендер печатает ССЫЛКОЙ (контракт вводного текста).
 *
 * ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В ШАБЛОНЕ И НЕ В КОНФИГЕ ПОЛЯ. Разбор
 * lexical в `apps/web` печатает ссылкой только два вида адресов — путь от корня
 * сайта и абсолютный `http(s)`. Всё остальное (`mailto:`, `tel:`,
 * `javascript:`, протокольно-относительная форма `//host`, внутренняя ссылка по
 * идентификатору записи) остаётся ТЕКСТОМ: слова не теряются, но ссылочность
 * исчезает, и редактор об этом не узнаёт — в админке ссылка выглядит ссылкой.
 *
 * Молчаливая деградация лечится не второй проверкой в шаблоне, а тем, что
 * недопустимый адрес НЕВОЗМОЖНО сохранить: `apps/cms` вешает
 * {@link validatePublicRichTextHref} на поле адреса ссылки в редакторе
 * (`LinkFeature`). Чтобы «что печатается» и «что можно сохранить» не разошлись,
 * правило одно и лежит в общем пакете: у `apps/web` предикат
 * {@link publicRichTextHref}, у `apps/cms` — валидатор поверх него.
 *
 * Расширять набор схем можно только ВМЕСТЕ с рендером: разрешить здесь
 * `mailto:`, не научив шаблон его печатать, — значит вернуть ту же
 * деградацию, от которой модуль и существует.
 */
import { looksLikeAbsoluteUrl } from './routes.js';

/** Схемы, которые публичный рендер выводит ссылкой. Набор закрыт намеренно. */
const RENDERABLE_SCHEME = /^https?:\/\//iu;

/** Разобранный адрес ссылки вводного текста. */
export interface PublicRichTextHref {
  readonly href: string;
  /**
   * Адрес ведёт на другой хост — шаблон добавит `rel="nofollow noopener"`.
   *
   * Абсолютный адрес считается внешним даже при совпадении хоста с `SITE_URL`:
   * внутренние ссылки в проекте пишутся путём от корня, и это же правило
   * держит единственность источника хоста.
   */
  readonly external: boolean;
}

/**
 * Адрес ссылки либо `null`, если публичный рендер печатает его текстом.
 *
 * Белый список, а не чёрный: пропускается путь от корня сайта и абсолютный
 * адрес по `http`/`https`. `javascript:` и `data:` не «плохие исключения», а
 * просто не входят в набор — исполняемый код в атрибуте `href` не должен
 * зависеть от полноты списка запретов.
 */
export function publicRichTextHref(value: unknown): PublicRichTextHref | null {
  if (typeof value !== 'string') {
    return null;
  }
  const url = value.trim();
  if (url === '') {
    return null;
  }
  if (!looksLikeAbsoluteUrl(url)) {
    return url.startsWith('/') ? { external: false, href: url } : null;
  }
  return RENDERABLE_SCHEME.test(url) ? { external: true, href: url } : null;
}

/** Печатает ли публичный рендер этот адрес ссылкой. */
export function isPublicRichTextHref(value: unknown): boolean {
  return publicRichTextHref(value) !== null;
}

/**
 * Валидатор адреса ссылки для поля редактора (`apps/cms`).
 *
 * Пусто — норма для валидатора: обязательность самого поля задаёт Payload
 * (`required: true` у адреса ссылки), а «пусто» и «не той схемы» — разные
 * отказы, и смешивать их в одном тексте значило бы объяснять редактору не то,
 * что произошло.
 */
export function validatePublicRichTextHref(value: unknown): string | true {
  if (value === undefined || value === null) {
    return true;
  }
  if (typeof value !== 'string') {
    return (
      'Адрес ссылки задаётся строкой: путём от корня сайта (например /usloviya) либо ' +
      'полным адресом по http или https.'
    );
  }
  const url = value.trim();
  if (url === '') {
    return true;
  }
  if (isPublicRichTextHref(url)) {
    return true;
  }
  return (
    `«${url}» — адрес, который публичный ` +
    'рендер ссылкой не выводит: он напечатал бы текст, и ссылочность потерялась бы молча. ' +
    'Внутренняя ссылка задаётся путём от корня сайта (например /podborki/prazdniki/8-marta), ' +
    'внешняя — полным адресом по http или https. Схемы mailto:, tel:, javascript: и ' +
    'протокольно-относительная форма //host в наборе не значатся: чтобы они появились, ' +
    'сначала их обязан научиться печатать шаблон.'
  );
}
