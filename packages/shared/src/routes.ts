/**
 * Правило завершающего слеша и его область применения.
 *
 * Норма — `CLAUDE.md`, раздел «Правила URL — нарушать запрещено»: единое правило
 * по всему сайту, выбрана форма **БЕЗ завершающего слеша** (решение Ч-21,
 * 2026-08-21; заменяет прежний выбор «со слешем»). Канонический вид маршрута
 * страницы — `/otkrytki/8-marta`; обращение с завершающим слешем отдаёт
 * одиночный 301 на форму без слеша. Две формы одного пути, отвечающие 200, —
 * это дубль, поэтому правило одно и живёт в одном месте.
 *
 * Область применения правила задаёт {@link isPageRoute}: URL файлов слешем не
 * заканчиваются и нормализации не подлежат. Маршруты админки Payload отдаёт
 * `apps/cms` (собственный роутер по `PAYLOAD_ADMIN_PATH`) вне нормализации
 * Astro — предикат про них ничего не знает и знать не должен: попытка
 * нормализовать путь админки здесь означала бы редирект на чужом роутере.
 *
 * Чего в этом модуле НЕТ намеренно:
 *   - самого middleware редиректа (Astro, задача Э3-01) — здесь только правило;
 *   - реестра зарезервированных маршрутов — `./reserved-routes.ts`;
 *   - сборки абсолютного URL — `./site-url.ts`.
 */

/**
 * Единое правило завершающего слеша по всему сайту: `false` — канонический вид
 * маршрута страницы БЕЗ завершающего слеша (решение Ч-21).
 *
 * Константа load-bearing: {@link canonicalizePath} строит путь по ней, поэтому
 * смена значения меняет форму всех канонических URL сразу, а не в одном месте
 * из нескольких. Менять её после первой индексации нельзя — это 301 всего сайта.
 */
export const TRAILING_SLASH = false;

/**
 * Расширение в последнем сегменте пути. Именно оно отличает URL файла от
 * маршрута страницы: slug страницы точку не допускает (`isValidSlug` её
 * отклоняет), поэтому точка в последнем сегменте всегда означает файл.
 */
const EXTENSION_IN_LAST_SEGMENT = /\.[^./]+$/;

/** Схема в начале строки: признак того, что на вход дали URL, а не путь. */
const URL_SCHEME = /^[a-z][a-z0-9+.-]*:/i;

function assertPathShape(value: string): void {
  if (value.includes('?') || value.includes('#')) {
    throw new Error(
      `«${value}» не является путём: параметры запроса и фрагмент в путь не входят. ` +
        'Канонический URL параметров не содержит (CLAUDE.md, правила URL), поэтому ' +
        'путь передаётся отдельно от строки запроса, а не вычищается догадкой.',
    );
  }
}

function splitSegments(value: string): string[] {
  return value.split('/').filter((segment) => segment !== '');
}

/**
 * Сегменты пути без пустых: `/otkrytki//8-marta/` → `['otkrytki', '8-marta']`.
 * Нужен и реестру маршрутов (проверка сегмента `page` на любой позиции), и
 * сборке URL, поэтому живёт здесь, а не дублируется.
 */
export function pathSegments(value: string): readonly string[] {
  assertPathShape(value);
  return splitSegments(value);
}

/**
 * Маршрут страницы (`true`) или URL файла (`false`).
 *
 * Файлом считается путь, последний сегмент которого содержит расширение:
 * `/media/cards/r2/otkrytka-640.webp`, `/robots.txt`, `/sitemap.xml`. Точка в
 * родительском сегменте файлом путь не делает — расширение ищется только в
 * последнем сегменте.
 *
 * Корень (`/` и пустая строка) — маршрут страницы: это главная.
 *
 * Завершающий слеш решения не меняет: `/otkrytki/8-marta/` остаётся маршрутом
 * страницы, иначе middleware не выдал бы на него 301, а `/robots.txt/` файлом и
 * остаётся. Ведущий слеш необязателен — ключи объектов `packages/images`
 * приходят без него.
 *
 * Про админку: её маршруты сюда не попадают, их отдаёт `apps/cms` вне
 * нормализации Astro (см. шапку модуля).
 *
 * @throws Error если во входе есть `?` или `#` — это не путь.
 */
export function isPageRoute(value: string): boolean {
  assertPathShape(value);
  const last = splitSegments(value).at(-1);
  if (last === undefined) {
    return true;
  }
  return !EXTENSION_IN_LAST_SEGMENT.test(last);
}

/**
 * Приводит путь к канонической форме: ведущий слеш, без повторных слешей, без
 * завершающего слеша у маршрутов страниц (при {@link TRAILING_SLASH} `false`).
 *
 * Повторные слеши схлопываются, а не отклоняются: `/otkrytki//8-marta` и
 * `/otkrytki/8-marta` обязаны быть одним URL, иначе получается дубль.
 *
 * @throws Error если во входе есть `?` или `#`.
 */
export function canonicalizePath(value: string): string {
  const segments = [...pathSegments(value)];
  if (segments.length === 0) {
    return '/';
  }
  const path = `/${segments.join('/')}`;
  const wantsTrailingSlash: boolean = TRAILING_SLASH;
  if (wantsTrailingSlash && isPageRoute(path)) {
    return `${path}/`;
  }
  return path;
}

/**
 * Признак того, что на вход дали абсолютный URL там, где ожидался путь.
 * Отдельная функция, потому что нужна и сборке URL, и вызывающему коду.
 */
export function looksLikeAbsoluteUrl(value: string): boolean {
  return URL_SCHEME.test(value.trim());
}
