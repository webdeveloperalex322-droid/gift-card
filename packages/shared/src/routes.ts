/**
 * Правило завершающего слеша и его область применения.
 *
 * Норма — `CLAUDE.md`, раздел «Правила URL — нарушать запрещено»: единое правило
 * по всему сайту, выбрана форма **БЕЗ завершающего слеша** (решение Ч-21,
 * 2026-08-21; заменяет прежний выбор «со слешем»). Канонический вид маршрута
 * страницы — `/otkrytki/8-marta`; обращение с завершающим слешем отдаёт
 * одиночный 301 на форму без слеша. Две формы одного пути, отвечающие 200, —
 * это дубль, поэтому правило одно и живёт в одном месте.
 *
 * Область применения правила задаёт {@link isPageRoute}: URL файлов слешем не
 * заканчиваются и нормализации не подлежат. Маршруты админки Payload отдаёт
 * `apps/cms` (собственный роутер по `PAYLOAD_ADMIN_PATH`) вне нормализации
 * Astro — предикат про них ничего не знает и знать не должен: попытка
 * нормализовать путь админки здесь означала бы редирект на чужом роутере.
 *
 * Здесь же живёт распознавание АБСОЛЮТНОГО адреса, отданного вместо пути:
 * {@link looksLikeAbsoluteUrl} и {@link isProtocolRelativeUrl}. Обе формы —
 * одно правило про один и тот же риск (чужой хост в canonical, sitemap или
 * редиректе), поэтому они рядом и в общем пакете: потребитель, который узнал бы
 * только про одну из них, закрыл бы половину дыры.
 *
 * Чего в этом модуле НЕТ намеренно:
 *   - самого middleware редиректа (Astro, задача Э3-01) — здесь только правило;
 *   - реестра зарезервированных маршрутов — `./reserved-routes.ts`;
 *   - сборки абсолютного URL — `./site-url.ts`.
 *
 * ## Зафиксированное расхождение с политикой запроса в apps/web
 *
 * {@link canonicalizePath} пустые сегменты В СЕРЕДИНЕ пути СХЛОПЫВАЕТ
 * (`/otkrytki//8-marta` → `/otkrytki/8-marta`), а входной сервер apps/web
 * (`apps/web/src/routing/path-policy.ts`) такой ЗАПРОС отвергает с 404. Это не
 * рассогласование правил, а разные роли:
 *
 *   - здесь вход — путь, который мы СТРОИМ сами (canonical, sitemap, редирект по
 *     данным CMS). Он обязан получить каноническую форму, а не отказ: два
 *     написания одного пути в наших же данных должны сойтись в один URL;
 *   - там вход — цель ЗАПРОСА извне. Редирект на схлопнутую форму дал бы 301 на
 *     выдуманный адрес в случае `//host/x` (для браузера это чужой хост), а 200
 *     по обеим формам дал бы дубль. Отказ не порождает `Location` вовсе.
 *
 * Расхождение зафиксировано, а не устранено, и менять поведение этого модуля под
 * серверную политику нельзя: тогда `canonicalizePath` перестал бы быть полной
 * функцией для собственных данных. Сервер сверяется с этим модулем сам —
 * `assertCanonical` в `path-policy.ts` падает, если формы разойдутся.
 */

/**
 * Единое правило завершающего слеша по всему сайту: `false` — канонический вид
 * маршрута страницы БЕЗ завершающего слеша (решение Ч-21).
 *
 * Константа load-bearing: {@link canonicalizePath} строит путь по ней, поэтому
 * смена значения меняет форму всех канонических URL сразу, а не в одном месте
 * из нескольких. Менять её после первой индексации нельзя — это 301 всего сайта.
 */
export const TRAILING_SLASH = false;

/**
 * Расширение в последнем сегменте пути. Именно оно отличает URL файла от
 * маршрута страницы: slug страницы точку не допускает (`isValidSlug` её
 * отклоняет), поэтому точка в последнем сегменте всегда означает файл.
 */
const EXTENSION_IN_LAST_SEGMENT = /\.[^./]+$/;

/** Схема в начале строки: признак того, что на вход дали URL, а не путь. */
const URL_SCHEME = /^[a-z][a-z0-9+.-]*:/i;

/**
 * Начало протокольно-относительного адреса: два разделителя подряд в самом
 * начале строки.
 *
 * Обратный слеш учитывается наравне с прямым: парсер URL приводит `\` к `/` в
 * адресах со специальной схемой, поэтому `/\host`, `\/host` и `\\host` для
 * браузера и краулера — тот же самый `//host`. Проверять только `//` означало бы
 * закрыть одну форму из четырёх.
 */
const PROTOCOL_RELATIVE_PREFIX = /^[/\\]{2}/;

/**
 * Коды символов, которые парсер URL (WHATWG) удаляет ИЗ СЕРЕДИНЫ адреса:
 * табуляция, перевод строки, возврат каретки.
 */
const URL_REMOVED_CHAR_CODES: ReadonlySet<number> = new Set([0x09, 0x0a, 0x0d]);

/** Верхняя граница символов, которые парсер URL обрезает по краям адреса. */
const LAST_TRIMMED_CHAR_CODE = 0x20;

/**
 * Вход в том виде, в каком его увидит парсер URL браузера или краулера.
 *
 * Нормализация до проверки обязательна: `/<tab>/host` парсер видит как
 * `//host`, а ведущие пробелы и управляющие символы он обрезает. Проверка по
 * «сырой» строке пропустила бы обе формы, то есть пропустила бы чужой хост.
 */
function asUrlParserSeesIt(value: string): string {
  let compacted = '';
  for (const char of value) {
    if (!URL_REMOVED_CHAR_CODES.has(char.charCodeAt(0))) {
      compacted += char;
    }
  }

  let start = 0;
  let end = compacted.length;
  while (start < end && compacted.charCodeAt(start) <= LAST_TRIMMED_CHAR_CODE) {
    start += 1;
  }
  while (end > start && compacted.charCodeAt(end - 1) <= LAST_TRIMMED_CHAR_CODE) {
    end -= 1;
  }
  return compacted.slice(start, end);
}

function assertPathShape(value: string): void {
  if (isProtocolRelativeUrl(value)) {
    throw new Error(
      `«${value}» не является путём: это протокольно-относительный адрес, то есть ` +
        'абсолютный адрес ДРУГОГО хоста. Схлопнуть ведущий двойной слеш нельзя — ' +
        'чужой хост стал бы первым сегментом пути, и подмена осталась бы невидимой: ' +
        'путь выглядел бы валидным. Хост попадает в абсолютный URL только из SITE_URL ' +
        '(CLAUDE.md, правила URL), поэтому такой вход отклоняется, а не исправляется.',
    );
  }
  if (value.includes('?') || value.includes('#')) {
    throw new Error(
      `«${value}» не является путём: параметры запроса и фрагмент в путь не входят. ` +
        'Канонический URL параметров не содержит (CLAUDE.md, правила URL), поэтому ' +
        'путь передаётся отдельно от строки запроса, а не вычищается догадкой.',
    );
  }
}

function splitSegments(value: string): string[] {
  return value.split('/').filter((segment) => segment !== '');
}

/**
 * Сегменты пути без пустых: `/otkrytki//8-marta/` → `['otkrytki', '8-marta']`.
 * Нужен и реестру маршрутов (проверка сегмента `page` на любой позиции), и
 * сборке URL, поэтому живёт здесь, а не дублируется.
 *
 * @throws Error если во входе есть `?`/`#` или это адрес другого хоста.
 */
export function pathSegments(value: string): readonly string[] {
  assertPathShape(value);
  return splitSegments(value);
}

/**
 * Маршрут страницы (`true`) или URL файла (`false`).
 *
 * Файлом считается путь, последний сегмент которого содержит расширение:
 * `/media/cards/r2/otkrytka-640.webp`, `/robots.txt`, `/sitemap.xml`. Точка в
 * родительском сегменте файлом путь не делает — расширение ищется только в
 * последнем сегменте.
 *
 * Корень (`/` и пустая строка) — маршрут страницы: это главная.
 *
 * Завершающий слеш решения не меняет: `/otkrytki/8-marta/` остаётся маршрутом
 * страницы, иначе middleware не выдал бы на него 301, а `/robots.txt/` файлом и
 * остаётся. Ведущий слеш необязателен — ключи объектов `packages/images`
 * приходят без него.
 *
 * Про админку: её маршруты сюда не попадают, их отдаёт `apps/cms` вне
 * нормализации Astro (см. шапку модуля).
 *
 * @throws Error если во входе есть `?`/`#` или это адрес другого хоста — это не
 *   путь.
 */
export function isPageRoute(value: string): boolean {
  assertPathShape(value);
  const last = splitSegments(value).at(-1);
  if (last === undefined) {
    return true;
  }
  return !EXTENSION_IN_LAST_SEGMENT.test(last);
}

/**
 * Приводит путь к канонической форме: ведущий слеш, без повторных слешей, без
 * завершающего слеша у маршрутов страниц (при {@link TRAILING_SLASH} `false`).
 *
 * Повторные слеши В СЕРЕДИНЕ схлопываются, а не отклоняются: `/otkrytki//8-marta`
 * и `/otkrytki/8-marta` обязаны быть одним URL, иначе получается дубль.
 *
 * Двойной слеш В НАЧАЛЕ — другой случай и другое решение: `//host/x` для
 * браузера и краулера означает абсолютный адрес другого хоста, поэтому вход
 * отклоняется. Схлопывание превратило бы чужой хост в первый сегмент пути, и
 * ошибка стала бы невидимой — путь выглядел бы валидным, а canonical или
 * редирект уводил бы на чужой домен.
 *
 * @throws Error если во входе есть `?`/`#` или это адрес другого хоста.
 */
export function canonicalizePath(value: string): string {
  const segments = [...pathSegments(value)];
  if (segments.length === 0) {
    return '/';
  }
  const path = `/${segments.join('/')}`;
  const wantsTrailingSlash: boolean = TRAILING_SLASH;
  if (wantsTrailingSlash && isPageRoute(path)) {
    return `${path}/`;
  }
  return path;
}

/**
 * Протокольно-относительный адрес (`//host/x`) — абсолютный адрес ДРУГОГО хоста
 * без схемы.
 *
 * Отдельный предикат нужен потому, что схемы в такой строке нет и проверка «есть
 * ли схема» её пропускает, а последствия те же: canonical, редирект или ссылка
 * уводят на чужой домен. Формы `\\host`, `/\host`, `\/host`, `///host`,
 * `/<tab>/host` и вариант с ведущими пробелами — это тот же адрес: парсер URL
 * приводит их к `//host`, поэтому здесь они распознаются все.
 *
 * Двойной слеш в СЕРЕДИНЕ пути (`/a//b`) адресом другого хоста не является и
 * этим предикатом не отклоняется — его схлопывает {@link canonicalizePath}.
 */
export function isProtocolRelativeUrl(value: string): boolean {
  return PROTOCOL_RELATIVE_PREFIX.test(asUrlParserSeesIt(value));
}

/**
 * Признак того, что на вход дали абсолютный адрес там, где ожидался путь.
 * Отдельная функция, потому что нужна и сборке URL, и вызывающему коду.
 *
 * Абсолютным считается и адрес со схемой (`https://host/x`, `mailto:`), и
 * протокольно-относительный (`//host/x`): для браузера и краулера обе формы
 * ведут на другой хост, поэтому и правило про них одно. Разделять их в
 * потребителях нельзя — тот, кто проверит только схему, оставит дыру; там, где
 * нужна причина отказа, есть {@link isProtocolRelativeUrl}.
 */
export function looksLikeAbsoluteUrl(value: string): boolean {
  const probe = asUrlParserSeesIt(value);
  return URL_SCHEME.test(probe) || PROTOCOL_RELATIVE_PREFIX.test(probe);
}
