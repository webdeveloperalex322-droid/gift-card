/**
 * СВЯЗЬ ДВУХ ПОЛОВИН ОДНОЙ ЗАЩИТЫ: набор узлов, которые можно СОХРАНИТЬ, и набор
 * узлов, которые умеет НАПЕЧАТАТЬ публичный разбор.
 *
 * Половины лежат в разных приложениях и до этого теста были связаны только
 * словами в шапках:
 *
 *   - `PUBLIC_RICH_TEXT_NODE_TYPES` (`apps/cms/src/editor/public-rich-text.ts`) —
 *     серверный хук отклоняет документ с узлом вне набора, поэтому набор
 *     описывает всё, что вообще может оказаться в опубликованном поле;
 *   - `PRINTABLE_NODE_TYPES` (`apps/web/src/seo/rich-text.ts`) — разбор либо
 *     печатает такой узел, либо сознательно пропускает; узел ВНЕ набора и без
 *     детей даёт отказ.
 *
 * Что происходило без проверки. Тип, добавленный в набор CMS вместе с новой
 * фичей редактора, но без правки разбора, давал один из двух исходов, и оба
 * обнаруживались не здесь, а на опубликованной странице:
 *
 *   1. узел БЕЗ детей (`upload`, `relationship`, `block`) — `assertPrintable`
 *      бросает исключение, то есть 500 на странице, которую человек опубликовал;
 *   2. узел С ДЕТЬМИ (например новый вид контейнера) — разбор раскрывает его в
 *      детей, и блок молча расплющивается: текст на месте, структуры нет.
 *
 * Направление включения ровно одно и обратным быть не может: у разбора в наборе
 * есть типы, которых в CMS нет намеренно (`autolink` и `horizontalrule` —
 * документы прежнего, более широкого редактора; их разбор обязан уметь читать,
 * но сохранять их больше нельзя). Поэтому проверяется «CMS ⊆ web», а не
 * равенство.
 *
 * Импорт из `apps/cms` в тест законен: тесты — единственное место, где границы
 * приложений сходятся. В дерево зависимостей публичного сервера `apps/cms` от
 * этого не попадает.
 */
import { describe, expect, it } from 'vitest';

import { PRINTABLE_NODE_TYPES } from '../../apps/web/src/seo/rich-text.js';

/**
 * Почему набор CMS приходит ДИНАМИЧЕСКИМ импортом, а не обычным.
 *
 * `apps/cms` не может быть composite-проектом TypeScript: Next требует `noEmit`,
 * а composite требует emit объявлений (обоснование — в `apps/cms/tsconfig.json`).
 * Поэтому проект тестов на него не ссылается, и обычный импорт втянул бы
 * ИСХОДНИК cms в проект тестов — с чужим разрешением модулей (`NodeNext` против
 * `Bundler`) и, как следствие, с ошибками TS2742 в типах
 * `@payloadcms/richtext-lexical`. Проверять типы чужого приложения из проекта
 * тестов — та же ошибка владения, которую уже исправляли для `apps/web`.
 *
 * Форма с переменной-спецификатором выбрана намеренно: она даёт РУНТАЙМНОЕ
 * значение (то самое, что работает в продакшене) без включения файла в проект
 * тестов. Тот же приём в `./web-rich-text.test.ts` используется для импорта
 * `@payloadcms/richtext-lexical`.
 */
const CMS_EDITOR_MODULE = '../../apps/cms/src/editor/public-rich-text.ts';

const cmsEditor = (await import(CMS_EDITOR_MODULE)) as {
  readonly PUBLIC_RICH_TEXT_NODE_TYPES: ReadonlySet<string>;
};
const PUBLIC_RICH_TEXT_NODE_TYPES = cmsEditor.PUBLIC_RICH_TEXT_NODE_TYPES;

describe('узлы вводного текста: сохранить можно только то, что печатается', () => {
  it('каждый тип из набора CMS умеет обработать публичный разбор', () => {
    const unprintable = [...PUBLIC_RICH_TEXT_NODE_TYPES].filter(
      (type) => !PRINTABLE_NODE_TYPES.has(type),
    );

    expect(
      unprintable,
      'Эти типы узлов CMS разрешает сохранить, а публичный разбор их не знает. Узел без ' +
        'детей даст отказ на опубликованной странице, узел с детьми — молча расплющится. ' +
        'Либо научите разбор (apps/web/src/seo/rich-text.ts), либо уберите тип из набора ' +
        'apps/cms/src/editor/public-rich-text.ts.',
    ).toEqual([]);
  });

  it('оба набора непусты — иначе включение выполнялось бы тривиально', () => {
    // Проверка от подмены: пустой набор CMS (или пустой набор разбора,
    // превративший тест в тавтологию) означал бы, что связь есть только на вид.
    expect(PUBLIC_RICH_TEXT_NODE_TYPES.size).toBeGreaterThan(0);
    expect(PRINTABLE_NODE_TYPES.size).toBeGreaterThanOrEqual(PUBLIC_RICH_TEXT_NODE_TYPES.size);
  });

  it('база документа lexical есть в обоих наборах', () => {
    // `root`, `paragraph` и `text` — минимум, без которого поле не хранит ничего.
    // Отдельная проверка нужна затем, чтобы включение не выполнялось за счёт
    // случайно совпавших редких типов при потерянной базе.
    for (const type of ['root', 'paragraph', 'text']) {
      expect(PUBLIC_RICH_TEXT_NODE_TYPES.has(type), `набор CMS: ${type}`).toBe(true);
      expect(PRINTABLE_NODE_TYPES.has(type), `набор разбора: ${type}`).toBe(true);
    }
  });
});
