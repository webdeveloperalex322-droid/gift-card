/**
 * Требование: обход сайта поисковой системой НЕ ограничивается по частоте.
 *
 * Появился этот spec на задаче Э6-03 (ограничение частоты на API-ключ, Ч-14).
 * Сама задача трогает только `apps/cms`, но требование, которое она задевает, —
 * SEO-шное, и до сих пор оно не проверялось ничем: краулер Яндекса и Google не
 * предъявляет API-ключ и вообще не аутентифицируется, поэтому любой ответ `429`
 * на публичном адресе для него — это не «клиент шумит», а урезанный краул-бюджет
 * и выпадение адресов из обхода. Яндекс при повторяющихся `429` снижает частоту
 * обращений к сайту целиком, то есть цена ошибки платится не той страницей, на
 * которой она произошла.
 *
 * ЧТО ИМЕННО ЗДЕСЬ ПРОВЕРЯЕТСЯ. Пачка запросов БЕЗ единого заголовка
 * авторизации, числом заведомо больше утверждённого всплеска Ч-14 (120), по
 * адресам, которые краулер и запрашивает в первую очередь: корень, `/robots.txt`,
 * `/sitemap.xml`, служебная `/search`. Ни один ответ не имеет права быть `429` и
 * не имеет права принести `Retry-After`, а статус каждого адреса обязан остаться
 * тем же, каким был на первом запросе, — «сначала 200, потом отказ» это и есть
 * троттлинг, как бы он ни назывался.
 *
 * ЧЕГО ЭТОТ SPEC НЕ ПРОВЕРЯЕТ И ПОЧЕМУ. Он не трогает `/api` CMS: приёмка
 * поднимает только собранный `apps/web` (см. `support/serve-built-web.mjs`), а
 * `apps/web` маршрутов `/api` не имеет вовсе. Разделение границы «ключ
 * ограничивается, аноним и сессия — нет» доказывается живыми запросами в
 * `tests/api/rate-limit.test.ts`; здесь проверяется другое утверждение — что
 * ограничение не переехало на публичную поверхность сайта. Оба нужны: первое
 * может остаться зелёным, если ограничение однажды навесят ещё и на маршруты
 * `apps/web` (middleware, прокси, шлюз) — а тогда первым его почувствует именно
 * краулер, потому что он единственный ходит по сайту сотнями запросов подряд.
 */

import { expect, test } from '@playwright/test';

import { fetchRaw } from './support/http.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/**
 * Адреса обхода. Взяты те, что существуют при ЛЮБОМ состоянии базы (то же
 * правило, что у `support/pages.ts`): статус здесь — утверждение о коде, а не о
 * содержимом чьей-то базы.
 */
const CRAWLED_PATHS = ['/', '/robots.txt', '/sitemap.xml', '/search'] as const;

/**
 * Сколько запросов делает «краулер».
 *
 * Число выбрано БОЛЬШЕ утверждённого всплеска Ч-14 (120) намеренно: при меньшем
 * пачка прошла бы и через включённое ограничение, и spec был бы зелёным ровно в
 * том случае, который обязан ловить. Запросы идут подряд, поэтому за время
 * прогона (единицы секунд) пополнение бакета вернуло бы считаные токены — то
 * есть 121-й запрос при включённом ограничении получил бы отказ.
 */
const BURST_SIZE = 132;

test('пачка анонимных запросов не получает 429: обход сайта краулером не троттлится', async ({
  request,
}) => {
  test.setTimeout(90_000);

  // Статус, с которого адрес начал. Сравнение идёт с ним, а не с константой 200:
  // проверяется НЕИЗМЕННОСТЬ ответа под нагрузкой, и подмена ожидания на «всегда
  // 200» превратила бы этот spec во вторую копию `status-ignores-query`.
  const baseline = new Map<string, number>();

  for (let attempt = 0; attempt < BURST_SIZE; attempt += 1) {
    const path = CRAWLED_PATHS[attempt % CRAWLED_PATHS.length] ?? '/';
    const response = await fetchRaw(request, urlFor(target, path));

    expect(
      response.status,
      `${path}: запрос №${String(attempt + 1)} из ${String(BURST_SIZE)} получил 429. Краулер ` +
        'Яндекса и Google не аутентифицируется и не предъявляет API-ключ, поэтому ограничение ' +
        'частоты, дотянувшееся до публичных адресов, бьёт именно по обходу: адреса выпадают из ' +
        'краула, а повторяющийся 429 снижает частоту обращений ко всему сайту. Ограничение ' +
        'Ч-14 задано НА КЛЮЧ и обязано считать только запросы с заголовком «users API-Key ...» ' +
        '(apps/cms/src/http/api-rate-limit.ts).',
    ).not.toBe(429);

    expect(
      response.headers['retry-after'],
      `${path}: запрос №${String(attempt + 1)} принёс Retry-After при статусе ` +
        `${String(response.status)}. На публичном адресе этот заголовок означает просьбу ` +
        'притормозить обход — то есть троттлинг, даже если код ответа не 429. Законное место ' +
        'Retry-After — только ответ 503 режима обслуживания (см. maintenance-mode-503.spec.ts).',
    ).toBeUndefined();

    const first = baseline.get(path);
    if (first === undefined) {
      baseline.set(path, response.status);
    } else {
      expect(
        response.status,
        `${path}: статус изменился под нагрузкой — первый запрос ответил ${String(first)}, ` +
          `запрос №${String(attempt + 1)} ответил ${String(response.status)}. Адрес, который ` +
          'отвечает по-разному в зависимости от числа обращений, для краулера неотличим от ' +
          'нестабильного сайта.',
      ).toBe(first);
    }
  }

  // Страховка от тихого вырождения набора: если бы адреса перестали запрашиваться
  // (опечатка в списке, пустой цикл), все утверждения выше выполнились бы
  // тривиально.
  expect(
    baseline.size,
    'ни один адрес обхода не был запрошен — spec прошёл бы вхолостую.',
  ).toBe(CRAWLED_PATHS.length);
});
