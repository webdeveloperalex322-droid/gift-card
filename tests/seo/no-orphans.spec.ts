/**
 * Требование (п. 22, чек-лист: «нет страниц-сирот»; п. 5.1.5: «включена в
 * навигацию»; задача Э4-08): каждая ИНДЕКСИРУЕМАЯ страница достижима за ≤ 4
 * перехода от главной по обычным `<a href>` из серверного HTML.
 *
 * Измеряется обходом (`support/crawl.ts`), а не рассуждением о шаблонах: ссылок в
 * базе нет, перелинковку собирает шаблон, и «запись опубликована» — это ещё не
 * «на неё есть ссылка». Правила подсчёта (ширина, минимальная глубина, редирект
 * переходом не считается, предел запросов) и все расхождения с обходом дашборда
 * `apps/cms/src/audit/link-audit.ts` — в шапке `support/crawl.ts`.
 *
 * ═══ ЧТО СЧИТАЕТСЯ «ОБЯЗАННЫМ БЫТЬ ДОСТИЖИМЫМ» ═══
 *
 * Норма говорит про ИНДЕКСИРУЕМЫЕ страницы, а не про все. Список таких страниц
 * собирается из ТРЁХ независимых источников — независимых намеренно, потому что
 * каждый по отдельности можно потерять:
 *
 *   1. **карта сайта** (`/sitemap.xml` → файлы → `<loc>`). По построению в неё
 *      входят только страницы, отвечающие 200, каноничные сами себе и открытые в
 *      индекс (`CLAUDE.md`, «Sitemap и robots»), то есть это и есть список, с
 *      которым к сайту приходит поисковая система. Источник внешний по отношению
 *      к обходу: страница, на которую нет ни одной ссылки, в обходе не встретится
 *      никогда — а в карте она есть, и именно так сирота и обнаруживается;
 *   2. **инвентарь приёмки** — записи, объявленные с директивой `index,…`
 *      (`support/declared-pages.ts`). Нужен потому, что карта сайта может
 *      оказаться пустой по своей собственной поломке, а не по отсутствию
 *      индексируемых страниц;
 *   3. **живые ответы обхода** — страницы, фактически отдающие `index,…`. Этот
 *      источник ловит случай, которого не видят первые два: страница открыта в
 *      индекс, но в карту не попала. Найти «сироту» он по определению не может
 *      (страница пришла из обхода, значит ссылка на неё есть), зато находит
 *      «глубже нормы».
 *
 * ═══ ПОЧЕМУ СЕЙЧАС ПРОВЕРЯТЬ НЕЧЕГО И ПОЧЕМУ ЭТО НЕ ПРОПУСК ═══
 *
 * Замер 2026-09-04: в `index,follow` не открыта НИ ОДНА страница сайта — ни одной
 * из 1021 карточки и 24 подборок базы стенда, ни один статический маршрут. Открытие в индекс
 * — решение человека (п. 7.1 и п. 23 ТЗ, условия п. 5.1), и его никто не
 * принимал: «подтверждённый спрос» данными не подтверждён (Ч-04-1). Значит все
 * три источника пусты, и множество «обязанных быть достижимыми» пусто тоже.
 *
 * Зелёный тест в этом состоянии НЕ означает «сирот нет» — он означает «сирот
 * искали не в чем». Разница между этими двумя утверждениями в проекте объявлена
 * дороже упавшего теста, поэтому пустой прогон помечается аннотацией «проверено
 * нечем» и строкой в stdout (`support/not-checked.ts`).
 *
 * Чтобы пустая аннотация не превратилась в удобную отписку, вместе с ней
 * УТВЕРЖДАЕТСЯ работоспособность самого инструмента: главная обязана ответить
 * 200, и обход обязан найти с неё больше одного адреса. Иначе сломанный обход
 * («ссылок не нашлось вовсе») выглядел бы точно так же, как честное «индексируемых
 * страниц пока нет».
 *
 * Полную силу проверка получает в день, когда человек откроет в индекс первую
 * страницу, — правок в этом файле для того не нужно: страница придёт из карты
 * сайта, из инвентаря или из живого ответа сама.
 *
 * ═══ ЧЕГО ЭТОТ SPEC НЕ ДЕЛАЕТ ═══
 *
 *   - не проверяет статусы всех встреченных ссылок. Битые внутренние ссылки —
 *     отдельная находка и предмет ежесуточной проверки Э5-03; смешивать их с
 *     достижимостью значило бы называть одно другим;
 *   - не требует, чтобы индексируемая страница была в карте сайта. Обратное
 *     направление («в карте только каноничные и открытые») проверяет
 *     `sitemap-entries-are-indexable.spec.ts`; прямое — «каждая открытая в
 *     индекс страница попала в карту» — требование другое, и spec’а под него в
 *     приёмке пока нет (записано в `README.md`);
 *   - не исправляет находок. Найденная сирота передаётся владельцу шаблона
 *     (`astro-web`), а не правится приёмкой.
 */

import { expect, test } from '@playwright/test';

import {
  CRAWL_MAX_REQUESTS,
  MAX_CLICKS_FROM_HOME,
  crawlFromHome,
  crawlKey,
  isIndexableDirective,
} from './support/crawl.js';
import { noteNotChecked } from './support/not-checked.js';
import { ACCEPTANCE_PAGES, isIndexable } from './support/pages.js';
import { readSitemapTree } from './support/sitemap-tree.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

test.describe('достижимость от главной', () => {
  /**
   * Свой бюджет времени: обход делает десятки запросов подряд, и в него же
   * попадает первый запуск chromium (карта сайта разбирается настоящим
   * `DOMParser`, `support/xml.ts`). Утверждения при этом ждут не дольше
   * `expect.timeout` из конфига — длинный таймаут здесь платит за запросы, а не
   * прячет медленный ответ.
   */
  test.describe.configure({ timeout: 300_000 });

  test('каждая индексируемая страница достижима за ≤ 4 перехода от главной', async ({
    browser,
    request,
  }, testInfo) => {
    const crawl = await crawlFromHome(request, target);
    const home = crawl.targets.get(crawl.start);

    expect(
      home?.status,
      `Главная ${crawl.start} обязана отвечать 200: обход начинается с неё, и без её ответа ` +
        'измерение достижимости смысла не имеет.',
    ).toBe(200);

    expect(
      crawl.targets.size,
      `С главной не нашлось ни одной внутренней ссылки <a href> (обойдено адресов: ` +
        `${String(crawl.targets.size)}). Либо навигация собирается скриптом (прямой запрет ` +
        'п. 23 ТЗ), либо сломан сам обход — и тогда любое «сирот не найдено» ниже было бы ' +
        'ложным.',
    ).toBeGreaterThan(1);

    const measuredDepth = Math.max(
      ...[...crawl.targets.values()]
        .filter((found) => found.status === 200)
        .map((found) => found.depth),
    );
    const stats =
      `обойдено адресов: ${String(crawl.targets.size)}, запросов: ` +
      `${String(crawl.requested)} из ${String(CRAWL_MAX_REQUESTS)}, максимальная измеренная ` +
      `глубина ответивших 200: ${String(measuredDepth)}` +
      (crawl.truncated ? ', обход ОБОРВАН пределом запросов' : '');

    /** Адрес → почему он обязан быть достижим. */
    const required = new Map<string, string>();

    const tree = await readSitemapTree(request, browser, target);
    for (const loc of tree.pageUrls) {
      const key = crawlKey(loc);
      if (key !== null) {
        required.set(key, `адрес входит в карту сайта (${loc})`);
      }
    }

    for (const page of ACCEPTANCE_PAGES.filter(isIndexable)) {
      required.set(
        urlFor(target, page.path),
        `инвентарь приёмки объявляет страницу как «${page.expectedRobots}» (${page.task})`,
      );
    }

    for (const found of crawl.targets.values()) {
      if (found.status === 200 && isIndexableDirective(found.robots)) {
        required.set(found.url, `страница фактически отдаёт «${found.robots ?? ''}»`);
      }
    }

    if (required.size === 0) {
      noteNotChecked(
        testInfo,
        'Отсутствие страниц-сирот НЕ проверено: индексируемых страниц на сайте ноль. Ни один ' +
          'из трёх источников не дал ни одного адреса — карта сайта пуста, инвентарь приёмки ' +
          'не объявляет ни одной страницы с «index,…», и ни один живой ответ такой директивы ' +
          'не отдаёт. Причина одна: открытие страницы в index,follow — решение человека (п. 7.1 ' +
          'и п. 23 ТЗ), и его пока никто не принимал (Ч-04-1 — спрос данными не подтверждён). ' +
          'Прогон прошёл ВХОЛОСТУЮ: зелёный статус означает «сирот искали не в чем», а не ' +
          `«сирот нет». Сам обход при этом работает — ${stats}. Полную силу проверка получает ` +
          'в день, когда человек откроет в индекс первую страницу; правок в spec для этого не ' +
          'нужно.',
      );
      return;
    }

    const orphans: string[] = [];
    const tooDeep: string[] = [];
    const notServed: string[] = [];
    const notMeasured: string[] = [];

    for (const [url, why] of required) {
      const found = crawl.targets.get(url);

      if (found === undefined) {
        (crawl.truncated ? notMeasured : orphans).push(
          `${url} — ни одной ссылки на этот адрес в обходе от главной не встретилось (${why})`,
        );
        continue;
      }
      if (found.status === null) {
        notMeasured.push(`${url} — адрес не спрошен: обход упёрся в предел (${why})`);
        continue;
      }
      if (found.status !== 200) {
        notServed.push(
          `${url} — отвечает ${String(found.status)}, а не 200 (${why}); ссылки на него есть: ` +
            `${found.referrers.length === 0 ? 'нет' : found.referrers.join(', ')}`,
        );
        continue;
      }
      if (found.depth > MAX_CLICKS_FROM_HOME) {
        tooDeep.push(
          `${url} — ${String(found.depth)} перехода от главной, норма ${String(MAX_CLICKS_FROM_HOME)} (${why}); ` +
            `ближайшие ссылки: ${found.referrers.join(', ')}`,
        );
      }
    }

    console.log(
      `[обход достижимости] ${stats}; адресов, обязанных быть достижимыми: ` +
        `${String(required.size)}.`,
    );

    expect(
      notServed,
      'Адрес, объявленный индексируемым (или входящий в карту сайта), обязан отвечать 200. ' +
        'Пока он отвечает иначе, разговор о его достижимости беспредметен — и правится это не ' +
        'перелинковкой, а публикацией, редиректом или удалением адреса из карты.',
    ).toEqual([]);

    expect(
      orphans,
      'СТРАНИЦА-СИРОТА: индексируемая страница, на которую от главной не ведёт ни одна ссылка ' +
        '<a href>. Требование п. 22 и п. 5.1.5 нарушено: краулер до такой страницы доходит ' +
        'только из карты сайта, а посетитель — никогда. Исправляет владелец шаблона ' +
        '(`astro-web`) блоками перелинковки и навигацией, а не приёмка.',
    ).toEqual([]);

    expect(
      tooDeep,
      `Индексируемая страница обязана быть достижима за ≤ ${String(MAX_CLICKS_FROM_HOME)} ` +
        'переходов от главной. Путь длиннее означает, что достижимость держится на цепочке ' +
        'списков вместо прямых ссылок из меню и с главной на праздничные узлы (следствие ' +
        'Ч-04-5) или на серверных блоках перелинковки карточки (Ч-04-8). Напомним правило ' +
        'подсчёта: редирект переходом не считается, адреса с параметрами в обход не берутся ' +
        '(разбор — в шапке support/crawl.ts).',
    ).toEqual([]);

    if (notMeasured.length > 0) {
      noteNotChecked(
        testInfo,
        `Достижимость ${String(notMeasured.length)} адресов НЕ измерена: обход оборван ` +
          `пределом в ${String(CRAWL_MAX_REQUESTS)} запросов, и «ссылок не найдено» при ` +
          'недообойдённом сайте не означает ничего. Адреса: ' +
          `${notMeasured.join('; ')}. Предел поднимается в support/crawl.ts осознанно — он ` +
          'ограничивает время обязательного шлюза `pnpm verify`.',
      );
    }
    if (crawl.truncated && notMeasured.length === 0) {
      noteNotChecked(
        testInfo,
        `Обход оборван пределом в ${String(CRAWL_MAX_REQUESTS)} запросов, но все ` +
          `${String(required.size)} адресов, обязанных быть достижимыми, найдены в пределах ` +
          'нормы. Утверждение о НИХ верно (найденный путь короче нормы остаётся путём); не ' +
          'измерена глубина остальных страниц сайта.',
      );
    }
  });
});
