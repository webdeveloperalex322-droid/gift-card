/**
 * Требование: страница, ОБЪЯВЛЕННАЯ в выборке приёмки (п. 22 ТЗ), но не
 * отдаваемая стендом, обязана быть НАЗВАНА в отчёте — и её отсутствие обязано
 * выглядеть как законный 404, а не как что угодно.
 *
 * Это обратная сторона расширения выборки на контентные страницы (Э4-07). Адрес
 * такой страницы гарантирован репозиторием, а существование — решением человека
 * о публикации (разбор в шапке `support/declared-pages.ts`), поэтому на стенде с
 * пустой или частично наполненной базой часть выборки законно отсутствует. Два
 * способа отчитаться об этом были бы ошибкой:
 *
 *   - молча выкинуть страницу из выборки. Тогда `pnpm verify` зелёный и НИГДЕ не
 *     сказано, что карточка, подборка и пагинация не проверялись. Это ровно тот
 *     ложный зелёный, из-за которого в этом проекте запрещено выдавать `SKIPPED`
 *     за `PASSED`;
 *   - объявить отсутствие нормой (`test.skip`). Пропуск не показывает ни того,
 *     ЧТО не проверено, ни того, что нужно сделать, чтобы проверилось.
 *
 * Поэтому здесь на каждую отсутствующую страницу порождается ОТДЕЛЬНЫЙ тест. Он
 * делает две разные вещи, и обе обязательны:
 *
 *   1. УТВЕРЖДАЕТ, что адрес отвечает ровно 404 без `Location`. Неопубликованная
 *      запись и пустая подборка отвечают именно так (ТЗ §5.3, таблица
 *      «HTTP-статусы»). Ответ 500 — дефект рендера, 301 — редирект на
 *      каноническом адресе, 200 — страница есть, и тогда её надо проверять
 *      целиком, а не считать отсутствующей. Ни один из этих случаев не имеет
 *      права выглядеть как «контента пока нет»;
 *   2. ставит аннотацию «проверено нечем» с перечислением требований, которые
 *      из-за отсутствия страницы остались непроверенными, и с текстом
 *      `appearsWhen` — что должно случиться, чтобы страница появилась. Механика
 *      пометки (аннотация плюс строка в stdout) — в `support/not-checked.ts`.
 *
 * Когда объявленных, но отсутствующих страниц нет, файл не порождает ни одного
 * теста: полнота выборки в этом случае проверена, и отдельного «всё хорошо» здесь
 * не нужно — состав выборки проверяет
 * `acceptance-sample-covers-checklist.spec.ts`.
 */

import { expect, test } from '@playwright/test';

import { ABSENT_STATUS } from './support/discovery.js';
import { fetchRaw } from './support/http.js';
import { noteNotChecked } from './support/not-checked.js';
import { ABSENT_ACCEPTANCE_PAGES } from './support/pages.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/**
 * Что теряется вместе со страницей.
 *
 * Список общий на все виды страниц намеренно: это и есть набор инвариантных
 * проверок, который идёт по инвентарю. Перечислять его для каждой страницы
 * отдельно значило бы держать две копии одного факта.
 */
const UNCHECKED_ON_ABSENT_PAGE = [
  'ровно один непустой H1',
  'абсолютный self-canonical, в том числе при параметрах',
  'директива робота из допустимого набора',
  'уникальность title/H1/description на выборке',
  'внутренние ссылки — только <a href>',
  'полноценный ответ без JS (в том числе в браузере с отключённым JS)',
  'отсутствие исполняемого клиентского JS',
  'контракт изображений: src, width, height, alt, ровно одно неленивое',
  'соответствие структурированных данных видимому содержимому',
  'независимость статуса и canonical от параметров',
  'отсутствие .html-двойника и формы со слешем',
  'постоянная навигация и боковое меню категорий в HTML',
].join('; ');

for (const absent of ABSENT_ACCEPTANCE_PAGES) {
  const { page } = absent;

  test(`объявленная страница не отдаётся: ${page.path} (${page.sampleRole})`, async ({
    request,
  }, testInfo) => {
    const response = await fetchRaw(request, urlFor(target, page.path));

    expect(
      response.status,
      `Объявленная страница ${page.path} (${page.sampleRole}, ${page.task}) не отдаётся, и это ` +
        'законно только в одной форме — 404. Получено ' +
        `${String(response.status)}${response.location === null ? '' : ` Location: ${response.location}`}.\n` +
        '  200 означает, что страница ЕСТЬ: значит замер присутствия разошёлся с ответом ' +
        'сервера, и страницу надо проверять целиком, а не считать отсутствующей.\n' +
        '  3xx на каноническом адресе — нарушение само по себе: канонический адрес не ' +
        'редиректит (решение Ч-21).\n' +
        '  5xx — дефект рендера, а не «контента пока нет».',
    ).toBe(ABSENT_STATUS);

    expect(
      response.location,
      `У ответа 404 на ${page.path} не должно быть заголовка Location: перевод робота с ` +
        'адреса неопубликованной записи куда бы то ни было — это скрытый редирект, а ' +
        'массовый редирект удалённых страниц запрещён прямым пунктом 23 ТЗ.',
    ).toBeNull();

    noteNotChecked(
      testInfo,
      `Вид страницы «${page.sampleRole}» (${page.path}, ${page.task}) в этом прогоне НЕ ` +
        `проверен: адрес отвечает 404. Появится, когда ${page.appearsWhen ?? '—'}. ` +
        `Из-за отсутствия страницы не проверены: ${UNCHECKED_ON_ABSENT_PAGE}. ` +
        'Зелёный статус этого теста означает «отсутствие законно и названо», а не ' +
        '«требования п. 22 на этой странице выполнены». Полную силу проверки получают в день, ' +
        'когда человек опубликует запись; правок в specs для этого не нужно.',
    );
  });
}
