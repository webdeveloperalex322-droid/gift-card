/**
 * Пометка «проверено нечем»: тест зелёный, но проверять ему было нечего.
 *
 * Такое состояние в этом проекте законно — сайт наполняется, и часть материала
 * появится только с первой опубликованной записью и первой страницей, открытой в
 * `index,follow`. Незаконно другое: чтобы зелёный статус читался как покрытие.
 * Поэтому пустой прогон обязан быть ВИДЕН, и делается это двумя действиями:
 *
 *   1. аннотация в `testInfo` — структурированная пометка, уезжает в отчёт
 *      Playwright и в трассировку;
 *   2. строка в stdout теста. Замерено 2026-08-28: репортёр `list` —
 *      единственный включённый в `playwright.config.ts` — аннотации ПРОШЕДШИХ
 *      тестов не печатает. Одна только аннотация была бы видна лишь тому, кто
 *      откроет отчёт, то есть почти никому: статус переносят из вывода
 *      `pnpm test:seo`. Пометка, которой не видно там, — та же ошибка
 *      отчётности, что и `SKIPPED`, выданный за `PASSED`.
 *
 * Заменой утверждения это не является и являться не должно: тест, которому
 * нечего проверять, ставит пометку и ЗАВЕРШАЕТСЯ, а не пропускает проверку,
 * которую мог бы выполнить. Каждое место, где пометка ставится, названо в
 * таблице «Чего приёмка пока НЕ проверяет» в `tests/seo/README.md`.
 */

/** Тип аннотации. Одно значение на всю приёмку — по нему отчёт и ищется. */
export const NOT_CHECKED_ANNOTATION = 'проверено нечем';

/** Минимум от `TestInfo`, который нужен пометке. Полный тип здесь избыточен. */
export interface AnnotatableTestInfo {
  readonly annotations: { type: string; description?: string }[];
}

export function noteNotChecked(testInfo: AnnotatableTestInfo, description: string): void {
  testInfo.annotations.push({ description, type: NOT_CHECKED_ANNOTATION });
  console.log(`[${NOT_CHECKED_ANNOTATION}] ${description}`);
}
