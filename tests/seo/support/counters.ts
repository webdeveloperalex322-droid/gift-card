/**
 * Область кода сторонних счётчиков в ответе сервера (решение Ч-36).
 *
 * ЧТО ЭТО ЗА ПОСЛАБЛЕНИЕ. Инвариант проекта — ноль клиентского JS по умолчанию,
 * и приёмка (`../no-client-javascript.spec.ts`) падает на любом исполняемом
 * `<script>`. Код счётчика вставляет человек в настройках сайта, и это
 * произвольный HTML: по содержимому скрипта узнать его «свой или чужой» нельзя.
 * Поэтому послабление сделано по МЕСТУ: шаблон обводит код комментариями-
 * маркерами, и исполняемый `<script>` допустим РОВНО между ними. Общего
 * «скрипты разрешены» не появляется.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЛОКАЛЬНАЯ ФУНКЦИЯ SPEC'А. Это единственное
 * послабление приёмки за всё время проекта, то есть единственный код, ошибка в
 * котором не делает тесты красными, а делает их НЕПРАВДИВЫМИ: расширься область
 * на один байт — и запрещённый скрипт проедет как разрешённый. Такой код обязан
 * иметь собственный контракт, проверяемый на синтетическом HTML
 * (`../counters-region-contract.spec.ts`), а не только на живом ответе: на
 * живом ответе области нет вовсе, пока человек не включил счётчик, то есть
 * обычный прогон `pnpm test:seo` эту ветку не исполняет НИ РАЗУ.
 *
 * МАРКЕРЫ ЗАДАНЫ ЗДЕСЬ СТРОКАМИ, а не импортированы из `@otkritka/shared`. Это
 * то же правило, по которому приёмка не импортирует `isPageRoute` (см.
 * `crawl.ts`): переименуй продукт маркер — и приёмка, импортировав новое
 * значение, приняла бы перемену АВТОМАТИЧЕСКИ, без строки в дифе. Расхождение
 * при копии безопасно в нужную сторону: области в ответе не найдётся, и
 * послабление просто исчезнет, то есть приёмка станет строже, а не слабее.
 */
import type { ScriptTag } from './html.js';

/** Копия продуктовых маркеров — почему копия, а не импорт, сказано в шапке. */
export const COUNTERS_START = '<!-- site-counters:start -->';
export const COUNTERS_END = '<!-- site-counters:end -->';

/**
 * `type` структурированных данных: это НЕ клиентский JS.
 *
 * Значение одно на модуль и на spec, потому что от него зависит и отбор, и текст
 * сообщения о нарушении: два литерала однажды разошлись бы, и сообщение называло
 * бы не то исключение, которое применено.
 */
export const STRUCTURED_DATA_TYPE = 'application/ld+json';

/**
 * Что найдено в ответе.
 *
 *   - `absent` — маркеров нет вовсе. Это НОРМАЛЬНОЕ состояние: счётчик не
 *     включён, послаблений на странице нет, требование действует в полную силу;
 *   - `region` — ровно одна пара маркеров в правильном порядке;
 *   - `malformed` — форма области нарушена. Отдельное состояние, а не «считаем,
 *     что области нет»: вторая пара маркеров означает, что маркер попал в сам
 *     код счётчика (запрещено валидацией поля `validateSiteCountersCode`), то
 *     есть границу послабления задаёт содержимое поля, а запрет на вводе обойдён.
 *     Молча ужесточиться здесь нельзя — об этом обязан узнать человек.
 */
export type CountersRegion =
  | { readonly kind: 'absent' }
  | { readonly kind: 'region'; readonly from: number; readonly to: number }
  | { readonly kind: 'malformed'; readonly reason: string };

function occurrences(html: string, marker: string): number {
  let count = 0;
  let at = html.indexOf(marker);
  while (at !== -1) {
    count += 1;
    at = html.indexOf(marker, at + marker.length);
  }
  return count;
}

/** Границы области счётчиков в ответе. Разбор формы — см. {@link CountersRegion}. */
export function countersRegion(html: string): CountersRegion {
  const starts = occurrences(html, COUNTERS_START);
  const ends = occurrences(html, COUNTERS_END);

  if (starts === 0 && ends === 0) {
    return { kind: 'absent' };
  }
  if (starts !== 1 || ends !== 1) {
    return {
      kind: 'malformed',
      reason:
        `открывающих маркеров ${String(starts)}, закрывающих ${String(ends)}, а область ` +
        'обводится РОВНО одной парой. Иное означает, что маркер попал в сам код счётчика, ' +
        'то есть границу послабления задаёт содержимое поля.',
    };
  }

  const from = html.indexOf(COUNTERS_START);
  const to = html.indexOf(COUNTERS_END);
  if (to < from) {
    return {
      kind: 'malformed',
      reason: 'закрывающий маркер стоит ПЕРЕД открывающим: такая «область» не ограничена ничем.',
    };
  }

  return { from, kind: 'region', to };
}

/**
 * Исполняемые скрипты ответа, которым послабление Ч-36 НЕ помогает.
 *
 * Разрешённым считается скрипт, открывающий тег которого физически стоит внутри
 * области — по смещению из {@link ScriptTag.at}, а не по совпадению текста тега
 * (почему именно так, сказано там же). Структурированные данные
 * (`application/ld+json`) исполняемым JS не являются и отсеиваются до области:
 * они обязательны по ТЗ и разрешены везде.
 */
export function executableScriptsOutsideCounters(
  scripts: readonly ScriptTag[],
  region: CountersRegion,
): readonly ScriptTag[] {
  return scripts.filter((script) => {
    if (script.type === STRUCTURED_DATA_TYPE) {
      return false;
    }
    if (region.kind !== 'region') {
      // Области нет (или её форма нарушена) — послабления не существует.
      return true;
    }
    return script.at < region.from || script.at > region.to;
  });
}
