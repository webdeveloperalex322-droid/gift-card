/**
 * ОБЪЯВЛЕННАЯ выборка приёмки: состав п. 22 ТЗ и ожидаемые факты о каждой
 * странице — директива робота, состав изображений, вид структурированных данных,
 * наличие `<meta name="description">`.
 *
 * Файл статический: ни одного запроса, ни одного чтения окружения. Присутствие
 * страницы на стенде выясняет `./discovery.ts`, а «представление выборки с
 * учётом присутствия» собирает `./pages.ts` — специи импортируют по-прежнему
 * оттуда. Разделение на два файла не косметика: `./pages.ts` читает результат
 * замера, а замер делает `../global-setup.ts` ДО загрузки spec-файлов; импортируй
 * global-setup сразу `./pages.ts`, модуль вычислился бы в момент, когда замера
 * ещё нет, и остался бы в кеше процесса уже неверным.
 *
 * ═══ ГЛАВНОЕ ПРАВИЛО ФАЙЛА: адрес обязан быть гарантирован РЕПОЗИТОРИЕМ ═══
 *
 * Прежняя формулировка правила была уже: «сюда попадает только то, что
 * гарантирует КОД», то есть маршрут Astro со своим текстом. Она отсекала
 * карточку, подборки, каталог и пагинацию — их страница существует только у
 * ОПУБЛИКОВАННОЙ записи, а запись лежит в базе, которой в репозитории нет.
 * Правило защищало от настоящей беды: инвентарь, зависящий от содержимого чьей-то
 * базы, красит `pnpm verify` у того, у кого база пуста, и зеленит у того, кто
 * вчера гонял смоук.
 *
 * Расширение правила (задача Э4-07) сохраняет ту же защиту и снимает цену.
 * Различаются ДВА разных утверждения, которые прежняя формулировка держала за
 * одно:
 *
 *   1. **адрес** страницы — что он такой и не другой. Для контентных страниц он
 *      гарантирован репозиторием ровно так же, как маршрут: пути подборок и
 *      slug’и открыток эталонной выборки Ч-06 лежат в
 *      `content/pilot-2026-08/site-content.json` — файл в репозитории, из него
 *      же импортируется каталог (`apps/cms/scripts/import-pilot-content.ts`).
 *      Приёмка не выдумывает адреса и не подбирает их обходом сайта: она берёт
 *      объявленные;
 *   2. **существование** страницы по этому адресу — факт о базе. Он от
 *      репозитория не зависит и зависеть не может: публикация — решение человека
 *      (п. 7.1 и п. 23 ТЗ), и на чистой базе те же адреса законно отвечают 404
 *      (пустая подборка не отдаёт 200, ТЗ §5.3).
 *
 * Отсюда поле {@link AcceptancePage.availability} и обещание, которое даёт
 * приёмка вместо прежнего умолчания:
 *
 *   - страница, которая ОТДАЁТ 200, проверяется ПОЛНОСТЬЮ — тем же набором
 *     инвариантных specs, что и маршруты. Ни одного ослабленного утверждения для
 *     контентных страниц не заведено;
 *   - страница, которой на стенде нет, даёт ВИДИМУЮ аннотацию «проверено нечем»
 *     (`declared-page-not-served.spec.ts`) с перечислением того, что осталось
 *     непроверенным, и с указанием, что должно случиться, чтобы страница
 *     появилась ({@link AcceptancePage.appearsWhen}). Молчаливого зелёного здесь
 *     нет: тем же spec’ом проверяется, что отсутствие выглядит именно как 404, а
 *     не как 500, 301 или пустой 200;
 *   - `pnpm verify` на пустой базе остаётся зелёным, но ЧЕСТНЫМ: в выводе
 *     перечислено, чего он не проверил.
 *
 * Механизм замера присутствия — `./discovery.ts`; почему выбран он, а не
 * фикстуры и не подбор адресов обходом, — там же.
 *
 * ═══ ПРО ПОЛЕ `expectedRobots` ═══
 *
 * Оно фиксирует, что страница отдаёт СЕЙЧАС, и охраняет границу: перевод
 * страницы в `index,follow` — решение человека (п. 7.1 и п. 23 ТЗ), а не побочный
 * эффект правки шаблона. Если рефакторинг layout молча откроет страницу в индекс,
 * `robots-directive-present.spec.ts` упадёт. Обратная сторона: когда человек
 * ОСОЗНАННО открывает страницу, он правит и эту строку — то есть решение видно в
 * дифе. Аудитор значения здесь не «повышает»: смена `noindex` на `index` в этом
 * файле без решения человека — нарушение границ агента `seo-auditor`.
 *
 * Замер 2026-10-02, после ПОЛНОЙ публикации карточек (решение Ч-35, поверх
 * волны 1 — Ч-34): в `index,follow` открыты ШЕСТЬ подборок — праздничные
 * посадочные `8-marta`, `23-fevralya`, `9-maya`, `14-fevralya`, `novyy-god`,
 * `den-rozhdeniya`. Карточки: 0 `review` + 135 `draft` + 1098 `published`,
 * директива `noindex,follow` у всех 1233 — в индекс карточки не открывались ни
 * волной 1, ни полной публикацией. Подборки: 20 `review` + 11 `published`, из
 * опубликованных 6 в `index,follow` и 5 в `noindex,follow`. Оставшиеся 135
 * черновиков заблокированы хуком визуальных дублей: pHash нашёл похожие
 * изображения (расстояние 10–14 при пороге Ч-08 = 14), и вход в `review`
 * требует явного решения редактора, которого человек не принимал.
 *
 * Предыдущий замер 2026-09-04 (до волны 1): в `index,follow` не открыта ни одна
 * страница, 1021 карточка и 24 подборки целиком `noindex,follow`. Записей
 * харнесса API в контентной базе НОЛЬ (проверено: `slug LIKE 'e602%'` — ноль
 * карточек и ноль подборок): решением человека харнесс переведён на отдельную
 * базу `otkritka_api_tests`, а его следы из контентной вычищены. До этого 4
 * опубликованные фикстуры лежали в каталоге и попадали в сетку — то есть числа
 * приёмки зависели от того, гоняли ли API-тесты; теперь не зависят.
 */

/**
 * Директивы, допустимые в `<meta name="robots">` на этом сайте.
 *
 * ## Почему это копия набора и почему она копией остаётся
 *
 * С задач Э4-05 и Э4-06 набор живёт в `@otkritka/shared`
 * (`ROBOTS_DIRECTIVES`) в единственном экземпляре: `apps/cms` строит из него
 * поле записи, `apps/web` — проверку директивы и отбор в sitemap, своих списков
 * ни у того, ни у другого больше нет. Внутри ПРОДУКТА это правильно: две копии
 * расходятся молча. Приёмка — случай другой, и переход на общий импорт здесь
 * рассмотрен и ОТКЛОНЁН.
 *
 * Довод один, но решающий: приёмка не имеет права брать эталон из кода, который
 * проверяет. Импортируй она `ROBOTS_DIRECTIVES`, добавление в общий набор нового
 * значения — скажем, `index,nofollow` — приёмка приняла бы АВТОМАТИЧЕСКИ:
 * страница, начавшая его отдавать, прошла бы `robots-directive-present.spec.ts`
 * без единого падения и без строки в дифе приёмки. Директива управляет
 * попаданием страницы в индекс, расширять набор без решения человека нельзя
 * (шапка `packages/shared/src/robots.ts` говорит это прямо), — а молчаливое
 * согласие приёмки как раз и превратило бы правку кода в такое решение.
 *
 * Расхождение при этом не остаётся незамеченным, и направление у него безопасное:
 *
 *   - значение ДОБАВИЛИ в общий набор и страница его отдала — приёмка падает с
 *     «значение не входит в список допустимых директив проекта». Это и нужно:
 *     человек видит новое значение и решает, законно ли оно;
 *   - значение УБРАЛИ из общего набора — приёмка остаётся строже кода. Ложного
 *     зелёного не возникает: страница такого значения уже не печатает, а
 *     проверять по списку, в котором лишняя строка, безопасно.
 *
 * То есть копия здесь самосторожащая, тогда как импорт снял бы сторожа. Тождество
 * наборов внутри продукта проверяет `tests/unit/robots.test.ts` — там оно и
 * должно проверяться.
 */
export const ALLOWED_ROBOTS_DIRECTIVES = [
  'index,follow',
  'noindex,follow',
  'noindex,nofollow',
] as const;

export type RobotsDirective = (typeof ALLOWED_ROBOTS_DIRECTIVES)[number];

/**
 * Что страница обязана содержать по части изображений.
 *
 * Поле объявляется в инвентаре, а не выводится из ответа, по той же причине, что
 * и {@link AcceptancePage.expectedRobots}: проверка «у всех `<img>` есть
 * `width`, `height`, `alt`, и ровно одно изображение не ленивое» на странице БЕЗ
 * изображений выполняется тривиально, то есть spec выглядел бы работающим,
 * ничего не проверяя. Объявление разделяет три состояния:
 *
 *   - `none` — изображений на странице нет НИ ПРИ КАКОМ состоянии базы, и это
 *     утверждение проверяется: появление `<img>` валит spec с требованием
 *     объявить страницу заново. Молчаливо получить непроверенную картинку на
 *     первом экране нельзя;
 *   - `primary` — есть первое крупное изображение (LCP-кандидат) плюс, возможно,
 *     ленивые. Тогда работает весь контракт раздела «Изображения»;
 *   - `data-driven` — состав изображений определяют ОПУБЛИКОВАННЫЕ ЗАПИСИ, а не
 *     маршрут. Так устроена главная: блок свежих открыток печатается, только
 *     если открытки есть. Это НЕ поблажка: при непустой сетке работает весь
 *     контракт `primary`, а при пустой проверяется, что и сетки на странице нет
 *     — плитки без `<img>` (изображение потерялось на рендере) валят spec.
 *     Состояние «нет ни сетки, ни изображений» законно только на пустой базе, и
 *     spec помечает такой прогон аннотацией, чтобы это было видно в отчёте.
 *
 * Контентные страницы объявляются `primary`, а не `data-driven`: их существование
 * УЖЕ означает непустую выборку — подборка без открыток отвечает 404, а не
 * пустым 200 (ТЗ §5.3). Единственное исключение — группирующий узел таксономии
 * (`/otkrytki/prazdniki`): он печатает список дочерних узлов без превью, поэтому
 * объявлен `none`, и появление изображений на нём валит spec с требованием
 * объявить страницу заново (замер 2026-09-03: ноль `<img>`).
 */
export type ImageExpectation = 'none' | 'primary' | 'data-driven';

/**
 * Какой вид структурированных данных (`application/ld+json`) страница отдаёт.
 *
 * Три состояния, и каждое проверяется УТВЕРЖДЕНИЕМ, а не пропуском:
 *
 *   - `none` — разметки нет вовсе; появление блока валит spec, иначе разметка,
 *     приехавшая с правкой layout, осталась бы непроверенной;
 *   - `site` — документ описывает САЙТ, а не список: узел `WebSite` (ТЗ §5.2 —
 *     «JSON-LD: WebSite + Organization»), при заполненном глобале рядом
 *     `Organization` (Ч-17). Элементов списка (`ListItem`) на такой странице нет
 *     и быть не должно: крошек у главной нет по ТЗ §7.6, а `ItemList` §5.2 от
 *     главной не требует;
 *   - `list` — документ описывает ВИДИМЫЙ СПИСОК: `BreadcrumbList` у любой
 *     страницы глубже главной (ТЗ §7.6) и/или `ItemList` подборки и каталога
 *     (ТЗ §5.3). Тогда включается сверка каждого `ListItem` с видимым текстом и
 *     ссылками страницы.
 *
 * ## Почему появилось третье состояние, а не «ListItem обязателен, когда в
 * документе есть WebPage/CollectionPage»
 *
 * Оба варианта лечат одно падение: главная (Э3-09) отдаёт `WebSite`, а инвентарь
 * объявлял `/` как `none`. Выбран третий вид объявления, потому что условие
 * «обязателен, когда есть WebPage» ослабляет проверку молча. При нём страница,
 * у которой разметка деградировала до одного `WebSite` (например, у подборки
 * пропали и крошки, и `ItemList`), проходила бы приёмку: узла `WebPage` в
 * документе нет — значит `ListItem` и не требуется. Объявление же говорит, чего
 * от страницы ЖДУТ, и любое расхождение с ожиданием — падение с требованием
 * объявить страницу заново. Ровно этим свойством ценно и состояние `none`.
 *
 * Второе, менее очевидное: `site` не просто «не требует списка», а ЗАПРЕЩАЕТ
 * `ListItem`. Появление крошек на главной — расхождение с ТЗ §7.6, а появление
 * `ItemList` — разметка, которой ТЗ не просит; и то и другое обязано быть
 * замеченным, а не молча принятым.
 */
export type StructuredDataExpectation = 'none' | 'site' | 'list';

/**
 * Есть ли на странице `<meta name="description">`.
 *
 * Поле пришлось объявить, когда в инвентарь вошли информационные страницы
 * (Э3-11). У них description ПУСТ, потому что текст берётся из глобала настроек,
 * а глобал — заглушка (Ч-19), и правило проекта «пустое поле — значит тега нет
 * вовсе» (Ч-10, Ч-17, шапка `BaseLayout.astro`) убирает тег целиком.
 *
 * Дальше было ровно два честных выхода, и подгонка теста не входила ни в один:
 *
 *   1. требовать непустой description на каждой странице выборки. Тогда
 *      приёмка требовала бы, чтобы АГЕНТ придумал описание страницы «Условия
 *      использования» вместо человека, — то есть шаблонный SEO-текст, прямой
 *      запрет п. 23.4 и обход Ч-19;
 *   2. объявить факт «тега нет» и проверять его утверждением — как у
 *      `images: 'none'`. Выбрано это.
 *
 * `absent` держит проверку в обе стороны: description, появившийся у страницы,
 * валит spec (значит человек заполнил глобал — факт надо объявить заново), а
 * страница, объявленная `absent` и при этом ИНДЕКСИРУЕМАЯ, валит spec всегда: у
 * индексируемой страницы description обязателен (п. 22.1). То есть в момент,
 * когда человек по Ч-23 откроет `/o-proekte` в `index,follow`, приёмка потребует
 * заполненного описания — а не промолчит.
 *
 * У страниц пагинации (`/otkrytki/page/N`) тега нет тоже, и по той же механике:
 * `metaDescription` записи описывает ПЕРВУЮ страницу списка, а страницам 2+
 * шаблон описания не собирает — собирать его по шаблону запрещено п. 23.4.
 * Страница пагинации `noindex,follow` (Ч-05), поэтому обязательности description
 * для неё не возникает.
 */
export type DescriptionExpectation = 'present' | 'absent';

/**
 * Чем гарантирован АДРЕС страницы и от чего зависит её существование.
 *
 *   - `route` — маршрут Astro со своим текстом: отвечает 200 при любом состоянии
 *     базы. Отсутствие такой страницы — дефект кода, и специи падают на нём
 *     сразу (`expect(status).toBe(200)`), никакой пометки «проверено нечем» для
 *     них не предусмотрено;
 *   - `content` — страница опубликованной записи. Адрес объявлен здесь и взят из
 *     `content/pilot-2026-08/site-content.json`, существование зависит от решения
 *     человека о публикации. Отсутствие — законное состояние стенда, но НЕ
 *     молчаливое: см. {@link AcceptancePage.appearsWhen} и
 *     `declared-page-not-served.spec.ts`.
 */
export type PageAvailability = 'route' | 'content';

export interface AcceptancePage {
  /**
   * Канонический путь страницы: без завершающего слеша (решение Ч-21),
   * единственное исключение — корень `/`.
   */
  readonly path: string;
  /** Чем гарантирован адрес: маршрутом кода или опубликованной записью. */
  readonly availability: PageAvailability;
  /**
   * Требование п. 22, ради которого страница входит в выборку («главная»,
   * «раздел», «праздничная посадочная», …).
   *
   * Поле не декоративное: `acceptance-sample-covers-checklist.spec.ts`
   * проверяет по нему, что в выборке ОБЪЯВЛЕН каждый вид страницы из п. 22 ТЗ.
   * Без него удаление страницы из инвентаря выглядело бы как уменьшение числа
   * тестов, а не как сужение приёмки.
   */
  readonly sampleRole: string;
  /**
   * Что должно произойти, чтобы страница появилась на стенде; `null` у
   * маршрутов кода — они есть всегда.
   *
   * Текст уходит в аннотацию «проверено нечем», поэтому он адресный: читающий
   * отчёт видит не «страницы нет», а «человек ещё не опубликовал такую-то
   * запись».
   */
  readonly appearsWhen: string | null;
  /** Ожидаемое значение `<meta name="robots">`. */
  readonly expectedRobots: RobotsDirective;
  /** Ожидаемый состав изображений. */
  readonly images: ImageExpectation;
  /** Ожидаемый вид структурированных данных. */
  readonly structuredData: StructuredDataExpectation;
  /** Ожидаемое наличие `<meta name="description">`. */
  readonly description: DescriptionExpectation;
  /** Задача, которой страница принадлежит, — чтобы падение указывало на владельца. */
  readonly task: string;
  /** Зачем страница существует и что на ней проверяется. */
  readonly note: string;
}

