/**
 * Боковое меню категорий открыток в ответе сервера.
 *
 * Меню появилось вместе с левым рельсом (`apps/web/src/components/SiteSidebar.astro`)
 * и печатается layout'ом на каждой странице, кроме 404. Для приёмки это НОВЫЙ
 * источник внутренних ссылок на каждой странице сайта, и требования к нему те же,
 * что к любой постоянной навигации (п. 5.1 «включена в навигацию», п. 22 «нет
 * страниц-сирот», «внутренние ссылки — `<a href>`»): один и тот же состав везде,
 * каждая ссылка ведёт на страницу, отвечающую 200 без перехода.
 *
 * ## Как меню опознаётся и почему именно так
 *
 * По ДОСТУПНОМУ ИМЕНИ ориентира — `<nav aria-label="Категории открыток">`, — а не
 * по классу CSS. Класс — деталь оформления, он меняется при любой перекраске и
 * ничего не обещает посетителю; доступное имя ориентира читает скринридер, то
 * есть это часть контракта страницы, а не её стилей.
 *
 * Совпадение строки здесь ЖЁСТКОЕ и это осознанно. Переименование ориентира валит
 * оба spec'а с сообщением «меню не найдено», и правка приёмки становится
 * обязательной частью такого переименования. Мягкое опознание (любой `<nav>` с
 * подстрокой «категор») выглядело бы устойчивее, а на деле означало бы, что
 * приёмка сама решает, какой из ориентиров считать меню, — и молча перестала бы
 * проверять его в тот день, когда рядом появится второй похожий блок.
 *
 * Отсутствие меню — законное состояние и НЕ ошибка разбора: на пустой таксономии
 * компонент не печатает ничего (показывать нечего). Поэтому здесь возвращается
 * `null`, а решение, что с этим делать, принимает spec: он ставит пометку
 * «проверено нечем», а не проходит молча.
 */

import { anchorLinks, attributeValue, openingTags, type AnchorLink } from './html.js';

/**
 * Доступное имя ориентира бокового меню. Задано в
 * `apps/web/src/components/SiteSidebar.astro` (`aria-label`).
 */
export const CATEGORY_MENU_LABEL = 'Категории открыток';

/**
 * Ссылки бокового меню в порядке их следования в ответе.
 *
 * @returns `null` — ориентира в ответе нет вовсе (пустая таксономия либо страница
 *   без рельса, как 404). Пустой массив — ориентир есть, а ссылок в нём нет; это
 *   уже дефект, и spec обязан его назвать.
 */
export function categoryMenuLinks(html: string): readonly AnchorLink[] | null {
  const opening = openingTags(html, 'nav').find(
    (tag) => attributeValue(tag, 'aria-label') === CATEGORY_MENU_LABEL,
  );
  if (opening === undefined) {
    return null;
  }

  const start = html.indexOf(opening);
  const bodyStart = start + opening.length;
  // Вложенного `<nav>` внутри меню нет и быть не может: ориентир навигации внутри
  // ориентира навигации — дефект разметки сам по себе. Поэтому конец области —
  // первый же `</nav>`, и при появлении вложенности область окажется КОРОЧЕ
  // настоящей, то есть проверка ослабнет в сторону пропуска ссылок, а не выдумки.
  const end = html.indexOf('</nav>', bodyStart);
  const region = end === -1 ? html.slice(bodyStart) : html.slice(bodyStart, end);

  return anchorLinks(region);
}

/** Ссылки меню как список адресов; `null` — меню нет. */
export function categoryMenuHrefs(html: string): readonly (string | null)[] | null {
  return categoryMenuLinks(html)?.map((link) => link.href) ?? null;
}
