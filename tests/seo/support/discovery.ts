/**
 * Замер присутствия объявленных страниц: какие из адресов
 * {@link DECLARED_ACCEPTANCE_PAGES} стенд отдаёт в ЭТОМ прогоне.
 *
 * Нужен ровно для того, чтобы приёмка могла проверять контентные страницы
 * (карточку, подборки, каталог, пагинацию) ПОЛНОСТЬЮ там, где они есть, и честно
 * говорить «проверено нечем» там, где их нет, — не завися при этом от того, что
 * лежит в чьей-то базе. Разбор самого разделения «адрес гарантирован
 * репозиторием / существование зависит от решения человека» — в шапке
 * `./declared-pages.ts`.
 *
 * ═══ ПОЧЕМУ ЗАМЕР, А НЕ ОДИН ИЗ ТРЁХ ОЧЕВИДНЫХ ВАРИАНТОВ ═══
 *
 * 1. **Фикстуры (сеялка в приёмке).** Отклонено и остаётся отклонённым:
 *    `pnpm test:seo` входит в `pnpm verify`, который гоняет каждый агент на
 *    каждой задаче, — то есть стандартная команда проверки ПУБЛИКОВАЛА БЫ записи
 *    в базу контента, а публикация есть решение человека (п. 7.1 и п. 23 ТЗ).
 *    Оборванный прогон при этом оставляет записи опубликованными. Полный разбор
 *    (плюс довод про тавтологичность проверок на своих же данных) — в
 *    `tests/seo/README.md`.
 * 2. **Подбор адресов обходом сайта** («возьми первую ссылку на карточку из
 *    сетки каталога»). Отклонено: тогда ВЫБОРКА приёмки берётся из кода, который
 *    приёмка проверяет. Сломанная сетка давала бы не падение, а другую выборку —
 *    и «проверено нечем» вместо «сетка пуста». Это ровно тот довод, по которому
 *    приёмка держит свою копию набора robots-директив.
 * 3. **Пропуск (`test.skip`) на отсутствующей странице.** Отклонено: пропуск,
 *    притворяющийся проверкой, — та же ошибка отчётности, что `SKIPPED`,
 *    выданный за `PASSED`. Отсутствие страницы обязано быть НАЗВАНО (аннотация
 *    «проверено нечем» плюс строка в stdout), а сам факт «отсутствие выглядит
 *    как 404, а не как 500 или 301» — проверен утверждением.
 *
 * ═══ КАК ЗАМЕР ДОСТАЁТСЯ ДО SPEC-ФАЙЛОВ ═══
 *
 * Списки тестов в Playwright строятся СИНХРОННО при загрузке spec-файлов,
 * поэтому спросить сайт в момент объявления теста нельзя. Замер делает
 * `../global-setup.ts`, и порядок задач Playwright это позволяет: в CLI-прогоне
 * задачи идут `webServer` (плагин конфига) → `globalSetup` → ЗАГРУЗКА
 * spec-файлов → тесты (`runAllTestsWithConfig`,
 * `playwright/lib/runner/index.js`, замерено на playwright 1.62.1). То есть к
 * моменту загрузки инвентаря сервер поднят и замер уже сделан.
 *
 * Результат передаётся переменной окружения, а не файлом на диске, и это выбор:
 *
 *   - воркеры Playwright — дочерние процессы, форкнутые ПОСЛЕ `globalSetup`,
 *     поэтому переменную они наследуют, а сам инвентарь в главном процессе
 *     читает её из того же `process.env`, куда её положил замер;
 *   - файл пришлось бы чистить и проверять на свежесть: несовпадение адреса
 *     стенда со адресом в артефакте — это ложный «проверено нечем» на странице,
 *     которая на самом деле отдаётся. У переменной окружения жизнь ровно одна —
 *     прогон; и всё равно проверяется, что origin в ней совпадает с BASE_URL
 *     ({@link readDeclaredPageProbe}).
 *
 * ═══ ЕСЛИ ЗАМЕРА НЕТ ═══
 *
 * `playwright test --list`, UI-режим и любой запуск с конфигом без
 * `globalSetup` загружают spec-файлы, не спросив сайт. Тогда инвентарь считает
 * контентные страницы ПРИСУТСТВУЮЩИМИ — то есть специи для них порождаются и
 * упадут на первом же `expect(status).toBe(200)`, если страницы нет. Направление
 * выбрано намеренно: отсутствие замера обязано давать красный отчёт с внятной
 * причиной, а не тихо уменьшать приёмку до маршрутов кода.
 */

import type { AcceptancePage } from './declared-pages.js';

/**
 * Ключ, которым замер передаётся из `global-setup` в spec-файлы.
 *
 * Префикс `SEO_` — как у остальных переменных приёмки (`SEO_REUSE_SERVER`,
 * `SEO_SERVER_PORT`): по нему видно, что переменная принадлежит стенду, а не
 * продукту.
 */
export const DECLARED_PAGE_PROBE_ENV_KEY = 'SEO_DECLARED_PAGE_PROBE';

/** Статус, при котором страница считается присутствующей и проверяется целиком. */
export const PRESENT_STATUS = 200;

/**
 * Статус, при котором отсутствие страницы считается ЗАКОННЫМ.
 *
 * Ровно 404 и ничего больше: пустая подборка и неопубликованная запись отвечают
 * именно так (ТЗ §5.3, таблица «HTTP-статусы»). Любой другой ответ — 500, 301,
 * 200 с чужим телом — это дефект, и он обязан падать, а не превращаться в
 * «страницы пока нет». Утверждение живёт в
 * `declared-page-not-served.spec.ts`, здесь только значение.
 */
export const ABSENT_STATUS = 404;

/** Результат замера: что ответил каждый объявленный контентный адрес. */
export interface DeclaredPageProbe {
  /** Origin стенда, на котором сделан замер. Сверяется с BASE_URL при чтении. */
  readonly origin: string;
  /** Время замера — попадает в сообщения об ошибках, чтобы не путать прогоны. */
  readonly probedAt: string;
  /** Путь → код ответа. Пути — ровно те, что объявлены как `content`. */
  readonly statuses: Readonly<Record<string, number>>;
}

/**
 * Спрашивает объявленные контентные адреса.
 *
 * Без перехода по `Location` (`redirect: 'manual'`): переход показал бы конечную
 * страницу и скрыл бы сам факт редиректа, а редирект на объявленном
 * КАНОНИЧЕСКОМ адресе — нарушение, которое обязано быть видно.
 *
 * Сбой соединения — не «страницы нет», а несостоявшийся замер, поэтому ошибка
 * поднимается наружу и валит прогон. Иначе упавший сервер выглядел бы как пустая
 * база: приёмка отчиталась бы «страниц нет, проверять нечего» и осталась бы
 * зелёной.
 */
export async function probeDeclaredPages(
  origin: string,
  pages: readonly AcceptancePage[],
): Promise<DeclaredPageProbe> {
  const statuses: Record<string, number> = {};

  for (const page of pages) {
    const url = `${origin}${page.path}`;
    let response: Response;
    try {
      response = await fetch(url, {
        headers: { 'cache-control': 'no-cache' },
        redirect: 'manual',
      });
    } catch (error) {
      throw new Error(
        `SEO-приёмка: замер присутствия страниц не состоялся.\n` +
          `  Адрес ${url} не ответил: ${error instanceof Error ? error.message : String(error)}\n` +
          '  Это не «страницы нет», а недоступный стенд. Отличать одно от другого обязательно: ' +
          'иначе упавший сервер выглядел бы как пустая база и приёмка осталась бы зелёной, ' +
          'ничего не проверив.',
      );
    }
    statuses[page.path] = response.status;
  }

  return { origin, probedAt: new Date().toISOString(), statuses };
}

/** Кладёт замер в окружение, откуда его прочитают инвентарь и воркеры. */
export function publishDeclaredPageProbe(probe: DeclaredPageProbe): void {
  process.env[DECLARED_PAGE_PROBE_ENV_KEY] = JSON.stringify(probe);
}

function isStatusMap(value: unknown): value is Record<string, number> {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  return Object.values(value).every((status) => typeof status === 'number');
}

/**
 * Читает замер из окружения.
 *
 * `null` — замера не было (см. раздел «ЕСЛИ ЗАМЕРА НЕТ» в шапке). Несовпадение
 * origin — ошибка, а не повод молча пересчитать: замер с другого адреса означает,
 * что присутствие страниц взято не с того стенда, против которого идёт прогон.
 */
export function readDeclaredPageProbe(
  origin: string,
  env: Readonly<Record<string, string | undefined>> = process.env,
): DeclaredPageProbe | null {
  const raw = (env[DECLARED_PAGE_PROBE_ENV_KEY] ?? '').trim();
  if (raw === '') {
    return null;
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    throw new Error(
      `SEO-приёмка: значение ${DECLARED_PAGE_PROBE_ENV_KEY} не разбирается как JSON. ` +
        'Переменную ставит tests/seo/global-setup.ts; задавать её руками не нужно.',
    );
  }

  if (
    typeof parsed !== 'object' ||
    parsed === null ||
    !('origin' in parsed) ||
    !('statuses' in parsed) ||
    typeof parsed.origin !== 'string' ||
    !isStatusMap(parsed.statuses)
  ) {
    throw new Error(
      `SEO-приёмка: значение ${DECLARED_PAGE_PROBE_ENV_KEY} не похоже на результат замера.`,
    );
  }

  if (parsed.origin !== origin) {
    throw new Error(
      `SEO-приёмка: замер присутствия страниц сделан на ${parsed.origin}, а прогон идёт ` +
        `против ${origin}. Присутствие страниц с другого стенда использовать нельзя: ` +
        'страница, которой там нет, здесь может отдаваться — и наоборот.',
    );
  }

  return {
    origin: parsed.origin,
    probedAt: 'probedAt' in parsed && typeof parsed.probedAt === 'string' ? parsed.probedAt : '',
    statuses: parsed.statuses,
  };
}
