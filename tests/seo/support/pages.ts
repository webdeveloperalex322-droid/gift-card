/*
 * ПОЧЕМУ ЗДЕСЬ ПОКА НЕТ КАРТОЧКИ И ПОДБОРОК (Э3-05, Э3-06), хотя шаблоны готовы.
 *
 * Их страницы существуют только у ОПУБЛИКОВАННОЙ записи, а в базе опубликованных
 * записей ноль: `/otkrytki/<slug>` и `/podborki/...` отвечают 404, и любая запись
 * в этом списке валила бы приёмку на первом же утверждении «страница обязана
 * отдавать 200». Наполнение — задача Э3-13, и упирается она в человека: ≥ 120
 * реальных открыток агент не создаёт.
 *
 * Вариант «завести записи на временных фикстурах» рассмотрен и ОТКЛОНЁН, причины
 * по убыванию веса:
 *
 *   1. `pnpm test:seo` входит в `pnpm verify`, который гоняет каждый агент на
 *      каждой задаче. Сеялка внутри приёмки означала бы, что стандартная команда
 *      проверки ПУБЛИКУЕТ записи в базу контента. Публикация — решение человека
 *      (п. 7.1 и п. 23 ТЗ); в одноразовом скрипте, который разработчик запускает
 *      сам (`apps/web/scripts/smoke-pages.ts`), это допустимо, а как побочный
 *      эффект `pnpm verify` — нет. Оборванный прогон при этом оставляет
 *      опубликованные записи в базе: автору того смоука понадобилась отдельная
 *      уборка чужих следов ровно поэтому;
 *   2. проверки на своих же фикстурах частью тавтологичны. «title уникален и
 *      непуст» на данных, которые сеялка сама и написала, доказывает сеялку, а не
 *      сайт; настоящую силу это утверждение получает только на реальном
 *      каталоге, где шаблонный title «Открытки на <тема>» и порождает дубли;
 *   3. проверки, которые на фикстурах ДЕЙСТВИТЕЛЬНО работают (один H1, одно
 *      неленивое изображение, `ItemList` = видимая сетка, ноль клиентского JS,
 *      301 на слеш, 404 у черновика), уже сделаны против собранного сервера в
 *      `apps/web/scripts/smoke-pages.ts` — 65 проверок, включая браузер с
 *      отключённым JS. Вторая копия тех же фикстур с другим владельцем добавила
 *      бы не покрытие, а расхождение;
 *   4. приёмка стала бы зависеть от PostgreSQL, конфига CMS и пайплайна
 *      изображений — то есть краснела бы по причинам, к состоянию сайта не
 *      относящимся. Этот довод уже принят в `support/serve-built-web.mjs`
 *      (проект `tests/` намеренно не собирается перед стартом сервера).
 *
 * Что вместо этого: specs написаны так, что страница входит в проверку ОДНОЙ
 * записью в этом списке. Состав, который добавляется на Э3-13, известен заранее —
 * `/otkrytki/<slug>`, `/podborki/prazdniki`, `/podborki/prazdniki/<tema>`,
 * `/podborki/prazdniki/<tema>/<adresat>`, `/podborki/adresaty/<adresat>`, у всех
 * `expectedRobots: 'noindex,follow'`, `images: 'primary'`,
 * `structuredData: 'required'`. Обязательное условие для каждой добавляемой
 * страницы: у записи ЗАПОЛНЕН `metaDescription`. При пустом поле тега
 * `<meta name="description">` нет вовсе (то же правило «пустое — значит блока
 * нет», что у Ч-10 и Ч-17), и `unique-title-h1-description.spec.ts` упадёт —
 * справедливо, потому что у индексируемой страницы description обязателен
 * (п. 22.1), а подставлять его шаблоном запрещено (п. 23.4).
 */

/** Индексируемая страница — та, чья директива начинается с `index`. */
export function isIndexable(page: AcceptancePage): boolean {
  return page.expectedRobots.startsWith('index');
}

/**
 * Ожидаемый путь в self-canonical. Совпадает с {@link AcceptancePage.path}: у
 * корня канонический абсолютный адрес — `<origin>/`, у остальных страниц —
 * `<origin><path>` без завершающего слеша.
 */
export function expectedCanonicalPath(page: AcceptancePage): string {
  return page.path;
}
