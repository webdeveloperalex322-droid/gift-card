/**
 * Требование («Правила URL» и «HTTP-статусы»): «Цепочки редиректов запрещены».
 * Петля — предельный случай цепочки: краулер тратит на неё бюджет обхода и
 * никогда не доходит до страницы.
 *
 * Проверяются враждебные формы пути, которые нормализация обрабатывает по
 * отдельным ветвям и на которых петля и возникает:
 *   - процентно-закодированный слеш (`/%2F`, `/%2F/`) — декодирование и
 *     нормализация легко начинают отменять друг друга: один шаг убирает
 *     завершающий слеш, второй возвращает его из `%2F`;
 *   - подряд идущие слеши (`////`) — если каждый шаг снимает по одному, вместо
 *     одиночного 301 получается лестница с промежуточными `Location: //`, а
 *     адрес, начинающийся с `//`, браузер читает как ЧУЖОЙ хост;
 *   - те же формы внутри пути страницы.
 *
 * Утверждения требованию соответствуют буквально: цепочка обязана завершиться,
 * переходов не больше одного, и ни одна из этих форм не отдаёт 200 (иначе это
 * второй адрес того же материала). Конкретный код (404 или 301 на каноническую
 * форму) — выбор владельца слоя.
 */

import { expect, test } from '@playwright/test';

import { describeChain, followRedirects, hopCount, isRedirect } from './support/http.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

const HOSTILE_PATHS: readonly { readonly path: string; readonly note: string }[] = [
  { path: '/%2F', note: 'процентно-закодированный слеш вместо пути' },
  { path: '/%2F/', note: 'он же с завершающим слешем — классическая пара для петли' },
  { path: '////', note: 'несколько слешей подряд: лестница переходов вместо одного' },
  { path: '/otkrytki/%2F', note: 'закодированный слеш внутри пути раздела' },
  { path: '/otkrytki////8-marta', note: 'несколько слешей внутри пути карточки' },
];

for (const hostile of HOSTILE_PATHS) {
  test(`нет петли и лестницы переходов: ${hostile.path} (${hostile.note})`, async ({ request }) => {
    const chain = await followRedirects(request, urlFor(target, hostile.path));
    const first = chain[0];
    const last = chain[chain.length - 1];
    const context = `\n  Цепочка:\n    ${describeChain(chain)}`;

    expect(
      last === undefined ? true : isRedirect(last.status),
      `Цепочка не завершилась: последний ответ снова переход. Это петля.${context}`,
    ).toBe(false);

    expect(
      hopCount(chain),
      `Переходов не больше одного: цепочки редиректов запрещены.${context}`,
    ).toBeLessThanOrEqual(1);

    for (const response of chain) {
      if (response.resolvedLocation !== null) {
        expect(
          new URL(response.resolvedLocation).origin,
          `Location обязан остаться на нашем хосте: путь, начинающийся с «//», браузер читает ` +
            `как адрес чужого хоста — это открытый редирект.${context}`,
        ).toBe(target.origin);
      }
    }

    // Проверяется ПЕРВЫЙ ответ, а не последний, и это не мелочь: одиночный 301 в
    // каноническую форму — верное поведение, и 200 на канонической форме в конце
    // такой цепочки нарушением не является. Нарушение — 200 по самому
    // враждебному адресу: тогда у материала появляется второй адрес.
    expect(
      first?.status,
      `«${hostile.path}» адресом страницы не является: 200 здесь означает второй адрес того ` +
        `же материала.${context}`,
    ).not.toBe(200);
  });
}
