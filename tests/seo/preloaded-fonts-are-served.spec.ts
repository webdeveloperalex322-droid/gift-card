/**
 * Файлы шрифтов, которые страница ЗАКАЗЫВАЕТ, обязаны существовать и отдаваться
 * своим же доменом.
 *
 * ## Зачем это в SEO-приёмке
 *
 * Требование не из п. 22 — оно из раздела «Производительность» `CLAUDE.md`
 * (LCP ≤ 2,5 с, CLS < 0,1, «критический CSS первым») и появилось вместе с
 * дизайн-направлением «Почтовый штемпель» (2026-08-31), которое положило шрифты
 * в `apps/web/public/fonts` и предзагружает два из них на КАЖДОЙ странице.
 *
 * Пропажа такого файла — самая тихая поломка первого экрана из возможных:
 * страница отвечает 200, разметка цела, ни один другой spec не шевелится, а
 * посетитель получает 404 на `rel="preload"`, текст рисуется резервным шрифтом и
 * подмены не происходит вовсе. Ломается это одним движением: правкой имени файла,
 * переносом каталога, забытым `public/` в `.gitignore` — файлы шрифтов лежат в
 * git, автоматической синхронизации с `@fontsource/*` НЕТ (шапка
 * `BaseLayout.astro` говорит это прямо), и `pnpm check` расхождения не увидит.
 *
 * ## Что именно утверждается
 *
 *   1. заказы шрифтов на странице ЕСТЬ. Пустой список валит тест: иначе
 *      предзагрузка, случайно удалённая из layout'а, оставила бы тест зелёным;
 *   2. каждый заказанный адрес — СВОЙ, то есть путь от корня. Внешний origin
 *      (`fonts.googleapis.com`) отклонён решением слоя как второй DNS+TLS в
 *      критическом пути первого экрана; утверждение держит это решение, а не
 *      вкус;
 *   3. каждый адрес отвечает 200 БЕЗ перехода и с типом `font/woff2`. Без
 *      перехода — потому что редирект на шрифте первого экрана добавляет круг к
 *      LCP; тип — потому что 200 с HTML-телом (страница 404, отданная как 200)
 *      выглядит для теста так же, как файл;
 *   4. у ссылки предзагрузки есть `as="font"` и `crossorigin`. Оба обязательны:
 *      без `as` браузер не знает приоритета и не сопоставляет предзагрузку с
 *      последующим запросом, а без `crossorigin` шрифт скачивается ВТОРОЙ раз —
 *      шрифты запрашиваются в режиме CORS всегда, в том числе со своего домена.
 *      Двойная загрузка не ломает страницу и потому не будет замечена никем,
 *      кроме этого утверждения.
 *
 * ## Почему проверяются не только предзагруженные файлы
 *
 * Предзагружены два файла из шести, остальные четыре объявлены в `@font-face`
 * того же критического CSS. Пропажа непредзагруженного файла тише ровно на
 * столько же и заметна ещё позже (латиница — это цифры и знаки препинания, то
 * есть даты и подписи на всех страницах). Поэтому в проверку идут ОБА источника
 * адресов: `rel="preload"` и `src: url(...)` из `@font-face`. Разбор `@font-face`
 * тут узкий — вытащить адреса, а не понять CSS; на большее он и не претендует.
 *
 * ## Что этот spec НЕ проверяет
 *
 * `Cache-Control` у шрифтов. Замерено 2026-08-31: `apps/web` отдаёт файлы из
 * `public/` без заголовка кеширования вовсе. Требование «длительное кеширование
 * статики» относится к развёртыванию (перед приложением встанет обратный прокси,
 * решение по `/media` — Ч-03), а не к dev-серверу приёмки, и утверждение здесь
 * фиксировало бы сегодняшнюю конфигурацию стенда как норму. Строка про это есть
 * в таблице «Чего приёмка пока НЕ проверяет» в `tests/seo/README.md`.
 */

import { expect, test } from '@playwright/test';

import { attributeValue, openingTags } from './support/html.js';
import { fetchRaw, isRedirect } from './support/http.js';
import { ACCEPTANCE_PAGES } from './support/pages.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/** Заказ шрифта: откуда взят адрес и сам адрес, как он написан в ответе. */
interface FontRequest {
  readonly source: 'rel="preload"' | '@font-face';
  readonly href: string;
  /** Открывающий тег `link` целиком — только у предзагрузки. */
  readonly tag: string | null;
}

function fontPreloads(html: string): FontRequest[] {
  return openingTags(html, 'link')
    .filter((tag) => attributeValue(tag, 'rel')?.trim().toLowerCase() === 'preload')
    .filter((tag) => attributeValue(tag, 'as')?.trim().toLowerCase() === 'font')
    .map((tag) => ({ source: 'rel="preload"' as const, href: attributeValue(tag, 'href') ?? '', tag }));
}

/**
 * Адреса из `src: url('…')` внутри блоков `@font-face`.
 *
 * Границы блока намеренно не разбираются: `url(...)` со шрифтом в критическом CSS
 * этого проекта встречается только в `@font-face`, а разбор вложенных фигурных
 * скобок в приёмке был бы вторым парсером CSS без нужды. Отбор идёт по расширению
 * файла — оно же и есть признак шрифта.
 */
function fontFaceSources(html: string): FontRequest[] {
  const styles = [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map(
    (match) => match[1] ?? '',
  );
  const found = new Set<string>();

  for (const css of styles) {
    for (const match of css.matchAll(/url\(\s*['"]?([^'")]+\.woff2)['"]?\s*\)/gi)) {
      found.add((match[1] ?? '').trim());
    }
  }
  return [...found].map((href) => ({ source: '@font-face' as const, href, tag: null }));
}

for (const page of ACCEPTANCE_PAGES) {
  test(`шрифты первого экрана отдаются: ${page.path} (${page.task})`, async ({ request }) => {
    const response = await fetchRaw(request, urlFor(target, page.path));
    expect(response.status, 'Страница обязана отдавать 200.').toBe(200);

    const preloads = fontPreloads(response.body);
    const requests = [...preloads, ...fontFaceSources(response.body)];

    expect(
      requests.length,
      `На странице ${page.path} нет ни одной ссылки rel="preload" as="font" и ни одного адреса ` +
        'шрифта в @font-face. Оформление проекта объявляет свои гарнитуры в критическом CSS ' +
        '(apps/web/src/layouts/BaseLayout.astro): если объявлений не стало, либо шрифты уехали ' +
        'на внешний origin — что решением слоя отклонено, — либо блок стилей потерялся. Пустой ' +
        'список оставил бы этот тест зелёным ни на чём.',
    ).toBeGreaterThan(0);

    // Предзагрузка — не то же самое, что @font-face: её отсутствие означает
    // открытое окно подмены шрифта на первом экране, то есть сдвиг макета.
    expect(
      preloads.length,
      `На странице ${page.path} нет ни одной ссылки rel="preload" as="font". Текст первого ` +
        'экрана ждёт кириллических файлов на каждой странице (шапка BaseLayout.astro), и без ' +
        'предзагрузки окно font-display: swap остаётся открытым — это сдвиг макета, а не ' +
        'оформление.',
    ).toBeGreaterThan(0);

    const badAttributes = preloads
      .filter(
        (item) =>
          attributeValue(item.tag ?? '', 'crossorigin') === null ||
          (attributeValue(item.tag ?? '', 'type') ?? '').trim().toLowerCase() !== 'font/woff2',
      )
      .map((item) => item.tag ?? item.href);

    expect(
      badAttributes,
      `Ссылка предзагрузки шрифта на ${page.path} объявлена не полностью. Обязательны ` +
        'crossorigin (без него шрифт скачивается ВТОРОЙ раз: шрифты запрашиваются в режиме ' +
        'CORS всегда, даже со своего домена) и type="font/woff2" (без него браузер не ' +
        'отбрасывает предзагрузку формата, который не поддерживает). Ни то, ни другое не ' +
        'ломает страницу видимым образом — поэтому это утверждение единственное, что об этом ' +
        'скажет.',
    ).toEqual([]);

    const external = requests
      .filter((item) => !item.href.startsWith('/'))
      .map((item) => `${item.source}: ${item.href}`);

    expect(
      external,
      `На странице ${page.path} шрифт заказан не своим адресом. Путь обязан начинаться со ` +
        'слеша: внешний origin — это DNS и TLS до появления текста плюс чужая ответственность ' +
        'за отдачу файла первого экрана (шапка BaseLayout.astro, раздел «Шрифты»). Относительный ' +
        'адрес без слеша тоже нарушение: он разрешается от адреса страницы, то есть на вложенном ' +
        'маршруте указывает в никуда.',
    ).toEqual([]);

    for (const item of requests) {
      const file = await fetchRaw(request, urlFor(target, item.href));

      // Переход называется отдельно от «не 200»: 301 на шрифте первого экрана —
      // это лишний круг до LCP, и сообщение обязано говорить про круг, а не про
      // пропавший файл.
      expect(
        isRedirect(file.status) ? (file.location ?? 'переход без Location') : null,
        `Файл шрифта ${item.href} (${item.source} на ${page.path}) отдаётся через переход. ` +
          'Адрес шрифта первого экрана обязан быть конечным: переход добавляет круг к LCP.',
      ).toBeNull();

      expect(
        `${String(file.status)} ${item.href}`,
        `Файл шрифта, заказанный на ${page.path} через ${item.source}, не отдаётся. Файлы лежат ` +
          'в apps/web/public/fonts и синхронизации с пакетами @fontsource НЕТ — расхождение ' +
          'имени или пути не поймает ни pnpm check, ни сборка. Страница при этом отвечает 200 ' +
          'и выглядит целой: текст просто остаётся резервным шрифтом.',
      ).toBe(`200 ${item.href}`);

      expect(
        (file.contentType ?? '').toLowerCase(),
        `Файл шрифта ${item.href} отдаётся не как woff2 (получено «${
          file.contentType ?? 'без типа'
        }»). Тип проверяется отдельно от статуса, потому что 200 с HTML-телом — так выглядит ` +
          'страница 404, отданная как файл, — от настоящего файла статусом не отличается.',
      ).toContain('font/woff2');
    }
  });
}
