/**
 * В отдаваемом тексте, который НЕ является разметкой, не должно быть литералов
 * вида `<буква`.
 *
 * ## Зачем это отдельный spec
 *
 * Приёмка разбирает ответ сервера регулярными выражениями по всему телу
 * (`support/html.ts`, и это осознанное решение — см. шапку того файла). У такого
 * разбора есть ровно одна слепая зона: три места, где текст уезжает в ответ БЕЗ
 * экранирования и при этом разметкой не является —
 *
 *   1. HTML-комментарий `<!-- … -->`. Astro оставляет такие комментарии в
 *      ответе — вырезаются только комментарии в фигурных скобках, JSX-вида;
 *   2. тело `<style>`, включая CSS-комментарии. Критический CSS уезжает с
 *      `is:inline`, то есть без обработки и без вырезания комментариев;
 *   3. тело `<script>`, включая `application/ld+json`.
 *
 * Имя тега, написанное там литералом, разбор считает РАЗМЕТКОЙ. Это не гипотеза:
 * при внедрении дизайн-направления «Почтовый штемпель» (2026-08-31) в
 * комментарии внутри `<style is:inline>` были написаны имена тегов со скобками,
 * и `image-attributes.spec.ts` упал на пяти страницах с «у img обязан быть
 * реальный src» — приёмка нашла «изображение», которого нет.
 *
 * То падение было ПРАВИЛЬНЫМ по факту и НЕГОДНЫМ по адресу: оно называло
 * нарушение контракта изображений, тогда как нарушен был контракт разбора.
 * Поймал его при этом случай — spec, который просто первым спотыкается о фальшивый
 * `<img`. Про фальшивый `<a`, `<link rel=canonical>` или `<h1` в комментарии никто
 * бы так же не узнал: они дали бы «ссылка без href», «два canonical» или «два H1»
 * на странице, где всё в порядке. Отсюда отдельное утверждение: нарушение обязано
 * называться своим именем и на своём месте.
 *
 * ## Почему правило запрещает любую букву после `<`, а не список имён тегов
 *
 * Список имён (`img`, `a`, `link`, `h1`, …) пришлось бы держать в согласии с
 * вокабуляром `support/html.ts`, и он бы отстал: новая функция разбора в
 * `support/html.ts` молча вывела бы своё имя тега из-под охраны. Правило «после
 * `<` не бывает буквы» от вокабуляра не зависит вовсе и потому не отстаёт.
 *
 * Ложных срабатываний оно почти не даёт: сравнения (`< 4`, `<= 2`) и CSS-синтаксис
 * идут не с буквы, а прозу «тег `<img>`» это правило и обязано запрещать. Исправление
 * тривиально и уже применено в `BaseLayout.astro`: убрать угловые скобки, оставив
 * имя тега словом.
 *
 * ## Что этот spec НЕ проверяет
 *
 * Экранирование ЗНАЧЕНИЙ из записей (описание открытки, в тексте которого стоит
 * имя тега со скобками) — не здесь: Astro экранирует интерполяцию, а JSON-LD
 * печатается через `jsonLdScriptText`, который переводит угловую скобку и
 * амперсанд в последовательности `<`, `>`, `&`
 * (`apps/web/src/seo/json-ld.ts`). Тело `script` попадает в проверку ровно
 * поэтому: правило удерживает это экранирование на живом ответе, а не на вере в
 * хелпер.
 */

import { expect, test } from '@playwright/test';

import { fetchRaw } from './support/http.js';
import { ACCEPTANCE_PAGES } from './support/pages.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/**
 * Адрес, которого нет. Тело 404 приходит из того же layout'а и того же блока
 * критического CSS, а страницей приёмочного инвентаря не является — поэтому
 * проверяется отдельным адресом, иначе единственная страница сайта с собственным
 * шаблоном осталась бы без охраны.
 */
const MISSING_PATH = '/takogo-adresa-net-e3-14';

/** `<` + латинская буква либо `/`+буква — то, что разбор примет за тег. */
const TAG_LITERAL = /<\/?[a-z]/iu;

interface UnescapedFragment {
  /** Откуда фрагмент взят — чтобы сообщение называло место, а не только страницу. */
  readonly kind: string;
  /** Текст фрагмента без обрамляющей разметки. */
  readonly text: string;
}

/**
 * Три поверхности, где текст уезжает в ответ без экранирования.
 *
 * Порядок разбора важен ровно в одном: комментарии ищутся по всему телу, поэтому
 * комментарий ВНУТРИ `<style>` попадает в выборку дважды — один раз как
 * комментарий, второй раз внутри тела стиля. Это не мешает: утверждение
 * одинаковое, а лишнее вхождение только уточняет сообщение.
 */
function unescapedFragments(html: string): UnescapedFragment[] {
  const fragments: UnescapedFragment[] = [];

  for (const match of html.matchAll(/<!--([\s\S]*?)-->/g)) {
    fragments.push({ kind: 'HTML-комментарий', text: match[1] ?? '' });
  }
  for (const match of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    fragments.push({ kind: 'тело <style>', text: match[1] ?? '' });
  }
  for (const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)) {
    fragments.push({ kind: 'тело <script>', text: match[1] ?? '' });
  }
  return fragments;
}

/** Место находки с окружением: по такому сообщению правка находится сразу. */
function violationsIn(fragment: UnescapedFragment): string[] {
  const found: string[] = [];
  const pattern = new RegExp(TAG_LITERAL.source, 'giu');

  for (const match of fragment.text.matchAll(pattern)) {
    const at = match.index;
    const around = fragment.text.slice(Math.max(0, at - 60), at + 60).replace(/\s+/gu, ' ');
    found.push(`${fragment.kind}: …${around}…`);
  }
  return found;
}

const PROBES = [
  ...ACCEPTANCE_PAGES.map((page) => ({ path: page.path, note: page.task })),
  { path: MISSING_PATH, note: 'тело страницы 404' },
];

for (const probe of PROBES) {
  test(`в отдаваемом тексте нет литералов тегов: ${probe.path} (${probe.note})`, async ({
    request,
  }) => {
    const response = await fetchRaw(request, urlFor(target, probe.path));

    // Сначала — что проверять было ЧТО. Иначе тест остался бы зелёным и на
    // ответе, который вообще не дошёл: пустое тело нарушений не содержит.
    const fragments = unescapedFragments(response.body);
    expect(
      fragments.length,
      `В ответе ${probe.path} нет ни комментария, ни блока <style>, ни блока <script>. ` +
        'Проверять нечего, а значит, зелёный статус этого теста ничего не значил бы: ' +
        'критический CSS приходит блоком <style is:inline> на КАЖДОЙ странице (см. шапку ' +
        'apps/web/src/layouts/BaseLayout.astro). Либо ответ не тот, либо оформление уехало во ' +
        'внешний файл — и тогда проверять надо его.',
    ).toBeGreaterThan(0);

    const violations = fragments.flatMap(violationsIn);

    expect(
      violations,
      `На странице ${probe.path} имя тега написано ЛИТЕРАЛОМ в тексте, который разметкой не ` +
        'является (комментарий, тело <style> или тело <script>). Разбор приёмки ищет теги ' +
        'регулярным выражением по всему ответу (tests/seo/support/html.ts) и такой литерал ' +
        'считает разметкой: дальше падает не этот spec, а случайный — «у img нет src», «два ' +
        'canonical», «два H1» — на странице, где с разметкой всё в порядке.\n' +
        'Как исправить: убрать угловые скобки, оставив имя тега словом («блок style», «тег ' +
        'img»). Так уже сделано в критическом CSS BaseLayout.astro. Если литерал пришёл из ' +
        'ЗНАЧЕНИЯ записи, скобки обязаны быть заэкранированы — в JSON-LD это делает ' +
        'jsonLdScriptText (apps/web/src/seo/json-ld.ts).',
    ).toEqual([]);
  });
}
