/**
 * Требование (п. 5.1: «включена в навигацию»; п. 22: «нет страниц-сирот — каждая
 * индексируемая страница достижима за ≤ 4 перехода от главной»; следствие Ч-04-5:
 * прямые ссылки из меню на праздничные узлы).
 *
 * Достижимость за четыре перехода держится не на дисциплине шаблонов, а на том,
 * что меню и подвал печатает LAYOUT — то есть они есть на каждой странице, а не
 * «пока не забыли». Проверяется ровно это: в ответе КАЖДОЙ страницы выборки, а
 * также на странице 404, присутствуют ссылки `<a href>` на корень и на оба
 * каталога — `/otkrytki` и `/podborki`. Через них достижимы группирующие узлы,
 * через узлы — подборки, через подборки — карточки.
 *
 * Почему проверяется НАЛИЧИЕ ССЫЛКИ, а не 200 у её цели: каталог без
 * опубликованных записей отвечает 404 намеренно (пустая страница не отдаёт 200,
 * ТЗ §5.3 — см. шапку `apps/web/src/data/catalog.ts`), и на пустой базе пункт
 * меню ведёт на 404. Это видимый признак ненаполненного сайта, а не дефект меню;
 * требовать здесь 200 значило бы требовать наполнения базы от команды `pnpm
 * verify`. Проверка «цель ссылки отвечает 200» входит в приёмку на Э3-13 вместе со
 * страницами списка.
 *
 * Что этот spec НЕ доказывает, и это записано в непокрытом: саму глубину «≤ 4
 * перехода» до карточки. Её можно измерить только обходом реальных ссылок от
 * главной, а для обхода нужны опубликованные записи. Здесь проверяется
 * необходимое условие — что точка входа в каталог есть на каждой странице.
 */

import { expect, test } from '@playwright/test';

import { anchorLinks } from './support/html.js';
import { fetchRaw } from './support/http.js';
import { ACCEPTANCE_PAGES } from './support/pages.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/** Пункты меню, обязательные на каждой странице. */
const REQUIRED_LINKS: readonly string[] = ['/', '/otkrytki', '/podborki'];

const PAGES: readonly { readonly path: string; readonly label: string }[] = [
  ...ACCEPTANCE_PAGES.map((page) => ({ label: page.task, path: page.path })),
  // Страница 404 в инвентаре быть не может (у неё нет своего адреса), но
  // навигация на ней обязательна прямым требованием таблицы «HTTP-статусы».
  { label: 'страница 404', path: '/takogo-adresa-net-e3-14' },
];

for (const page of PAGES) {
  test(`меню сайта есть в HTML: ${page.path} (${page.label})`, async ({ request }) => {
    const response = await fetchRaw(request, urlFor(target, page.path));

    const hrefs = new Set(anchorLinks(response.body).map((link) => (link.href ?? '').trim()));

    for (const required of REQUIRED_LINKS) {
      expect(
        hrefs.has(required),
        `В ответе ${page.path} нет ссылки <a href="${required}">. Меню печатает layout, поэтому ` +
          'его отсутствие означает либо страницу вне layout’а, либо ссылку, собранную ' +
          'скриптом, — а навигация обязана быть обычными <a href> в ответе сервера. Через эти ' +
          'ссылки держится достижимость каталога за один переход от любой страницы, то есть ' +
          'требование «нет страниц-сирот».',
      ).toBe(true);
    }
  });
}
