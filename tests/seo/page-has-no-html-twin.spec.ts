/**
 * Требование («Правила URL»): «Один материал доступен только по одному пути».
 * Второй адрес, отдающий 200 с тем же содержанием, — дубль, даже если canonical
 * указывает на первый.
 *
 * Здесь проверяется конкретный класс дублей — `.html`-двойник маршрута страницы:
 * `/index.html` для корня и `<путь>.html` / `<путь>/index.html` для остальных
 * страниц.
 *
 * ## Почему это не гипотетическая проверка
 *
 * `apps/web/astro.config.mjs` задаёт `build.format: 'file'` (парный к
 * `trailingSlash: 'never'`). В astro 7.2.4 при этом значении маршрутизатор перед
 * сопоставлением СРЕЗАЕТ `.html` и `/index.html` с пути запроса
 * (`normalizeFileFormatPathname`, вызывается под условием
 * `if (this.#buildFormat === "file")` — см. собранный
 * `apps/web/dist/server/entry.mjs`). То есть двойник получает КАЖДЫЙ маршрут
 * страницы, а не только корень, и отвечает 200 тем же HTML.
 *
 * Наше правило пути такой адрес не перехватывает: `isPageRoute()` видит
 * расширение и относит `/index.html` к URL файлов, а файловые URL из
 * нормализации исключены решением Ч-21. Дыра ровно на стыке двух верных по
 * отдельности решений.
 *
 * Ожидаемое поведение — любое из двух, оба закрывают дубль:
 *   - одиночный 301 на канонический адрес (предпочтительно: Яндекс склеивает
 *     301 надёжнее, чем canonical, и прямо рекомендует его для дублей);
 *   - 404 — двойник адресом страницы не является.
 *
 * Исправляет владелец слоя (`astro-web`, файлы `apps/web/src/routing/` и
 * `apps/web/astro.config.mjs`); аудитор код приложений не правит.
 */

import { expect, test } from '@playwright/test';

import { describeChain, fetchRaw, followRedirects, hopCount } from './support/http.js';
import { ACCEPTANCE_PAGES, expectedCanonicalPath } from './support/pages.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/** Адреса-двойники, которые фреймворк отдаёт вместо страницы при build.format: 'file'. */
function twinsFor(path: string): string[] {
  return path === '/' ? ['/index.html'] : [`${path}.html`, `${path}/index.html`];
}

for (const page of ACCEPTANCE_PAGES) {
  for (const twin of twinsFor(page.path)) {
    test(`нет .html-двойника страницы ${page.path}: ${twin} (${page.task})`, async ({
      request,
    }) => {
      const chain = await followRedirects(request, urlFor(target, twin));
      const first = chain[0];
      const context = `\n  Цепочка:\n    ${describeChain(chain)}`;

      expect(
        first?.status,
        `«${twin}» отдаёт 200 с тем же содержанием, что «${page.path}» — это второй адрес ` +
          'одного материала, то есть дубль. Требование «Один материал доступен только по одному ' +
          `пути» нарушено.${context}`,
      ).not.toBe(200);

      if (first !== undefined && first.status >= 300 && first.status < 400) {
        expect(first.status, 'Склейка дубля — это 301, а не временный редирект.').toBe(301);
        expect(
          first.resolvedLocation,
          'Двойник обязан вести на канонический адрес страницы.',
        ).toBe(urlFor(target, expectedCanonicalPath(page)));
        expect(hopCount(chain), `Переход обязан быть один.${context}`).toBe(1);
      }
    });
  }
}

/*
 * ───────────────────────────────────────────────────────────────────────────
 * ДОПОЛНЕНИЕ (Э4, по находке контролёра `url-guard` от 2026-08-28): тот же
 * двойник, записанный НЕ в канонической форме — со слешем после расширения.
 *
 * Почему этот класс проверяется отдельно и почему именно здесь. Блок выше
 * закрывает `<путь>.html` и `<путь>/index.html`; форму СО СЛЕШЕМ он не трогал, а
 * ломалась она дважды за этап:
 *
 *   1. сначала `/x.html` отдавал 200 с содержимым страницы — второй адрес одного
 *      материала (закрыто блоком выше);
 *   2. потом форма `/x.html/` вернула на провод дефект апстрима: запрос уходил в
 *      приложение сырым, и раньше нашего middleware отвечал встроенный
 *      обработчик слеша Astro — 301 с ТЕЛОМ, в котором
 *      `<meta http-equiv="refresh">` указывал НАЗАД на источник. Для клиента,
 *      предпочитающего meta заголовку, это бесконечный цикл; заодно на ответе
 *      3xx ехали чужой `<meta name="robots">` и относительный canonical.
 *
 * Оба раза приёмка молчала: живое покрытие класса было только в `smoke:slash` и
 * `smoke:redirects`, а они в `pnpm verify` не входят (одному нужен собранный
 * сервер, второму ещё и база). Стенд приёмки собирает и поднимает сайт сам и от
 * базы не зависит — значит, обязательный шлюз этот класс проверять может, и с
 * этого дополнения проверяет.
 *
 * ## Почему здесь требуется ровно 404, а не «301 или 404», как выше
 *
 * Для КАНОНИЧЕСКОЙ формы (`/o-proekte.html`) допустимы обе развязки: 301 туда
 * имеет куда вести — на существующий адрес страницы, и правило переноса с
 * легаси-адреса на `.html` обязано работать.
 *
 * У формы со слешем такой цели нет. Вести её 301 можно только на `<путь>.html`,
 * а тот сам отвечает 404 (или, в случае правила переноса, ещё одним 301) — то
 * есть переход был бы ЗВЕНОМ ЦЕПОЧКИ, оканчивающейся ничем: краулер тратит
 * бюджет обхода и не получает адреса. «Цепочки редиректов запрещены»
 * (`CLAUDE.md`, «Правила URL»), а `Location` на этой форме вдобавок узаконивал
 * бы вторую форму записи одного и того же файлового имени. Поэтому требование
 * здесь — 404 и отсутствие `Location`, и это требование, а не предпочтение
 * реализации.
 */

/** Формы двойника со слешем: адресами не являются ни на этом сайте, ни на прежнем. */
function slashTwinsFor(path: string): { readonly form: string; readonly note: string }[] {
  return path === '/'
    ? [
        { form: '/index.html/', note: 'второго адреса главной нет и в форме со слешем' },
        { form: '/index.html//', note: 'та же форма с пустым сегментом в хвосте' },
      ]
    : [
        { form: `${path}.html/`, note: 'слеш после расширения' },
        { form: `${path}/index.html/`, note: 'каталожная форма двойника со слешем' },
        { form: `${path}.html//`, note: 'пустой сегмент в хвосте того же класса' },
      ];
}

/**
 * Родственные формы того же класса, не привязанные к странице из инвентаря.
 *
 * Каждая замерена контролёром `url-guard` 2026-08-28 на живом сервере, и каждая
 * закрывает СВОЮ дыру, а не повторяет соседнюю:
 *
 *   - `/404.html/` — страница ошибки как файл: у неё нет своего адреса вовсе;
 *   - `/a.HTML/` — регистр расширения не создаёт исключения. Проверка по
 *     `endsWith('.html')` без приведения регистра пропустила бы эту форму, и
 *     двойник вернулся бы через верхний регистр;
 *   - `/media/foo.html/` — пространство производных изображений: `url-guard`
 *     замерил на нём тот же дефект, а решает его та же политика пути, а не
 *     отдельная ветка;
 *   - `/staraya.html/?utm_source=mail` — форма с query, на которой дефект и был
 *     пойман. Таблицу переносов спрашивают ТОЛЬКО о канонической форме адреса,
 *     поэтому query здесь ничего не меняет;
 *   - `/staraya.php/` и `/katalog/otkrytka.htm/` — симметрия расширений. Это не
 *     украшение списка, а существенная часть решения владельца слоя: вариант,
 *     дающий `.html` привилегию перед соседним расширением, был отклонён, и
 *     удерживать приёмка обязана именно симметрию.
 */
const RELATED_SLASH_FORMS: readonly { readonly form: string; readonly note: string }[] = [
  { form: '/404.html/', note: 'страница 404 недоступна как файл и со слешем' },
  { form: '/a.HTML/', note: 'верхний регистр расширения' },
  { form: '/media/foo.html/', note: 'пространство /media — той же политикой пути' },
  { form: '/staraya.html/?utm_source=mail', note: 'форма с query: адрес прежнего сайта' },
  { form: '/staraya.php/', note: 'симметрия: у «.html» нет привилегии перед «.php»' },
  { form: '/katalog/otkrytka.htm/', note: 'симметрия: «.htm» внутри пути' },
];

const ALL_SLASH_FORMS: readonly { readonly form: string; readonly note: string }[] = [
  ...ACCEPTANCE_PAGES.flatMap((page) =>
    slashTwinsFor(page.path).map((twin) => ({
      form: twin.form,
      note: `${twin.note} (страница ${page.path}, ${page.task})`,
    })),
  ),
  ...RELATED_SLASH_FORMS,
];

for (const slashForm of ALL_SLASH_FORMS) {
  test(`форма со слешем адресом не является: ${slashForm.form} (${slashForm.note})`, async ({
    request,
  }) => {
    const response = await fetchRaw(request, urlFor(target, slashForm.form));
    const seen =
      `Получено ${String(response.status)}` +
      (response.location === null ? '' : ` Location: ${response.location}`) +
      ` (тело ${String(response.body.length)} байт).`;

    expect(
      response.status,
      `«${slashForm.form}» обязан отдавать 404. ${seen}\n` +
        '  200 здесь — второй адрес одного материала: имя файла заранее отрендеренной страницы ' +
        'адресом не является.\n' +
        '  3xx здесь — звено цепочки в никуда: вести переход можно только на форму без слеша, ' +
        'а она сама отвечает 404. Ровно в этой ветке 2026-08-28 отвечал встроенный обработчик ' +
        'слеша Astro — 301 с телом, где meta-refresh указывал назад на источник.',
    ).toBe(404);

    expect(
      response.location,
      `У ответа на «${slashForm.form}» не должно быть заголовка Location: перевод робота с ` +
        `этой формы куда бы то ни было узаконил бы вторую форму записи адреса. ${seen}`,
    ).toBeNull();
  });
}

/**
 * Симметрия расширений — отдельным утверждением, а не следствием списка выше.
 *
 * Список проверяет каждую форму по отдельности, и при «почини только `.html`»
 * он падал бы на одной строке, не называя причины. Здесь сравниваются ОТВЕТЫ на
 * три соседних расширения: правило принимает политика пути по форме записи
 * адреса, а не по тому, какое расширение сайту знакомо. Расхождение означает,
 * что `.html` снова обрабатывается отдельной веткой, — а это ровно то состояние,
 * из которого и вырос дефект 2026-08-28.
 */
test('форма со слешем: «.html» отвечает так же, как «.php» и «.htm»', async ({ request }) => {
  const forms = ['/staraya.html/', '/staraya.php/', '/staraya.htm/'];
  const responses = await Promise.all(
    forms.map(async (form) => {
      const response = await fetchRaw(request, urlFor(target, form));
      return {
        form,
        status: response.status,
        location: response.location,
        bodyLength: response.body.length,
      };
    }),
  );
  const seen = responses
    .map(
      (entry) =>
        `${entry.form} -> ${String(entry.status)}` +
        (entry.location === null ? '' : ` Location: ${entry.location}`) +
        ` (тело ${String(entry.bodyLength)} байт)`,
    )
    .join('\n    ');

  // Сравниваются ответы МЕЖДУ СОБОЙ, а не с зашитым 404: сам код ответа на этих
  // формах пинают проверки списка выше, и повторять их здесь нечего. Требование
  // этого утверждения — именно равенство: как только `.html` получает свою
  // ветку, оно и расходится.
  const shapes = [
    ...new Set(
      responses.map(
        (entry) => `${String(entry.status)} ${entry.location ?? 'без Location'}`,
      ),
    ),
  ];

  expect(
    shapes,
    'Ответы на соседние расширения разошлись. Форма «имя.расширение со слешем» адресом не ' +
      'является ни при каком расширении, и решение принимает политика пути, а не список ' +
      'знакомых сайту расширений: привилегия «.html» перед «.php» была рассмотрена и отклонена ' +
      `владельцем слоя. Расхождение означает, что «.html» снова обрабатывается отдельно.\n  Замер:\n    ${seen}`,
  ).toHaveLength(1);
});
