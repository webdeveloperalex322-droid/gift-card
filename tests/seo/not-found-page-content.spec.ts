/**
 * Требование (`CLAUDE.md`, «HTTP-статусы»: «Страница 404 отдаёт настоящий 404 и
 * содержит навигацию»; ТЗ §5.6: в теле — навигация и ссылка на поиск).
 *
 * Статус проверяет `not-found-status.spec.ts`; здесь проверяется ТЕЛО — то, чего
 * до задачи Э3-11 на сайте не было вовсе (приходила страница Astro по умолчанию:
 * `<html lang="en">`, без навигации и без нашего оформления), и что в прежнем
 * spec'е было честно записано как непокрытое требование.
 *
 * Что проверяется и почему именно это:
 *
 *   - **ровно один непустой `<h1>`.** Страница ошибки — такая же страница: без
 *     заголовка она выглядит как сломанный шаблон, а не как ответ сайта;
 *   - **ссылка на внутренний поиск В ТЕЛЕ** (ТЗ §5.6). Именно в теле, а не только
 *     в меню: посетитель, попавший на несуществующий адрес, ищет выход в тексте.
 *     Поэтому проверяется, что ссылок на `/search` больше одной — одна приходит из
 *     меню layout'а, вторая обязана стоять в тексте страницы;
 *   - **навигация: ссылки на корень и на оба каталога.** Тупик вместо навигации —
 *     это потерянный переход и для человека, и для краулера;
 *   - **НЕТ `<link rel="canonical">`.** Канонического адреса у страницы 404 не
 *     существует: она отвечает по ЛЮБОМУ несуществующему адресу. Self-canonical
 *     указывал бы на адрес, которого нет, а canonical на главную заявлял бы, что
 *     содержимое главной живёт по этому адресу, — то есть прямо предлагал бы
 *     склеить мусорный URL с главной. Это утверждение — единственное место, где
 *     оно проверяется: инвариантный spec `self-canonical-absolute` идёт по
 *     инвентарю страниц, а страницы 404 в инвентаре нет и быть не может (у неё
 *     нет своего адреса);
 *   - **директива робота есть и она `noindex`.** Индексировать страницу ошибки не
 *     нужно, а `follow` при этом законен: ссылки на ней ведут в живые разделы.
 */

import { expect, test } from '@playwright/test';

import { anchorLinks, canonicalHrefs, headingTexts, metaContents } from './support/html.js';
import { fetchRaw } from './support/http.js';
import { resolveAcceptanceTarget, urlFor } from './support/target.js';

const target = resolveAcceptanceTarget();

/** Адрес, которого нет: тело страницы 404 одно на все такие адреса. */
const MISSING_PATH = '/takogo-adresa-net-e3-14';

test('тело страницы 404: заголовок, навигация, ссылка на поиск, отсутствие canonical', async ({
  request,
}) => {
  const response = await fetchRaw(request, urlFor(target, MISSING_PATH));

  expect(response.status, 'Несуществующий адрес обязан отдавать 404.').toBe(404);

  const headings = headingTexts(response.body, 1);
  expect(headings, 'На странице 404 обязан быть ровно один H1.').toHaveLength(1);
  expect((headings[0] ?? '').length, 'H1 страницы 404 пуст.').toBeGreaterThan(0);

  const links = anchorLinks(response.body).map((link) => (link.href ?? '').trim());

  expect(
    links.filter((href) => href === '/search').length,
    'В ТЕЛЕ страницы 404 обязана быть ссылка на внутренний поиск (ТЗ §5.6) — то есть ссылок на ' +
      '/search в ответе больше одной: одна приходит из меню layout’а, вторая стоит в ' +
      'тексте страницы. Посетитель, попавший на несуществующий адрес, ищет выход в тексте, а ' +
      'не в шапке.',
  ).toBeGreaterThan(1);

  for (const required of ['/', '/otkrytki', '/podborki']) {
    expect(
      links.includes(required),
      `На странице 404 нет ссылки на «${required}». Страница ошибки обязана содержать ` +
        'навигацию: тупик вместо навигации — потерянный переход и для человека, и для краулера.',
    ).toBe(true);
  }

  expect(
    canonicalHrefs(response.body),
    'У страницы 404 не должно быть <link rel="canonical"> вовсе. Self-canonical указывал бы на ' +
      'адрес, которого нет, а canonical на главную предлагал бы поисковой системе склеить ' +
      'мусорный URL с главной.',
  ).toEqual([]);

  const directives = metaContents(response.body, 'robots');
  expect(directives, 'На странице 404 обязана быть ровно одна директива робота.').toHaveLength(1);
  expect(
    (directives[0] ?? '').startsWith('noindex'),
    `Директива страницы 404 — «${directives[0] ?? '—'}». Страницу ошибки индексировать не нужно.`,
  ).toBe(true);
});
